#!/usr/bin/env bash
# Гейт раскладки Diamond-хранилища.
#
# Инвариант: ни один фасет не должен объявлять обычных state-переменных.
# Всё состояние живёт в namespaced-библиотеках (ERC-7201), иначе фасеты
# начнут делить слоты 0,1,2... и затирать друг друга через delegatecall.
#
# Agreement и MinimalForwarder исключены: это standalone-контракты,
# delegatecall в них не идёт, собственное хранилище им положено.
#
# Коды возврата:
#   0   — раскладка чистая
#   1   — у фасета найдена последовательная state-переменная
#   2   — не удалось разобрать вывод slither (формат принтера изменился,
#         раскладка НЕ проверена — это не то же самое, что "чисто")
#   127 — slither не найден
#   *   — сам slither упал; код возврата пробрасывается как есть
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v slither >/dev/null 2>&1; then
    echo "check-storage-layout: slither не найден (pip install slither-analyzer)" >&2
    exit 127
fi

# ВАЖНО: принтер `variable-order` пишет таблицы в stderr, а не в stdout
# (проверено на slither 0.11.5) — stdout при этом остаётся пустым. Поэтому
# stderr здесь сливается в захватываемый поток через 2>&1, а не глушится.
#
# Код возврата slither захватывается вручную, в обход `set -e`: если slither
# упадёт (битый компил, краш, сломанное окружение), это не должно выглядеть
# так же, как "раскладка не проверялась вообще" — молча, теми же средствами,
# что и настоящее нарушение. Поэтому код возврата проверяется отдельно и
# сообщается отдельным сообщением, прежде чем что-либо парсить.
set +e
OUT=$(slither . --filter-paths "lib/|test/|script/" --print variable-order 2>&1)
SLITHER_RC=$?
set -e

if [ "$SLITHER_RC" -ne 0 ]; then
    echo "check-storage-layout: slither завершился с ошибкой (код $SLITHER_RC) — раскладка НЕ проверена:" >&2
    printf '%s\n' "$OUT" >&2
    exit "$SLITHER_RC"
fi

# ВАЖНО: гейт отличает фасет от standalone-контракта только по суффиксу
# `Facet` в имени контракта — это не enforced нигде в компиляторе. Фасет,
# замонтированный в диамонд под другим именем, или опечатка в имени
# (например JobBordFacet), окажется вне этой проверки и вне
# test/StorageLayout.t.sol. Соглашение об именовании — часть контракта
# этого гейта, а не деталь реализации.
#
# По тому же суффиксу проходят два интерфейса — IReputationFacet и
# IArbiterRegistryFacet. Они безопасны только потому, что интерфейсы
# Solidity не могут объявлять state-переменные (их таблицы всегда пустые),
# а не потому что скрипт как-то отличает интерфейс от фасета.
VIOLATIONS=$(printf '%s\n' "$OUT" | awk '
    /^[A-Za-z_][A-Za-z0-9_]*:$/ { contract = substr($0, 1, length($0)-1); next }
    /^\| *[A-Za-z_]/ {
        if (contract ~ /Facet$/ && $0 !~ /Name/) print contract ": " $2
    }
')

# Санити-проверка самого парсера: Agreement — standalone-контракт, у него
# гарантированно есть последовательные state-переменные (см. exclusion-
# комментарий вверху файла; на этом же факте держится test/StorageLayout.t.sol).
# Если разбор вывода slither для Agreement дал ноль строк — значит сломался
# сам парсер (принтер `variable-order` поменял формат или поток пуст), а не
# то, что раскладка внезапно стала чистой. В этом случае "ок" означало бы
# ложное молчание — то есть ровно тот класс поломки, ради которого писался
# этот скрипт.
AGREEMENT_ROWS=$(printf '%s\n' "$OUT" | awk '
    /^[A-Za-z_][A-Za-z0-9_]*:$/ { contract = substr($0, 1, length($0)-1); next }
    /^\| *[A-Za-z_]/ {
        if (contract == "Agreement" && $0 !~ /Name/) print contract ": " $2
    }
')

if [ -z "$AGREEMENT_ROWS" ]; then
    echo "check-storage-layout: не удалось разобрать вывод slither — санити-проверка провалена." >&2
    echo "Agreement — standalone-контракт с заведомо непустым набором state-переменных," >&2
    echo "но парсер не нашёл для него ни одной строки. Либо формат принтера" >&2
    echo "variable-order изменился, либо поток вывода пуст. Раскладка НЕ проверена." >&2
    exit 2
fi

if [ -n "$VIOLATIONS" ]; then
    echo "check-storage-layout: у фасетов найдены последовательные state-переменные:" >&2
    printf '%s\n' "$VIOLATIONS" >&2
    echo "" >&2
    echo "Всё состояние фасета обязано лежать в namespaced-библиотеке." >&2
    exit 1
fi

echo "check-storage-layout: ок — ни один фасет не занимает последовательных слотов"
