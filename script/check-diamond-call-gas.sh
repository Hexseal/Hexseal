#!/usr/bin/env bash
# Гейт правила «обращение из Agreement наружу идёт под газ-капом».
#
# Пятый статический гейт репозитория, рядом с тремя про раскладку хранилища
# (check-storage-layout.sh, check-storage-structs.sh, check-agreement-layout.sh)
# и одним про ERC-2771 (check-gasless-sender.sh). Класс бага снова другой.
#
# Каждая сделка — клон EIP-1167 контракта Agreement, деньги лежат в клоне,
# диамонд стоит сбоку. Все обращения к нему обёрнуты в try/catch, и это
# СЧИТАЛОСЬ защитой. Не считается: try/catch ловит реверт, но не возвращает
# газ, уже сожжённый вызываемым. Фасет, застрявший в неограниченном цикле,
# съедает 63/64 предложенного, а с кадром прокси между ними — примерно 31/32
# остатка Agreement. Замер (docs/audits/2026-08-22-diamond-death-escrow.md,
# раздел 4): два таких обращения ПЕРЕД выплатой подняли стоимость автоапрува с
# 419 481 до 29 791 258 газа, в 71 раз. Деньги не выходили ни при каком
# разумном лимите, и ни один catch этому не мешал.
#
# Лекарство держится на одной строке `{gas: КАП}` в каждом вызове, а строки
# теряются. Отсюда гейт.
#
# ---------------------------------------------------------------------------
# «А ЕСЛИ ЧЕРЕЗ ПЕРЕМЕННУЮ?» — ОТВЕТ ЗАМЕРОМ, А НЕ ОБЕЩАНИЕМ
#
# Два гейта репозитория уже оказывались слепыми ровно так: сканер узнавал
# написание, а не то, на что оно ссылается (docs/PROCESS.md, шестой способ).
# Здесь разбирается AST solc, признак берётся типовой, и это проверено порчей
# кода — три формы, гейт прогнан на каждой:
#
#   1. `{gas: ...}` просто снят с _updateRegistry
#        -> КРАСНЫЙ: «БЕЗ КАПА и без записи: Agreement._updateRegistry ::
#           contract ISignatureRegistry.updateStatus»
#   2. вызов сделан ЧЕРЕЗ ПЕРЕМЕННУЮ интерфейса, кап снят:
#        `ISignatureRegistry reg = ISignatureRegistry(diamond); reg.updateStatus(...)`
#        -> КРАСНЫЙ, то же сообщение. Слова «diamond» в разборе нет вообще:
#           опознаётся ТИП получателя, а не имя переменной.
#   3. ассемблерный `staticcall(gas(), ...)` вместо `staticcall(gasCap, ...)`
#        в _verdictInFlight
#        -> КРАСНЫЙ: «БЕЗ КАПА и без записи: Agreement._verdictInFlight ::
#           assembly.staticcall»
#
# На чистом дереве гейт зелёный: 6 вызовов под капом, 6 объяснены в allow-файле.
#
# Случай, который сканер разобрать НЕ СМОГ, тоже краснеет («НЕ КЛАССИФИЦИРОВАН»),
# а не молчит — молчание здесь и есть тот дефект, ради которого гейт писался.
#
# ---------------------------------------------------------------------------
# ОБЛАСТЬ
#
# Только src/Agreement.sol — единственный контракт репозитория, который
# одновременно держит чужие деньги на своём балансе и зовёт диамонд снаружи.
# Фасеты живут ВНУТРИ диамонда (delegatecall), у них этого шва нет. Про
# src/Treasury.sol сказано вслух в докстринге check_diamond_call_gas.py и
# заведено пунктом в docs/OPEN-ITEMS.md — здесь это записано, а не умолчано.
#
# Использование:
#   ./script/check-diamond-call-gas.sh           — проверка (её вызывает CI)
#   ./script/check-diamond-call-gas.sh --print   — напечатать найденное
#                                                  заготовкой для allow-файла;
#                                                  причины дописывает человек
#
# Коды возврата:
#   0   — все внешние вызовы под капом или объяснены
#   1   — вызов без капа и без записи / изменилось число в записи /
#         протухшая запись / вызов, который не удалось разобрать
#   2   — allow-файл отсутствует, пуст или повреждён (запись без причины) —
#         сравнивать не с чем, это НЕ «чисто»
#   3   — разбор не состоялся: forge build упал, нет артефакта с AST, или в
#         файле не нашлось известных диамонд-интерфейсов. Сломан сам гейт,
#         правило НЕ проверено — это не то же самое, что «нарушений нет»
#   127 — python3 не найден
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v python3 >/dev/null 2>&1; then
    echo "check-diamond-call-gas: python3 не найден" >&2
    exit 127
fi

# Гейт читает AST из артефактов (out/<File>.sol/<Contract>.json, ключ "ast"),
# поэтому артефакты обязаны быть свежими — иначе правило проверялось бы по
# позавчерашнему коду. `ast = true` живёт в foundry.toml, см. комментарий там.
#
# Код возврата forge захватывается вручную, в обход `set -e`: под `set -e`
# падение сборки убило бы скрипт молча, до диагностики и до сентинела 3 — а
# молчаливый ненулевой код неотличим от «гейт нашёл нарушение».
set +e
BUILD_OUT=$(forge build 2>&1)
BUILD_RC=$?
set -e

if [ "$BUILD_RC" -ne 0 ]; then
    echo "check-diamond-call-gas: forge build завершился с ошибкой (код $BUILD_RC) — правило НЕ проверено:" >&2
    printf '%s\n' "$BUILD_OUT" >&2
    exit 3
fi

python3 script/check_diamond_call_gas.py "${1:---check}"
