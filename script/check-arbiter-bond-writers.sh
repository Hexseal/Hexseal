#!/usr/bin/env bash
# Гейт: ненулевую запись в `arbiterBond` делает РОВНО ОДНА функция.
#
# ⚠️ В CI ВКЛЮЧЁН с 21 августа 2026, седьмым. Здесь стояло «в CI не включён
# намеренно: каждый новый гейт — налог на каждый прогон». Налог замерили, а не
# прикинули: на тёплом кеше (а в CI он тёплый — `forge test` собирает раньше)
# гейт стоит 1,4 секунды, и собственный `forge build` внутри него попадает в
# кеш. Решение владельца, круг правок 2.
#
# Зачем он нужен при живом тесте про ручную посадку, что считается ненулевой
# записью, чего гейт не ловит и почему разбор идёт по AST, а не регуляркой —
# докстринг script/check_arbiter_bond_writers.py.
#
# Коротко: тест пришпиливает узкое («addArbiter сама залога не берёт»), а
# публичный документ утверждает широкое («залога нет у всякого, кого можно
# снести»). При двухшаговом залоге addArbiter залога по-прежнему брать не
# будет — тест останется зелёным, а утверждение станет ложным. Ревью задачи 6
# это разыграло: банк вырос на 50 000 000 при нуле красных из 852.
#
# Использование:
#   ./script/check-arbiter-bond-writers.sh           — проверка
#   ./script/check-arbiter-bond-writers.sh --print   — напечатать найденное
#
# Коды возврата:
#   0   — ненулевой писатель ровно один и он ожидаемый, и ни одна ссылка на
#         поле не утекла из-под разбора
#   1   — писателей стало больше/меньше, это не тот писатель, ИЛИ ссылка на
#         поле (либо локальный указатель на него) уехала туда, куда разбор не
#         идёт — аргументом в чужую функцию, возвратом, в кортеж
#   3   — разбор не состоялся (нет артефакта с AST, поле не найдено вовсе):
#         сломан сам гейт, правило НЕ проверено — это не «нарушений нет»
#   127 — python3 не найден
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v python3 >/dev/null 2>&1; then
    echo "check-arbiter-bond-writers: python3 не найден" >&2
    exit 127
fi

# AST читается из артефактов (out/<File>.sol/<Contract>.json, ключ "ast"),
# значит они обязаны быть свежими — иначе правило проверялось бы по
# позавчерашнему коду и молчало о сегодняшнем. `ast = true` живёт в
# foundry.toml, поэтому эта сборка почти всегда no-op.
#
# Код возврата forge захватывается вручную, в обход `set -e`: под ним падение
# сборки убило бы скрипт молча, до диагностики и до сентинела 3 — а молчаливый
# ненулевой код неотличим от «гейт нашёл нарушение».
set +e
BUILD_OUT=$(forge build 2>&1)
BUILD_RC=$?
set -e

if [ "$BUILD_RC" -ne 0 ]; then
    echo "check-arbiter-bond-writers: forge build завершился с ошибкой (код $BUILD_RC) — правило НЕ проверено:" >&2
    printf '%s\n' "$BUILD_OUT" >&2
    exit 3
fi

python3 script/check_arbiter_bond_writers.py "$@"
