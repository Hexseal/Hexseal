#!/usr/bin/env bash
# Гейт раскладки ПОЛЕЙ Diamond-хранилища.
#
# Дополняет два существующих гейта, которые про это ничего не знают:
#   - test/StorageLayout.t.sol   — пиннит только девять базовых слотов неймспейсов
#   - check-storage-layout.sh    — ловит только последовательные state-переменные
#                                  фасетов (другой класс дефекта)
#
# Ни один из них не заметил бы то, что реально сломалось в июле 2026: коммит
# 1772ed9 поменял тип поля `termsHash` (bytes32) на `terms` (string) ВНУТРИ
# struct Job — слот тот же, кодировка другая, старые записи стали читаться
# мусором. Этот скрипт — тонкая обёртка над python3-парсером, который сравнивает
# поля struct Layout/Data (и вложенных структур) со снапшотом в
# script/storage-structs.snapshot: любое изменение, кроме чистого дописывания
# в конец, — провал.
#
# Вся логика (разбор src/, сравнение, диагностика) — в check_storage_structs.py,
# см. подробный докстринг там же.
#
# Использование:
#   ./script/check-storage-structs.sh            — проверка (эту команду вызывает CI)
#   ./script/check-storage-structs.sh --update    — перегенерировать снапшот
#                                                    (после осознанного, ревьюженного
#                                                    изменения раскладки — коммитить
#                                                    файл вместе с изменением кода)
#   ./script/check-storage-structs.sh --print     — вывести текущую раскладку, не сверяя
#
# Коды возврата (пробрасываются из check_storage_structs.py как есть):
#   0    — раскладка чистая И снимок полон
#   1    — найдено запрещённое изменение (смена типа / реордер / вставка /
#          удаление / переименование структуры или поля)
#   2    — снапшот отсутствует или повреждён — сравнивать не с чем, это НЕ "чисто"
#   3    — парсер не нашёл ни одной storage-структуры в src/ — сам парсер
#          сломан (например, переименовали маркер erc7201), раскладка НЕ
#          проверена — это не то же самое, что "структур нет"
#   4    — раскладка ЦЕЛА, но снимок неполон: поля дописаны в конец законно и
#          в снимок не попали. Заведено кругом правок 1 к пункту 101
#          (21 августа 2026) по замеру дыры: пока поля нет в снимке, для него
#          нет базовой линии, и смена его типа проходит гейт МОЛЧА — ровно тот
#          класс, что сломал живой JobBoard. Замерено на дереве 8b230f6f:
#          chainProposalPath uint8 -> bytes32 давал rc=0 и слово «ок», та же
#          порча на соседнем поле из снимка — rc=1 с диагностикой. Два поля
#          одной структуры охранялись по-разному, и различало их только то,
#          добежал ли кто-то до --update.
#          Лечится `--update`; отдельный код, а не 1, потому что ЖИВОЕ
#          хранилище тут цело и чинить надо снимок, а не откатывать правку.
#   127  — python3 не найден
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v python3 >/dev/null 2>&1; then
    echo "check-storage-structs: python3 не найден" >&2
    exit 127
fi

python3 script/check_storage_structs.py "${1:---check}"
