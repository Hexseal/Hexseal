#!/usr/bin/env bash
# Гейт правила ERC-2771: сырой msg.sender в гейслесс-контрактах.
#
# Четвёртый статический гейт репозитория, рядом с тремя про раскладку
# хранилища (check-storage-layout.sh, check-storage-structs.sh,
# check-agreement-layout.sh). Класс бага другой.
#
# Протокол гейслесс: человек подписывает EIP-712, транзакцию отправляет релеер.
# Личность приезжает в контракт в хвосте calldata по ERC-2771 и достаётся
# только через _msgSender(). Прочитал msg.sender — получил адрес форвардера.
#
# Инцидент 31 июля 2026 (фикс d172064): ArbiterRegistryFacet.fundDispute и
# withdrawDisputeBounty читали msg.sender. Фронт зовёт обе ИСКЛЮЧИТЕЛЬНО через
# форвардер, поэтому проверка «ты сторона спора?» отвергала каждую оплату —
# платный вызов арбитра не сработал ни разу. В том же файле правило соблюдено
# пятнадцать раз; две новые функции его просто не унаследовали, компилятор
# молчал, и ни один из 550 тестов не ходил по этому пути через настоящий
# форвардер. Соглашение жило в головах — этот гейт переселяет его в проверку.
#
# Что именно проверяется, как разбирается код (AST solc, не регулярки) и как
# устроен реестр исключений — докстринг check_gasless_sender.py и шапка
# script/gasless-sender.allow.
#
# Использование:
#   ./script/check-gasless-sender.sh           — проверка (её вызывает CI)
#   ./script/check-gasless-sender.sh --print   — напечатать найденное заготовкой
#                                                для allow-файла; причины к
#                                                записям дописывает человек,
#                                                автообновления здесь нет и не
#                                                будет — оно бы и убило смысл
#
# Коды возврата:
#   0   — все сырые обращения объяснены в script/gasless-sender.allow
#   1   — необъяснённое обращение / изменилось их число в разрешённой функции /
#         изменилось их число в файле «вне области» / протухшая запись в
#         allow-файле
#   2   — allow-файл отсутствует, пуст или повреждён (в том числе запись без
#         причины) — сравнивать не с чем, это НЕ «чисто»
#   3   — разбор не состоялся: forge build упал, у файла из src/ нет артефакта
#         с AST, автопоиск не нашёл известных ERC-2771-контрактов. Сломан сам
#         гейт, правило НЕ проверено — это не то же самое, что «нарушений нет»
#   127 — python3 не найден
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v python3 >/dev/null 2>&1; then
    echo "check-gasless-sender: python3 не найден" >&2
    exit 127
fi

# Гейт читает AST из артефактов (out/<File>.sol/<Contract>.json, ключ "ast"),
# поэтому артефакты обязаны быть свежими — иначе правило проверялось бы по
# позавчерашнему коду и молчало о сегодняшнем.
#
# `ast = true` живёт в foundry.toml, а не флагом здесь: набор флагов входит в
# хеш настроек компилятора, и чередование `forge test` (без AST) с
# `forge build --ast` пересобирало бы via-ir проект целиком на каждом
# переключении. С настройкой в конфиге эта команда — почти всегда no-op.
#
# Код возврата forge захватывается вручную, в обход `set -e`, ровно по той же
# причине, что в check-agreement-layout.sh: под `set -e` падение сборки убило
# бы скрипт молча, до того как он напечатает диагностику и выйдет с сентинелом 3
# — а молчаливый ненулевой код неотличим от «гейт нашёл нарушение».
set +e
BUILD_OUT=$(forge build 2>&1)
BUILD_RC=$?
set -e

if [ "$BUILD_RC" -ne 0 ]; then
    echo "check-gasless-sender: forge build завершился с ошибкой (код $BUILD_RC) — правило НЕ проверено:" >&2
    printf '%s\n' "$BUILD_OUT" >&2
    exit 3
fi

python3 script/check_gasless_sender.py "${1:---check}"
