#!/usr/bin/env bash
# APPEAL_REVIEW_WINDOW объявлен private в ArbiterRegistryFacet, из цепи его не
# прочитать, поэтому релеер держит копию. Копия обязана совпадать с оригиналом:
# если окно апелляции удлинят, а релеер об этом не узнает, он сотрёт
# доказательства до того, как апелляция закончится — и оспорить вердикт станет
# нечем. Тот же класс гейта, что check-storage-layout.sh и check-gasless-sender.sh.
set -euo pipefail

SOL="src/facets/ArbiterRegistryFacet.sol"
JS="relayer/bagStore.js"

# `|| true` на каждой строке — не декоративный. Без него `set -o pipefail`
# делает статус всей команды подстановки равным статусу grep (1, "не нашёл
# совпадение"), а под `set -e` присваивание переменной с ненулевым статусом
# завершает скрипт НА ЭТОЙ СТРОКЕ — молча, кодом 1, раньше, чем выполнится
# хоть одна из проверок `-z` ниже, которые как раз и должны объяснить, что
# именно не нашлось. Проверено вживую до фикса: `APPEAL_REVIEW_WINDOW_DAYS`,
# ещё не добавленный в bagStore.js, давал `exit 1` без единой строки текста —
# гейт, который падает молча, нарушает то же самое правило, ради которого он
# существует (сверять текст ошибки, а не только статус). `|| true` не меняет
# исход: пустая строка по-прежнему пустая строка, `-z` ниже её ловит и печатает
# правильное сообщение.
sol_days="$(grep -oP 'APPEAL_REVIEW_WINDOW\s*=\s*\K[0-9]+(?=\s*days)' "$SOL" | head -1 || true)"
# Отличается от буквального текста черновика задачи (там ожидался плоский
# `const APPEAL_REVIEW_WINDOW_DAYS = 4`). bagStore.js держит ВСЕ сроки/лимиты
# одним и тем же приёмом файла (`export let X; X = Number(process.env.X ||
# умолчание)` в _refreshConfig() — см. заголовок bagStore.js, находка И-3) —
# ради живой ES-привязки и возможности переопределить через окружение, тем
# же способом, что BAG_TTL_MS/BAG_UNREAD_TTL_MS/BAG_MAX_AGE_MS рядом. Голый
# `NAME\s*=\s*[0-9]+` после "=" находит "Number(...)", не число, и вообще
# ничего не матчит. Гейт ищет ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ — то, что реально
# зашито в исходник и что видит CI — а не то, что решит переопределить
# .env на конкретном деплое; то же самое дерево решений, что у остальных
# статических гейтов репозитория (проверяют исходник, не рантайм).
js_days="$(grep -oP 'APPEAL_REVIEW_WINDOW_DAYS\s*=\s*Number\(process\.env\.APPEAL_REVIEW_WINDOW_DAYS\s*\|\|\s*\K[0-9]+' "$JS" | head -1 || true)"

if [[ -z "$sol_days" ]]; then
  echo "❌ не нашёл APPEAL_REVIEW_WINDOW в $SOL — гейт сломан, почини гейт"; exit 1
fi
if [[ -z "$js_days" ]]; then
  echo "❌ не нашёл APPEAL_REVIEW_WINDOW_DAYS в $JS"; exit 1
fi
if [[ "$sol_days" != "$js_days" ]]; then
  echo "❌ окно апелляции разошлось: контракт $sol_days дн., релеер $js_days дн."
  echo "   Пока они не совпадут, релеер будет стирать доказательства до конца апелляции."
  exit 1
fi
echo "✓ окно апелляции сходится: $sol_days дн."
