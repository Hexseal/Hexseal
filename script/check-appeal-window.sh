#!/usr/bin/env bash
# APPEAL_REVIEW_WINDOW и FINALIZE_DELAY объявлены private в
# ArbiterRegistryFacet, из цепи их не прочитать, поэтому релеер держит свои
# копии (обе нужны формуле dealDeadlineFromDispute()/dealDeadlineFromCreation()
# в relayer/bagStore.js — конец окна апелляции считается через ОБЕ константы,
# см. докстринг там же, находка I2 закрывающего раунда ревью). Копии обязаны
# совпадать с оригиналом: если любое из окон удлинят, а релеер об этом не
# узнает, он сотрёт доказательства до того, как апелляция закончится — и
# оспорить вердикт станет нечем. Тот же класс гейта, что check-storage-layout.sh
# и check-gasless-sender.sh.
set -euo pipefail

SOL="src/facets/ArbiterRegistryFacet.sol"
JS="relayer/bagStore.js"

# I-A (второй закрывающий раунд ревью): раньше здесь не было этой проверки —
# запуск не из корня репозитория (относительные пути $SOL/$JS не резолвятся)
# давал ТУ ЖЕ строку "не нашёл ... — гейт сломан, почини гейт", что и
# настоящее переименование/удаление константы. Человек, увидевший эту
# строку из чужого каталога, чинил бы несуществующую поломку. Различаем ДО
# любого grep: если файла физически нет — сообщение называет причину
# (не в корне репозитория), а не "гейт сломан".
if [[ ! -f "$SOL" ]]; then
  echo "❌ $SOL не найден (сейчас: $(pwd)) — запусти гейт из корня репозитория, не по относительному пути откуда-то ещё"
  exit 1
fi
if [[ ! -f "$JS" ]]; then
  echo "❌ $JS не найден (сейчас: $(pwd)) — запусти гейт из корня репозитория, не по относительному пути откуда-то ещё"
  exit 1
fi

# `|| true` на каждой строке — не декоративный. Без него `set -o pipefail`
# делает статус всей команды подстановки равным статусу grep (1, "не нашёл
# совпадение"), а под `set -e` присваивание переменной с ненулевым статусом
# завершает скрипт НА ЭТОЙ СТРОКЕ — молча, кодом 1, раньше, чем выполнится
# хоть одна из проверок `-z` ниже, которые как раз и должны объяснить, что
# именно не нашлось.
#
# I-A (второй закрывающий раунд ревью): ОБЕ стороны теперь заякорены на
# начало строки настоящего объявления (`^\s*uint256 private constant NAME`
# на стороне контракта, `^export const NAME` на стороне релеера) — не
# "первое текстовое совпадение где угодно в файле". До этой правки
# заякорена была только сторона релеера; строка на стороне контракта вида
#   // историческая справка: APPEAL_REVIEW_WINDOW = 4 days было до правки
#   uint256 private constant APPEAL_REVIEW_WINDOW = 7 days;
# матчилась голым `APPEAL_REVIEW_WINDOW\s*=\s*[0-9]+(?=\s*days)` НА
# КОММЕНТАРИИ (он стоит раньше в файле, `head -1` берёт первое совпадение),
# извлекая "4" вместо настоящих "7" — расхождение в три дня, гейт зелёный.
# Комментарий начинается с `//`, не с `uint256` — `^\s*uint256` его физически
# не может задеть.
sol_days="$(grep -oP '^\s*uint256 private constant APPEAL_REVIEW_WINDOW\s*=\s*\K[0-9]+(?=\s*days)' "$SOL" | head -1 || true)"
js_days="$(grep -oP '^export const APPEAL_REVIEW_WINDOW_DAYS = \K[0-9]+' "$JS" | head -1 || true)"

if [[ -z "$sol_days" ]]; then
  echo "❌ не нашёл APPEAL_REVIEW_WINDOW в $SOL — гейт сломан, почини гейт"; exit 1
fi
if [[ -z "$js_days" ]]; then
  echo "❌ не нашёл APPEAL_REVIEW_WINDOW_DAYS в $JS"; exit 1
fi
if [[ "$sol_days" != "$js_days" ]]; then
  echo "❌ окно апелляции разошлось: контракт $sol_days дн., релеер $js_days дн."
  echo "   Пока они не совпадут, релеер будет стирать доказательства до конца апелляции."
  exit 1
fi
echo "✓ окно апелляции сходится: $sol_days дн."

# Та же находка I-A, то же исправление: якорь на настоящее объявление, не на
# первое текстовое совпадение (комментарий с "24 hours" выше настоящих "72
# hours" раньше давал тот же ложный зелёный).
sol_hours="$(grep -oP '^\s*uint256 private constant FINALIZE_DELAY\s*=\s*\K[0-9]+(?=\s*hours)' "$SOL" | head -1 || true)"
js_hours="$(grep -oP '^export const FINALIZE_DELAY_HOURS = \K[0-9]+' "$JS" | head -1 || true)"

if [[ -z "$sol_hours" ]]; then
  echo "❌ не нашёл FINALIZE_DELAY в $SOL — гейт сломан, почини гейт"; exit 1
fi
if [[ -z "$js_hours" ]]; then
  echo "❌ не нашёл FINALIZE_DELAY_HOURS в $JS"; exit 1
fi
if [[ "$sol_hours" != "$js_hours" ]]; then
  echo "❌ окно финализации разошлось: контракт $sol_hours ч., релеер $js_hours ч."
  echo "   Пока они не совпадут, релеер будет стирать доказательства до того, как окно апелляции реально откроется/закроется."
  exit 1
fi
echo "✓ окно финализации сходится: $sol_hours ч."

# I-A, вторая часть находки: гейт сверял число (4, 24), но не множитель, на
# который релеер его умножает при переводе в миллисекунды. Подмена
# `DAY_MS`/`HOUR_MS` (например, дни на часы) оставляла бы сравнение "4=4"
# зелёным, при этом формула считала бы в 24 раза меньший интервал. Сверяем
# сами константы-множители буквально — их значение фиксировано (сутки/час в
# мс), в отличие от APPEAL_REVIEW_WINDOW_DAYS/FINALIZE_DELAY_HOURS у них нет
# "оригинала в контракте", это просто арифметика, но если её сломать —
# ломается вся формула молча.
day_ms_expr="$(grep -oP '^const DAY_MS = \K[0-9 \*]+(?=;)' "$JS" | head -1 || true)"
hour_ms_expr="$(grep -oP '^const HOUR_MS = \K[0-9 \*]+(?=;)' "$JS" | head -1 || true)"

if [[ -z "$day_ms_expr" ]]; then
  echo "❌ не нашёл объявление DAY_MS в $JS — гейт сломан, почини гейт"; exit 1
fi
if [[ -z "$hour_ms_expr" ]]; then
  echo "❌ не нашёл объявление HOUR_MS в $JS — гейт сломан, почини гейт"; exit 1
fi

day_ms_value=$(( day_ms_expr ))
hour_ms_value=$(( hour_ms_expr ))

if [[ "$day_ms_value" -ne 86400000 ]]; then
  echo "❌ DAY_MS в $JS считается как $day_ms_value мс, а не 86400000 (сутки) — подмена множителя, формула APPEAL_REVIEW_WINDOW_DAYS*DAY_MS считает не то"
  exit 1
fi
if [[ "$hour_ms_value" -ne 3600000 ]]; then
  echo "❌ HOUR_MS в $JS считается как $hour_ms_value мс, а не 3600000 (час) — подмена множителя, формула FINALIZE_DELAY_HOURS*HOUR_MS считает не то"
  exit 1
fi
echo "✓ множители сходятся: DAY_MS=$day_ms_value мс, HOUR_MS=$hour_ms_value мс"

# И сама формула обязана применять их к ПРАВИЛЬНОЙ константе — DAY_MS может
# быть верным числом, а формула — умножать APPEAL_REVIEW_WINDOW_DAYS на
# HOUR_MS по ошибке (дни на часы уже на месте применения, не на месте
# определения). Ищем буквальную подстроку применения в обеих формулах
# (dealDeadlineFromDispute/dealDeadlineFromCreation, обе используют одно и
# то же выражение — см. bagStore.js).
if ! grep -q 'APPEAL_REVIEW_WINDOW_DAYS \* DAY_MS' "$JS"; then
  echo "❌ не нашёл 'APPEAL_REVIEW_WINDOW_DAYS * DAY_MS' в $JS — формула применяет не тот множитель (дни на часы?)"
  exit 1
fi
if ! grep -q 'FINALIZE_DELAY_HOURS \* HOUR_MS' "$JS"; then
  echo "❌ не нашёл 'FINALIZE_DELAY_HOURS * HOUR_MS' в $JS — формула применяет не тот множитель (часы на дни?)"
  exit 1
fi
echo "✓ формула применяет множители к правильным константам"
