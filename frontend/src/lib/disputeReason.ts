'use client';

/**
 * Отправка причины спора — с обязательным следом в журнале на КАЖДОМ отказе.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Открыть спор можно из трёх мест (`components/DealCard.tsx`,
 * `components/DealActionBar.tsx`, `app/deal/[address]/page.tsx`), и во всех трёх
 * стоял один и тот же кусок: подписать причину, выстрелить POST'ом без ожидания
 * и проглотить любой исход — пустой `.catch` на запросе плюс пустой `catch`
 * с пометкой «non-critical» на подписи. Ни строчки в журнал ни на одном из путей.
 *
 * ПОЧЕМУ ЭТО НЕ МЕЛОЧЬ. Причина спора обязательна в интерфейсе: кнопка
 * подтверждения заблокирована на пустом поле во всех трёх местах. Человек пишет
 * до 2000 символов изложения своего дела, жмёт «Подтвердить» и видит зелёное
 * «Спор открыт!». Причина при этом могла не сохраниться вовсе — и узнать об
 * этом было нельзя ниоткуда:
 *
 *   • сторона записи молчала (оба проглатывания выше);
 *   • сторона чтения молчит тоже — `app/arbiter/page.tsx` читает причину как
 *     `.then(d => { if (d.reason) setDisputeReason(d.reason); }).catch(() => {})`,
 *     то есть «причины не написали» и «причину не удалось получить» для арбитра
 *     выглядят одинаково — пустым местом.
 *
 * Итог: арбитр решает судьбу эскроу, не видя изложения дела, а обе стороны
 * уверены, что он его читает. Спор при этом платный и идёт по таймерам.
 *
 * ЧТО ЗДЕСЬ ИСПРАВЛЕНО, А ЧТО НЕТ. Исправлен ровно след: теперь каждый отказ
 * (сеть, не-2xx от прокси, отказ от подписи) попадает в журнал с адресом
 * сделки. Поведение НЕ менялось: спор по-прежнему открывается даже без
 * сохранённой причины, и человеку по-прежнему показывается обычный успех.
 * Сообщать ли ему, что изложение не доехало, и не блокировать ли спор до
 * успешного сохранения — продуктовое решение, оно вынесено отдельно.
 */

export interface DisputeReasonPayload {
  agreement: string;
  raiser: string;
  reason: string;
  ts: number;
  sig: string;
}

export interface PostDisputeReasonOptions {
  fetchImpl?: typeof fetch;
  /** Подменяется в тестах; по умолчанию — журнал браузера. */
  warn?: (message: string, ...rest: unknown[]) => void;
}

/**
 * Отправляет причину спора. Никогда не бросает: вызывающий продолжает открывать
 * спор независимо от исхода. Возвращает `true`, только если релеер подтвердил
 * приём (2xx) — чтобы у вызывающего была возможность отреагировать, когда
 * продуктовое решение по этому вопросу будет принято.
 */
export async function postDisputeReason(
  payload: DisputeReasonPayload,
  opts: PostDisputeReasonOptions = {},
): Promise<boolean> {
  const fetchImpl = opts.fetchImpl ?? ((...args: Parameters<typeof fetch>) => fetch(...args));
  const warn = opts.warn ?? ((msg: string, ...rest: unknown[]) => console.warn(msg, ...rest));

  try {
    const res = await fetchImpl('/api/dispute-reason', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });
    if (!res.ok) {
      // Раньше статус ответа не проверялся вообще: 400 и 500 от прокси
      // проходили как успех, потому что сам `fetch` при не-2xx не отвергается.
      warn(
        `[dispute] причина спора по ${payload.agreement} не сохранена: HTTP ${res.status}. ` +
        `Спор будет открыт, но арбитр увидит дело без изложения — как если бы причину не писали вовсе.`,
      );
      return false;
    }
    return true;
  } catch (err) {
    warn(
      `[dispute] причина спора по ${payload.agreement} не доехала до релеера — ` +
      `спор будет открыт без изложения дела:`,
      err,
    );
    return false;
  }
}

/**
 * След для случая, когда причину не удалось даже подписать (человек отклонил
 * запрос, кошелёк отвалился, сработал потолок мьютекса). Спор после этого
 * открывается всё равно — но теперь это видно в журнале.
 */
export function warnDisputeReasonUnsigned(
  agreement: string,
  err: unknown,
  warn: (message: string, ...rest: unknown[]) => void = (msg, ...rest) => console.warn(msg, ...rest),
): void {
  warn(
    `[dispute] причина спора по ${agreement} не подписана — спор открывается без изложения дела:`,
    err,
  );
}
