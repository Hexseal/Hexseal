import { describe, expect, it } from 'vitest';
import { splitPot, usdcExact } from './splitPot';

/**
 * ПОЧЕМУ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
 *
 * `lib/splitPot` — две функции на девять строк, и обе про деньги: одна решает,
 * кому сколько досталось при дележе эскроу, вторая печатает это пользователю.
 * До сих пор они проверялись только косвенно — через `arbiterTimeoutSettlement`
 * и `settledRefund`, — а косвенная проверка держит ровно те значения, которые
 * случайно оказались в чужих сценариях: один нечётный котёл и один круглый.
 * Ни ноль, ни единица, ни крупная сумма через них не проходили никогда.
 *
 * Обе ошибки, от которых здесь стоит защита, ТИХИЕ: показанное число не сойдётся
 * с пришедшим на кошелёк, и заметит это только тот, кто сравнит.
 *
 *  • `splitPot` — вычитание вместо второго деления. `pot/2 + pot/2` на нечётном
 *    котле теряет юнит: он не показан никому, хотя контракт его платит.
 *  • `usdcExact` — округление. `.toFixed(2)` напечатал бы и 16, и 17 юнитов как
 *    «0.00», то есть скрыл бы выплату целиком.
 */

// ─── splitPot ────────────────────────────────────────────────────────────────
//
// Эталон — `src/Agreement.sol`, `triggerArbiterTimeout`, ветка
// `arbiter == address(0)`:
//
//     uint256 toExecutor = pot / 2;
//     uint256 toClient   = pot - toExecutor;   // вычитанием: остаток тому, чьи деньги
//
// Solidity делит целочисленно с отбрасыванием, как и bigint в JS, поэтому
// сверять можно выражение в выражение.

describe('splitPot — та же арифметика, что в контракте', () => {
  const CASES: { name: string; pot: bigint }[] = [
    { name: 'пустой котёл',                    pot: 0n },
    { name: 'неделимый юнит',                  pot: 1n },
    { name: 'два юнита — делится ровно',       pot: 2n },
    { name: 'нечётный котёл из живого теста',  pot: 33n },
    { name: 'круглые 200 USDC',                pot: 200_000_000n },
    { name: 'нечётные 200 USDC + юнит',        pot: 200_000_001n },
    // Больше, чем uint96, и заметно больше всего оборота протокола — здесь
    // важно, что арифметика bigint, а не number: 2**53 давно позади.
    { name: 'крупный котёл',                   pot: 123_456_789_012_345_678_901n },
  ];

  for (const { name, pot } of CASES) {
    it(`${name} (${pot}): floor(pot/2) исполнителю, ОСТАТОК клиенту`, () => {
      expect(splitPot(pot)).toEqual({ toExecutor: pot / 2n, toClient: pot - pot / 2n });
    });
  }

  // Главное свойство: ни один юнит не пропадает и ни один не появляется.
  // Второе деление вместо вычитания провалит его на каждом нечётном котле.
  it('сумма половин равна котлу — всегда', () => {
    for (const pot of [
      0n, 1n, 2n, 3n, 33n, 999_999n, 200_000_000n, 200_000_001n,
      123_456_789_012_345_678_901n,
    ]) {
      const { toExecutor, toClient } = splitPot(pot);
      expect(toExecutor + toClient).toBe(pot);
    }
  });

  it('нечётный юнит достаётся клиенту, а не исполнителю — это его деньги', () => {
    expect(splitPot(33n)).toEqual({ toExecutor: 16n, toClient: 17n });
    expect(splitPot(1n)).toEqual({ toExecutor: 0n, toClient: 1n });
  });

  it('на чётном котле половины равны', () => {
    expect(splitPot(200_000_000n)).toEqual({ toExecutor: 100_000_000n, toClient: 100_000_000n });
  });

  it('делённого пополам нуля не существует — обе доли нулевые', () => {
    expect(splitPot(0n)).toEqual({ toExecutor: 0n, toClient: 0n });
  });
});

// ─── usdcExact ───────────────────────────────────────────────────────────────

describe('usdcExact', () => {
  it('никогда не короче двух знаков после запятой', () => {
    expect(usdcExact(0n)).toBe('0.00');
    expect(usdcExact(200_000_000n)).toBe('200.00');
    expect(usdcExact(100_000n)).toBe('0.10');
    expect(usdcExact(1_500_000n)).toBe('1.50');
  });

  it('никогда не округляет — число обязано совпасть с выплаченным', () => {
    // Нечётный котёл 33 юнита делится 16 / 17; .toFixed(2) напечатал бы «0.00»
    // для обоих и спрятал бы выплату целиком.
    expect(usdcExact(16n)).toBe('0.000016');
    expect(usdcExact(17n)).toBe('0.000017');
    expect(usdcExact(1n)).toBe('0.000001');
    expect(usdcExact(25_000_001n)).toBe('25.000001');
  });

  it('крупные суммы печатаются целиком, без экспоненты и потери разрядов', () => {
    expect(usdcExact(123_456_789_012_345n)).toBe('123456789.012345');
  });

  it('половины нечётного котла печатаются как РАЗНЫЕ строки', () => {
    const { toExecutor, toClient } = splitPot(33n);
    expect(usdcExact(toExecutor)).not.toBe(usdcExact(toClient));
  });
});
