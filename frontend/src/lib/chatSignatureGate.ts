/**
 * chatSignatureGate.ts — когда можно открывать окно кошелька, а когда нельзя.
 *
 * ─── ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ ─────────────────────────────────────────────
 *
 * На телефоне кошелёк — ОТДЕЛЬНОЕ ПРИЛОЖЕНИЕ. Переключение на него замораживает
 * нашу страницу системой. Мы в этот момент запускали вторую подпись
 * автоматически — и она уходила в спящую страницу, теряясь до того, как человек
 * вернётся сам.
 *
 * Итог живого замера 8 августа: ключ выведен и лежит в хранилище телефона, но
 * НИКОМУ НЕ ОБЪЯВЛЕН (`POST /keys` берёт адрес из пропуска, а пропуск — из
 * второй подписи). Человек видит «никто не подключен» и уходит.
 *
 * На десктопе кошелёк-расширение живёт в той же странице, замораживания не
 * происходит — поэтому «на десктопе всегда всё гуд».
 *
 * ─── ПОЧЕМУ РАЗЛИЧАЕМ ИМЕННО ТАК ────────────────────────────────────────────
 *
 * Различать телефон от десктопа по названию браузера ЗАПРЕЩЕНО прямым указанием
 * и по существу: это гадание. Встроенный браузер кошелька, планшет с мышью,
 * десктоп с кошельком по QR-коду — все четверо ломают любую таблицу названий.
 *
 * Различаем по ПОВЕДЕНИЮ, которое и есть причина беды: **пропадала ли страница
 * из глаз, пока мы говорили с кошельком.** Пропадала — значит кошелёк снаружи,
 * значит следующую подпись обязан запустить человек нажатием. Не пропадала —
 * значит кошелёк здесь же, и всё идёт как шло (десктопный путь не удлиняется
 * ни на одно нажатие).
 *
 * Второй, более грубый порог рядом: **пока страница скрыта, подпись не просится
 * вовсе.** Он нужен сам по себе — опрос ящика тикает и в фоне (30 с), и на
 * холодном пропуске звал бы кошелёк у свёрнутого приложения.
 *
 * ─── ГДЕ СТОИТ ПОРОГ ────────────────────────────────────────────────────────
 *
 * Вокруг САМОГО ОКНА КОШЕЛЬКА, а не вокруг пропуска. Разница дорогая: пропуск
 * живёт 12 часов в `localStorage`, и на живом пропуске подписи нет вовсе.
 * Поставив порог вокруг пропуска, мы отняли бы работу у всех, у кого он уже
 * есть, — то есть у большинства заходов.
 */

/* ───────────────────────────── что видно снаружи ──────────────────────────── */

export type SignatureGateVerdict =
  /** Можно спрашивать кошелёк прямо сейчас. */
  | 'go'
  /** Страница скрыта. Спрашивать нельзя ничего и никак: окно уйдёт в никуда. */
  | 'page_hidden'
  /** Страница видима, но мы только что уходили к кошельку. Следующую подпись
   *  обязан запустить человек нажатием. */
  | 'needs_press';

/**
 * Причины отсрочки шире вердикта порога: опрос ящика откладывают и тогда, когда
 * подписывать нечего — пока наш ключ не объявлен, на складе для нас не может
 * лежать ни одного мешка (разбор — `lib/chatAnnounce.ts`).
 *
 * Отдельным типом, а не расширением вердикта: `signatureGateVerdict` про ОКНО
 * КОШЕЛЬКА и обязана остаться про него, иначе чистая функция начнёт отвечать на
 * второй вопрос и перестанет быть проверяемой одной таблицей.
 */
export type DeferReason = Exclude<SignatureGateVerdict, 'go'> | 'not_announced';

export interface SignatureGateInput {
  /** `document.visibilityState === 'hidden'` прямо сейчас. */
  hiddenNow: boolean;
  /** Страница пропадала из глаз с тех пор, как мы в прошлый раз пошли к кошельку. */
  wentAwayForWallet: boolean;
  /** Человек нажал кнопку. Прямое действие — страница заведомо жива и на переднем
   *  плане, потому что нажать по невидимой кнопке нельзя. */
  humanAsked: boolean;
}

/**
 * Единственное решающее правило, чистой функцией.
 *
 * Порядок проверок важен и он такой: скрытая страница перебивает даже прямую
 * просьбу человека. Нажатие могло случиться и до того, как приложение свернули
 * (палец по кнопке, звонок, переключение) — и тогда окно всё равно уйдёт в
 * никуда. Пустить его туда «потому что человек же просил» значило бы потерять
 * подпись ровно тем способом, от которого этот файл заведён.
 */
export function signatureGateVerdict(input: SignatureGateInput): SignatureGateVerdict {
  if (input.hiddenNow) return 'page_hidden';
  if (input.humanAsked) return 'go';
  if (input.wentAwayForWallet) return 'needs_press';
  return 'go';
}

/**
 * Отказ порога. НЕ ошибка кошелька, НЕ ошибка входа — именно «ещё не время».
 *
 * ⚠️ ОТДЕЛЬНЫЙ КЛАСС, А НЕ `Error` С ТЕКСТОМ. Опрос ящика считает отказы
 * `getPass` «неудачами входа» и на третьей подряд останавливает опрос навсегда
 * (`pollBags`, `DEFAULT_AUTH_FAILURE_LIMIT`). Отдать ему обычный отказ значило
 * бы убить чат за то, что человек ещё не нажал кнопку — то есть своя починка
 * оказалась бы хуже дефекта.
 */
export class ChatSignatureDeferred extends Error {
  readonly reason: DeferReason;
  constructor(reason: DeferReason) {
    super(reason === 'page_hidden'
      ? 'Подпись не запрашивается, пока страница скрыта'
      : reason === 'not_announced'
        ? 'Опрос ящика отложен: наш ключ ещё не объявлен, писать нам некуда'
        : 'Подпись ждёт нажатия человека: кошелёк уводил страницу из глаз');
    this.name = 'ChatSignatureDeferred';
    this.reason = reason;
  }
}

export function isSignatureDeferred(err: unknown): err is ChatSignatureDeferred {
  return err instanceof ChatSignatureDeferred;
}

/* ─────────────────────── память о том, что страница уходила ────────────────── */

/**
 * Наименьшее, что нам нужно от страницы. Тип свой, а не `Document`: модуль
 * обязан работать и на сервере (Next собирает страницы в узле, `document` там
 * нет вовсе), и в замерах, где страницу подделывают.
 */
interface PageLike {
  visibilityState?: string;
  addEventListener?: (type: string, fn: () => void) => void;
  removeEventListener?: (type: string, fn: () => void) => void;
}

/** Читается КАЖДЫЙ РАЗ, а не запоминается при загрузке модуля: иначе замер,
 *  подделывающий страницу, менял бы её после того, как мы её запомнили, и порог
 *  сторожил бы прошлое. */
function page(): PageLike | null {
  const doc = (globalThis as { document?: PageLike }).document;
  return doc && typeof doc === 'object' ? doc : null;
}

/** Страница скрыта прямо сейчас. Нет страницы вовсе (сервер) — считаем видимой:
 *  на сервере окон кошелька не бывает, и запирать там нечего. */
export function pageHidden(): boolean {
  return page()?.visibilityState === 'hidden';
}

/**
 * Уходила ли страница из глаз с последнего обращения к кошельку.
 *
 * Взводится слушателем, а не опросом: узнать про ПРОШЛОЕ скрытие иначе нечем, а
 * оно и есть главный случай. Обычный порядок на телефоне такой:
 *
 *   1. просим первую подпись → `noteWalletHandoff()`;
 *   2. система показывает кошелёк → страница `hidden` → отметка взведена;
 *   3. человек подтвердил и вернулся → страница снова `visible`;
 *   4. мы хотим вторую подпись — страница видима, но отметка помнит шаг 2.
 *
 * Без шага 4 порог сработал бы только в том случае, когда ответ кошелька
 * приходит, пока приложение ещё свёрнуто (WalletConnect), и промахнулся бы на
 * втором — когда человек возвращается сам (встроенный браузер, deep link).
 */
let _wentAway = false;
let _watching = false;
let _onVisibility: (() => void) | null = null;

function watch(): void {
  if (_watching) return;
  const doc = page();
  if (!doc?.addEventListener) return;
  _onVisibility = () => { if (pageHidden()) _wentAway = true; };
  doc.addEventListener('visibilitychange', _onVisibility);
  _watching = true;
}

/**
 * «Мы пошли к кошельку» — зовётся ровно перед окном подписи.
 *
 * Отметку СБРАСЫВАЕТ, а не только взводит наблюдение: каждое новое обращение к
 * кошельку начинает свой отсчёт. Иначе одно давнее сворачивание приложения
 * требовало бы нажатия до конца жизни вкладки — то есть порог из защиты
 * превратился бы в вечную преграду.
 */
export function noteWalletHandoff(): void {
  _wentAway = false;
  watch();
  // Уже скрыта в момент обращения — это тот же уход, только раньше.
  if (pageHidden()) _wentAway = true;
}

export function wentAwayForWallet(): boolean {
  return _wentAway;
}

/**
 * Человек нажал кнопку — прошлое больше не в счёт.
 *
 * Зовётся из обработчика нажатия, а не из порога: порог обязан оставаться чистой
 * функцией. Без этого сброса второе нажатие после успешной подписи снова
 * упиралось бы в отметку, оставленную первым.
 */
export function clearWalletHandoff(): void {
  _wentAway = false;
}

/** Только для замеров: вернуть невзведённое состояние вместе с наблюдением. */
export function _resetSignatureGateForTest(): void {
  const doc = page();
  if (_onVisibility && doc?.removeEventListener) doc.removeEventListener('visibilitychange', _onVisibility);
  _wentAway = false;
  _watching = false;
  _onVisibility = null;
}

/**
 * Порог целиком: посчитать вердикт по живой странице.
 *
 * Собран здесь, а не в месте вызова, чтобы «прямо сейчас» читалось из одного
 * места. Мест вызова два (`signChatKeyLocked` и `getBagPass`), и разъехаться им
 * нельзя: разъехавшись, один из них снова начнёт стрелять в спящую страницу.
 */
export function checkSignatureGate(humanAsked = false): SignatureGateVerdict {
  return signatureGateVerdict({
    hiddenNow: pageHidden(),
    wentAwayForWallet: wentAwayForWallet(),
    humanAsked,
  });
}

/**
 * Пропустить или отказать. Отказ — `ChatSignatureDeferred`, чтобы вызывающий
 * отличил «ещё не время» от «кошелёк сломался».
 */
export function requireSignatureGate(humanAsked = false): void {
  const verdict = checkSignatureGate(humanAsked);
  if (verdict !== 'go') throw new ChatSignatureDeferred(verdict);
}
