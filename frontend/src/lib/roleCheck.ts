import { classifyReadFailure } from '@/lib/contractReadError';

/**
 * Три ответа на вопрос «есть ли у этого адреса роль» вместо двух — плюс
 * честное «ещё проверяем».
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. 2 августа 2026 у владельца пропала роль арбитра:
 * вкладка «Арбитр» исчезла из шапки, пункты арбитра — из меню кошелька. На
 * цепи `isRegisteredArbiter` возвращал `true`; ручной `fetch` к `/api/rpc` из
 * того же браузера — тоже `true`; баланс USDC в том же меню показывался верно.
 * Виноват был один перебойный `502` от нашего же RPC-прокси и одна строка:
 *
 *     const isArbiter = !!isArbiterRaw;   // data: boolean | undefined
 *
 * `!!undefined` — это `false`. То есть СБОЙ СЕТИ ПРЕВРАЩАЛСЯ В УВЕРЕННОЕ
 * «ты не арбитр»: интерфейс исчезал молча, без единого намёка, что дело в
 * связи, и вернуть его можно было только перезагрузкой страницы (у react-query
 * в этом приложении `refetchInterval: false` и `refetchOnWindowFocus: false` —
 * упавший запрос сам не переспрашивается).
 *
 * ЭТО ТОТ ЖЕ КЛАСС, что «оборот $0 при сбое сабграфа» и «услуг вы ещё не
 * публиковали» при ревертнувшем чтении: отказ, притворяющийся данными.
 *
 * ДВА ПРАВИЛА, И ОНИ НЕ ПРОТИВОРЕЧАТ ДРУГ ДРУГУ:
 *
 *  1. **Прав при неизвестном состоянии не выдавать.** Кнопки, решающие судьбу
 *     чужих денег, показывать не убедившись в роли нельзя. Поэтому `'unreadable'`
 *     НЕ открывает ничего — ровно как `'no'`.
 *  2. **Но и обратного не утверждать.** Раз мы не знаем, надо так и сказать:
 *     видимый признак и кнопка «повторить», а не молчаливое исчезновение.
 *
 * ПОЧЕМУ ЧЕТЫРЕ ЗНАЧЕНИЯ, А НЕ ТРИ. `'checking'` — это не четвёртый ответ, а
 * отсутствие ответа в первые доли секунды. Слить его с `'unreadable'` нельзя:
 * тогда предупреждение «не смогли проверить» вспыхивало бы на КАЖДОЙ загрузке
 * страницы, обесценилось бы за день и перестало бы читаться как тревога именно
 * тогда, когда оно настоящее.
 */
export type RoleCheck = 'yes' | 'no' | 'checking' | 'unreadable';

/** Ровно те поля, что отдаёт `useReadContract` — но без самого wagmi, чтобы
 *  правило проверялось тестами без сети, React и провайдеров. */
export interface RoleRead<T> {
  data: T | undefined;
  isError: boolean;
  error?: unknown;
  /** `isPending` у wagmi/react-query: ответа ещё нет и запрос не провалился. */
  isPending: boolean;
  /** Есть ли вообще кого проверять (`query.enabled`). */
  enabled: boolean;
}

/**
 * Свести состояние чтения к вердикту о роли.
 *
 * `decide` отвечает на вопрос «это значение означает роль?» — для
 * `isRegisteredArbiter` это `Boolean`, для `owner()` — сравнение адресов.
 * Разделение нужно, чтобы правило про сбои было ОДНО на все роли: именно
 * размножение этой логики по месту использования и дало разное поведение
 * в шапке, в меню и в защите маршрута `/arbiter`.
 */
export function roleFromRead<T>(read: RoleRead<T>, decide: (data: T) => boolean): RoleCheck {
  // Кошелёк не подключён / адреса нет — проверять некого. Это не «сбой»:
  // никакой роли нет и вопроса нет.
  if (!read.enabled) return 'no';

  // ПОРЯДОК ВАЖЕН: данные проверяются ДО ошибки, и это не небрежность.
  //
  // У react-query (v5) `status` становится `'error'` при провале ЛЮБОГО
  // чтения, включая фоновое перечитывание, а уже полученное `data` при этом
  // сохраняется. Значит `isError && data !== undefined` — это «час назад цепь
  // ответила, только что переспросить не вышло». Это не «мы не знаем»: ответ
  // цепи у нас есть, он просто не свежий, а роли меняются раз в месяцы. Ключ
  // запроса у wagmi включает адрес, так что чужого ответа тут оказаться не
  // может — при смене кошелька это другой запрос, и `data` у него пуст.
  //
  // Ставить ошибку первой значило бы поднимать тревогу «не смогли проверить»
  // на каждой сетевой ряби, ничего при этом не меняя на экране. Предупреждение,
  // которое видно каждый день, перестают читать — и оно промолчит в тот раз,
  // когда оно настоящее.
  if (read.data !== undefined) return decide(read.data) ? 'yes' : 'no';

  // ⚠️ Реверт даёт 'unreadable', а не 'no'. `isRegisteredArbiter` — обычная
  // view-функция, которая либо вернёт bool, либо не вернёт ничего; её реверт
  // означает «селектора нет / фасет снят», а вовсе не «этот адрес не арбитр».
  // Считать отказ цепи отрицательным ответом — та же ошибка, ради которой
  // написан весь файл, только этажом ниже. Различие 'contract'/'transport' из
  // `classifyReadFailure` при этом не пропадает — см. `roleFailureKind`, оно
  // идёт в журнал.
  if (read.isError) return 'unreadable';

  // Данных нет, ошибки нет — либо ещё летит, либо react-query поставил запрос
  // на паузу (офлайн). И то и другое — «пока не знаем», и права не выдаются.
  if (read.isPending) return 'checking';

  // Сюда попадать нечему, но если попадём — «не знаем» безопаснее, чем «нет».
  return 'unreadable';
}

/**
 * Чем именно кончился провал — для журнала. UI на это не смотрит намеренно:
 * человеку в обоих случаях одинаково нечего показать, а вот расследованию
 * разница между «RPC отвалился» и «цепь ответила отказом» стоит недели.
 */
export function roleFailureKind(read: { isError: boolean; error?: unknown }): 'contract' | 'transport' | null {
  if (!read.isError) return null;
  return classifyReadFailure(read.error);
}

/** Роль подтверждена. ЕДИНСТВЕННЫЙ способ получить право — правило 1. */
export function roleGranted(check: RoleCheck): boolean {
  return check === 'yes';
}

/**
 * Роль подтверждённо отсутствует. Не то же самое, что `!roleGranted`.
 *
 * Нужно там, где действие имеет смысл только для НЕ-обладателя роли:
 * «Стать арбитром» при непрочитанной роли раньше показывалась (потому что
 * условие было `!isArbiter`, а `!false` — правда) и вела в гарантированный
 * реверт `applyAsArbiter`, потому что человек-то уже арбитр.
 */
export function roleDenied(check: RoleCheck): boolean {
  return check === 'no';
}

/** Надо ли сказать человеку, что проверка не удалась. */
export function roleUnreadable(...checks: RoleCheck[]): boolean {
  return checks.some(c => c === 'unreadable');
}
