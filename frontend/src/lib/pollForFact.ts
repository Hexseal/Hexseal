/**
 * «Опрашивать до факта» — один приём, вынесенный из двух мест, где он уже жил.
 *
 * ЗАЧЕМ. RPC за одним URL — это пул реплик (у нас drpc, за ним несколько
 * провайдеров), и чтение сразу после записи спокойно попадает на узел, который
 * этот блок ещё не видел. Квитанция транзакции тут ничего не обещает: она
 * доказывает, что транзакция замайнена, но не то, какой узел ответит на
 * СЛЕДУЮЩЕЕ чтение. Лечение везде одно — не читать один раз и надеяться, а
 * опрашивать, пока чтение не подтвердит факт.
 *
 * ГДЕ ЭТО УЖЕ БЫЛО:
 *  • `lib/walletLock.ts` — счётчик форвардера обязан быть больше того, который
 *    этот кошелёк уже потратил (иначе подпись уходит со старым nonce и релеер
 *    отвечает «nonce mismatch»);
 *  • `lib/subgraphSync.ts` — голова сабграфа обязана дойти до блока квитанции
 *    (иначе сброс кэша цементирует непроиндексированный снимок на 120 секунд);
 *  • `app/api/relay/route.ts` — allowance после permit'а.
 *
 * Шестой случай за сутки (роль арбитра сразу после квитанции) должен был стать
 * четвёртой копией цикла. Вместо копии — этот файл, и первый же из
 * перечисленных на него переведён.
 *
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ: сети, viem, ABI и любого знания о том, ЧТО
 * читается. Всё это приходит колбэком — так модуль проверяется тестами без
 * сети и годится и для цепи, и для чего угодно ещё с тем же свойством
 * «правда приедет, но не сразу».
 */

/** Шаг опроса по умолчанию. Блок Base Sepolia — 2 секунды, чаще смысла нет:
 *  за меньший интервал новый блок появиться не может, а каждая проба — полный
 *  round-trip через наш же прокси. Меньше времени блока — чтобы гарантированно
 *  не перепрыгнуть блок целиком. */
export const DEFAULT_POLL_INTERVAL_MS = 750;

/** Сколько всего чтений (первое + повторы). 9 × 750 мс — потолок 6 секунд, то
 *  есть три блока Base Sepolia при замеренном отставании реплик порядка одного
 *  блока. Выше задирать нельзя: человек всё это время смотрит на «крутилку». */
export const DEFAULT_POLL_ATTEMPTS = 9;

export interface FactPollOptions {
  attempts?: number;
  intervalMs?: number;
  sleep?: (ms: number) => Promise<void>;
}

export interface FactPollResult<T> {
  /** Последнее УДАЧНО прочитанное значение. */
  value: T;
  /** Подтвердилось ли то, чего ждали. `false` — вышли попытки. */
  satisfied: boolean;
  /** Сколько раз реально звали `read` (включая упавшие пробы). */
  reads: number;
  /**
   * Сколько проб РАЗОБРАЛОСЬ, то есть вернуло значение вместо броска. Первая
   * всегда среди них: её бросок уходит наружу, и результата не бывает вовсе.
   *
   * ⚠️ ЗАЧЕМ ОТДЕЛЬНОЕ ЧИСЛО (итоговое ревью ветки 4в-2, правка 4). По `reads`
   * НЕЛЬЗЯ отличить «узел отвечал девять раз и девять раз сказал нет» от «узел
   * ответил однажды и замолчал»: оба дают `reads: 9`, `satisfied: false` и одно
   * и то же последнее значение. А цена у них разная — первое это вердикт,
   * второе неизвестность. `lib/relayTarget.ts` отвечает на них разными кодами
   * (403 против 503), и без этого числа отличить их ему нечем.
   */
  okReads: number;
}

/**
 * Зовёт `read`, пока `satisfied` не скажет «да», но не больше `attempts` раз.
 *
 * Три правила, и все три — с живых случаев:
 *
 *  1. Первое чтение происходит СРАЗУ, без сна. Отставания могло не быть вовсе,
 *     а лишние секунды ожидания на ровном месте — чистый вред.
 *  2. Исчерпали попытки — возвращаем `satisfied: false` и последнее
 *     прочитанное. Молча висеть нельзя: вызывающая сторона обязана либо
 *     сказать человеку, либо хотя бы оставить след в журнале, а зависшая
 *     кнопка выглядит как сломанное приложение.
 *  3. Сбой ОДНОЙ пробы (сеть моргнула) не роняет весь путь — цикл идёт дальше
 *     с последним удачно прочитанным значением. Сбой ПЕРВОГО чтения бросается
 *     наружу: значения нет вообще, отдавать нечего.
 */
export async function pollForFact<T>(
  read: () => Promise<T>,
  satisfied: (value: T) => boolean,
  opts: FactPollOptions = {},
): Promise<FactPollResult<T>> {
  const attempts   = opts.attempts   ?? DEFAULT_POLL_ATTEMPTS;
  const intervalMs = opts.intervalMs ?? DEFAULT_POLL_INTERVAL_MS;
  const sleep      = opts.sleep      ?? (ms => new Promise<void>(r => setTimeout(r, ms)));

  // Правило 3, вторая половина: первое чтение не глушится.
  let value = await read();
  let reads = 1;
  let okReads = 1;
  if (satisfied(value)) return { value, satisfied: true, reads, okReads };

  for (let attempt = 1; attempt < attempts; attempt++) {
    await sleep(intervalMs);
    reads++;
    try {
      value = await read();
      okReads++;
    } catch {
      continue; // правило 3
    }
    if (satisfied(value)) return { value, satisfied: true, reads, okReads };
  }

  return { value, satisfied: false, reads, okReads }; // правило 2
}
