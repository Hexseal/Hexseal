/**
 * facetPresence.ts — «эта часть уже есть в цепи или ещё нет».
 *
 * ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Фронт этой ветки пишется ДО разреза: фасет
 * `ArbiterAccountabilityFacet` в даймонде ещё не смонтирован, и каждая новая
 * функция сегодня отсутствует. Вызов такого селектора уходит в fallback
 * даймонда и ревертит там строкой `"Diamond: function not found"`
 * (`src/DiamondProxy.sol`).
 *
 * Без разбора этого случая экран сыпал бы непонятными отказами, и владелец,
 * открыв страницу, полез бы искать поломку, которой нет. У нас это уже было —
 * поэтому экран обязан сказать прямо: «этой части ещё нет в цепи, будет после
 * разреза».
 *
 * ⚠️ И «НЕТ В ЦЕПИ» — ЭТО НЕ «СЕТЬ НЕ ОТВЕТИЛА». Новости разные, и советы
 * разные: первое лечится разрезом (и ждать его нечего — кнопки просто ещё
 * нет), второе — обновлением страницы. Свалить их в один текст значило бы
 * посоветовать ждать разреза человеку, у которого просто отвалился RPC.
 * Поэтому состояний четыре, а не два.
 */

export type FacetPresence =
  /** Ещё спрашиваем. */
  | 'checking'
  /** Ответила — селектор смонтирован. */
  | 'ready'
  /** Отказ ровно тот, который даёт даймонд на несмонтированном селекторе. */
  | 'absent'
  /** Отказ другой: сеть, RPC, что угодно ещё. */
  | 'unreachable';

/**
 * Признаки отказа даймонда на несмонтированном селекторе.
 *
 * ⚠️ ДВЕ СТРОКИ, А НЕ ОДНА, И ОБЕ НУЖНЫ. Первая — сама причина ревёрта из
 * `DiamondProxy.fallback`. Вторая — как viem описывает вызов, вернувший пустоту
 * («The contract function ... returned no data ("0x")»): на части провайдеров
 * eth_call с ревёртом строкой доезжает именно так, без самой строки. Оставить
 * только первую значило бы отдать честный случай в `unreachable` и посоветовать
 * обновить страницу там, где обновление не поможет никогда.
 */
const ABSENT_MARKERS = [
  'function not found',
  'returned no data',
];

/**
 * Разбор ответа `useReadContract` в одно из четырёх состояний.
 *
 * Аргументы намеренно «плоские», а не объект wagmi: у крючка форма меняется от
 * версии к версии, а этот разбор — про смысл, и его надо звать из теста без
 * половины React.
 */
export function facetPresence(read: {
  data: unknown;
  isLoading: boolean;
  error?: { message?: string } | null;
}): FacetPresence {
  // ⚠️ ДАННЫЕ СТАРШЕ ОТКАЗА, И ЭТО ПОЧИНКА, А НЕ ВКУС (круг правок 1).
  //
  // Раньше `error` проверялся первым, и замер ревьюера показал цену: ответ уже
  // прочитан (`data: 172800n`), очередной ПЕРЕЗАПРОС сорвался на 502 — и весь
  // экран уезжал в `unreachable`. То есть одна неудачная сетевая попытка гасила
  // числа и кнопки на ВСЕХ карточках списка, хотя правила цепи давно известны и
  // измениться не могли: все пять геттеров `pure`.
  //
  // wagmi держит прошлые данные рядом с новой ошибкой намеренно — это и есть
  // ответ на вопрос «что показывать, пока перезапрос не удался». Показывать
  // данные.
  if (read.data !== undefined && read.data !== null) return 'ready';

  if (read.error) {
    const text = (read.error.message ?? '').toLowerCase();
    return ABSENT_MARKERS.some((m) => text.includes(m)) ? 'absent' : 'unreachable';
  }

  // ⚠️ Отказ разобран ВЫШЕ загрузки нарочно: wagmi при повторе поднимает
  // `isLoading` обратно, не убирая `error`, и проверь мы загрузку первой —
  // «этой части ещё нет в цепи» мигало бы «спрашиваем…» каждые несколько
  // секунд. Сюда доходит только случай «ни данных, ни отказа», и это ровно
  // «ещё не знаем».
  return 'checking';
}
