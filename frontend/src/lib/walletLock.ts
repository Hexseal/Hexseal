'use client';

/**
 * walletLock.ts — один мьютекс на кошелёк для ВСЕГО приложения плюс память о
 * последнем израсходованном этим кошельком nonce форвардера (вторая половина
 * файла — она про ту же очередь и тот же адрес, см. её собственную шапку).
 *
 * Раньше эта функция жила внутри `lib/relay.ts` и была приватной. Её брали
 * только двенадцать гейслесс-путей в том же файле; ни один другой запрос
 * подписи — XMTP-инициализация, push-подписка, профиль, причина спора,
 * журнал арбитра — мьютекс не брал вообще. Кошелёк при этом умеет держать
 * ровно один открытый запрос: второй прилетает как
 *
 *   Request of type 'personal_sign' already pending for origin … (-32002)
 *
 * и в мобильном MetaMask его нечем отменить — просьба об этом висит у них с
 * 2023 года, единственный способ снять залипший запрос — закрыть приложение
 * кошелька начисто. То есть цена гонки здесь не «неудобно», а «человек
 * заблокирован до перезапуска кошелька».
 *
 * Поэтому мьютекс вынесен сюда и берётся ВЕЗДЕ, где может всплыть окно
 * подписи, включая законные действия человека: два подряд нажатия на разных
 * поверхностях (страница сделки и её же чат) — такая же гонка, как две
 * автоматики.
 *
 * Поведение специально не менялось при переносе: тот же таймаут, та же
 * очередь, тот же Web Locks поверх неё.
 */

import { pollForFact } from '@/lib/pollForFact';

// Каждый гейслесс-вызов для кошелька читает nonce (getNonce у форвардера
// и/или permit-nonce у USDC) и подписывается против него — но два вызова для
// ОДНОГО кошелька, стартовавшие рядом (заявка на две работы, действия по двум
// сделкам с одного дашборда), прочитают один и тот же nonce, оба будут
// подписаны, и второй долетевший до цепи ревертнётся. Человек платит трением
// настоящей подписи и за проигравший вызов, а видит невнятный дамп ошибки
// контракта без намёка, что достаточно просто повторить. Очередь на адрес
// заставляет второй вызов дождаться первого (успех или провал — неважно,
// nonce либо уже израсходован, либо не был отправлен) до чтения nonce.
const _walletLocks = new Map<string, Promise<void>>();

// Взятый лок освобождается только из `finally` держателя — а операции под ним
// (окно подписи без таймаута на уровне кода, мобильный круг WalletConnect)
// могут висеть бесконечно на совершенно обычном поведении кошелька
// (человек свернул вкладку посреди подписи, бросил открытое окно, мобильная
// сессия отвалилась и никогда не ответит отказом). Без потолка один брошенный
// вызов молча заклинил бы ЛЮБОЕ другое действие с подписью для этого кошелька
// — во всём приложении, до конца сессии, без ошибки и без выхода, кроме полной
// перезагрузки страницы. Ждём столько и пропускаем следующего в очереди,
// считая держателя брошенным. Это заново открывает узкое окно для той самой
// гонки nonce (только если брошенный вызов каким-то образом воскреснет после
// этой точки), но редкое дешёвое повторение уже обработанного сбоя куда лучше
// бессрочного клина без выхода.
const WALLET_LOCK_TIMEOUT_MS = 3 * 60_000; // 3 мин — с запасом на живое ожидание подписи

/** Ждёт, пока закончится любой ранее вставший в очередь вызов для этого
 *  кошелька, затем резервирует лок за вызывающим. Возвращает release-колбэк,
 *  который ОБЯЗАН быть вызван в `finally`, иначе следующий в очереди не
 *  поедет.
 *
 *  Map выше сериализует вызовы только внутри JS-рантайма ОДНОЙ вкладки — один
 *  и тот же кошелёк, действующий с двух сопутствующих поверхностей в разных
 *  вкладках/окнах (страница сделки и её же чат; список борда и страница
 *  конкретной работы — вполне реальные пары, не выдуманный сценарий), общего
 *  состояния не имеет и всё ещё может разыграть тот же nonce. Где доступно,
 *  берём поверх этого лок Web Locks API с тем же ключом: это настоящий
 *  меж-вкладочный мьютекс, и браузер сам отпускает его, если держащая вкладка
 *  закрылась или упала — чего Map в памяти для ДРУГОЙ вкладки не может в
 *  принципе. На браузерах без navigator.locks деградирует мягко (защита в
 *  пределах вкладки, как было). */
export async function acquireWalletLock(address: string): Promise<() => void> {
  const key = address.toLowerCase();
  const ahead = _walletLocks.get(key) ?? Promise.resolve();
  let release!: () => void;
  const ours = new Promise<void>(resolve => { release = resolve; });
  // Встаём новым хвостом очереди ДО любого await, чтобы третий параллельный
  // вызов встал за нами, а не за тем, кто был впереди нас.
  _walletLocks.set(key, ours);
  await Promise.race([
    ahead.then(() => {}, () => {}),
    new Promise<void>(resolve => setTimeout(resolve, WALLET_LOCK_TIMEOUT_MS)),
  ]);

  let releaseWebLock: (() => void) | undefined;
  if (typeof navigator !== 'undefined' && 'locks' in navigator) {
    try {
      await Promise.race([
        new Promise<void>(resolveAcquired => {
          navigator.locks.request(`hexseal-wallet-${key}`, () => new Promise<void>(resolveRelease => {
            releaseWebLock = resolveRelease;
            resolveAcquired();
          })).catch(() => { resolveAcquired(); }); // не поддержано/ошибка — едем без меж-вкладочной защиты
        }),
        new Promise<void>(resolve => setTimeout(resolve, WALLET_LOCK_TIMEOUT_MS)),
      ]);
    } catch { /* едем без меж-вкладочной защиты */ }
  }

  return () => {
    release();
    // Чистим запись в Map, только если за нами никто не встал — иначе мы
    // выдернем ссылку, на которую всё ещё смотрит `ahead` следующего.
    if (_walletLocks.get(key) === ours) _walletLocks.delete(key);
    releaseWebLock?.();
  };
}

/** Обёртка `acquireWalletLock` + `finally` для мест, где мьютекс нужен вокруг
 *  одного вызова подписи, а не вокруг длинной процедуры. Держит лок ровно на
 *  время `fn` — включая её собственные await'ы. */
export async function withWalletLock<T>(address: string, fn: () => Promise<T>): Promise<T> {
  const release = await acquireWalletLock(address);
  try {
    return await fn();
  } finally {
    release();
  }
}

// ─── Память о израсходованном nonce форвардера ────────────────────────────────
//
// Очередь выше решает половину задачи: два вызова для одного кошелька больше не
// читают nonce одновременно. Вторая половина — что даже строго ПОСЛЕ первого
// вызова прочитанный nonce может быть старым. RPC за одним URL — это пул реплик
// (у нас drpc, за ним несколько провайдеров), и следующее чтение спокойно
// попадает на узел, который предыдущий блок ещё не видел. Квитанция первой
// транзакции этого не спасает: она доказывает, что транзакция замайнена, но
// ничего не обещает про то, какой узел ответит на следующее чтение.
//
// Живой случай, 1 августа 2026: арбитр 0x42dCd14e жмёт «Принять дело», страница
// шлёт commitDisputeClaim (nonce 0, замайнен, счётчик на цепи стал 1) и сразу
// claimDispute — чтение вернуло всё ещё 0, подпись ушла с 0, релеер получил
// «MinimalForwarder: nonce mismatch», кнопка не работает вообще.
//
// Лечение — то же, что в четырёх других местах, где мы сегодня наткнулись на
// отставание реплик (`app/api/relay/route.ts` — allowance после permit,
// `relayer/app.js` — RECEIPT_POLL, `lib/subgraphSync.ts` — голова сабграфа):
// не читать один раз и надеяться, а опрашивать до факта. Факт здесь —
// «прочитанный счётчик больше того, который мы этим кошельком уже потратили».

/** Шаг опроса. Блок Base Sepolia — 2 секунды, значит чаще смысла нет: за
 *  меньший интервал новый блок появиться не может, а каждая проба — полный
 *  round-trip через наш же прокси `/api/rpc`. Меньше времени блока — чтобы
 *  гарантированно не перепрыгнуть блок целиком. */
const NONCE_POLL_INTERVAL_MS = 750;

/** Сколько всего чтений (первое + повторы). 9 чтений с шагом 750 мс — потолок
 *  ожидания 6 секунд, то есть три блока Base Sepolia. Замеренное отставание
 *  реплик того же порядка, что блок (соседний гейт в `api/relay/route.ts`
 *  обходится 5 пробами по 400 мс), так что три блока — кратный запас. Выше
 *  задирать нельзя: это ожидание стоит МЕЖДУ двумя окнами подписи, человек
 *  сидит и смотрит на «подтверждаем…». */
const NONCE_POLL_ATTEMPTS = 9;

/** Срок годности записи. Отставание реплик измеряется секундами; запись
 *  старше этого срока не несёт информации ни о чём.
 *
 *  Зачем срок вообще: nonce запоминается в момент ОТПРАВКИ, до того как
 *  известен исход, — иначе инвариант «не подписывать второй раз nonce, который
 *  уже улетел» не держится. Если та отправка в итоге не долетела до цепи
 *  (релеер отказал на симуляции, сработал прямой фолбэк мимо форвардера),
 *  счётчик на цепи не сдвинулся никогда, и без срока годности КАЖДОЕ следующее
 *  действие этого кошелька — вечно, во всех будущих сессиях — выжидало бы
 *  полный потолок впустую. */
const NONCE_MEMORY_TTL_MS = 5 * 60_000;

/** Резерв на случай недоступного localStorage (приватный режим Safari, iframe с
 *  третьесторонними куками, отключённое хранилище). Тогда защита остаётся в
 *  пределах одной жизни вкладки — как было, но не хуже. */
const _memoryNonces = new Map<string, { nonce: bigint; at: number }>();

/** Ключ включает АДРЕС ФОРВАРДЕРА, а не только кошелька: у legacy-агриментов
 *  свой форвардер со своим независимым счётчиком, и общая запись на два
 *  форвардера сравнивала бы несравнимое. Заодно это даёт бесплатный сброс при
 *  замене форвардера — новый адрес, новый ключ, счётчик снова с нуля. */
function nonceKey(address: string, forwarder: string): string {
  return `hexseal-fwd-nonce-${forwarder.toLowerCase()}-${address.toLowerCase()}`;
}

/** Хранилище — `localStorage`, а не переменная в модуле.
 *
 *  Причина конкретная и подтверждённая на этом проекте: Android выгружает
 *  вкладку посреди подписи. Память модуля при этом исчезает целиком, и защита
 *  пропадала бы ровно там, где нужнее всего — на втором шаге двухшагового
 *  действия, которое человек продолжает после возврата во вкладку.
 *  `sessionStorage` тут хуже: он привязан к вкладке и на восстановленной вкладке
 *  восстанавливается не везде. `localStorage` переживает и выгрузку, и
 *  перезагрузку, и виден соседним вкладкам того же origin — а соседняя вкладка
 *  с тем же кошельком это ровно тот сценарий, который уже прикрыт Web Locks
 *  выше. */
function loadSpent(key: string): { nonce: bigint; at: number } | null {
  try {
    const raw = globalThis.localStorage?.getItem(key);
    if (raw) {
      const [nonceStr, atStr] = raw.split(':');
      const nonce = BigInt(nonceStr);
      const at = Number(atStr);
      if (Number.isFinite(at)) return { nonce, at };
    }
  } catch { /* хранилище недоступно или запись битая — падаем на память */ }
  return _memoryNonces.get(key) ?? null;
}

function saveSpent(key: string, entry: { nonce: bigint; at: number }): void {
  _memoryNonces.set(key, entry);
  try {
    globalThis.localStorage?.setItem(key, `${entry.nonce}:${entry.at}`);
  } catch { /* хранилище недоступно — остаёмся с памятью вкладки */ }
}

/** Запомнить nonce, с которым подпись УЖЕ УШЛА (не «успешно выполнилась» —
 *  именно ушла: с этого момента повторно подписывать его вслепую нельзя).
 *
 *  Строго вверх, повтор того же значения запись НЕ обновляет. Две причины:
 *  соседняя вкладка могла потратить больший nonce, и затирать её запись меньшим
 *  — снова открыть ту же гонку; а срок годности должен считаться от ПЕРВОЙ
 *  отправки этого nonce, иначе застрявший (так и не долетевший до цепи) nonce
 *  освежал бы себе TTL на каждой повторной попытке и не протухал никогда. */
export function rememberSpentForwarderNonce(address: string, forwarder: string, nonce: bigint): void {
  const key = nonceKey(address, forwarder);
  const prev = loadSpent(key);
  if (prev && prev.nonce >= nonce) return;
  saveSpent(key, { nonce, at: Date.now() });
}

export interface FreshNonceOptions {
  attempts?:   number;
  intervalMs?: number;
  sleep?:      (ms: number) => Promise<void>;
  now?:        () => number;
}

/** Читает nonce форвардера так, чтобы он гарантированно не был протухшим.
 *
 *  `read` — само чтение с цепи; сюда оно передаётся колбэком, чтобы этот файл
 *  не тянул viem и ABI ради одной строки и оставался проверяемым без сети.
 *
 *  Три правила, ради которых функция вообще существует:
 *
 *  1. Первая транзакция кошелька НИЧЕГО не ждёт. Нечего с чем сравнивать —
 *     ноль законное значение, а лишние 6 секунд на первом же действии человека
 *     это чистый вред.
 *  2. Исчерпали попытки — пишем в журнал и отдаём что прочитали. Молча висеть
 *     нельзя: внятный отказ от контракта человек хотя бы увидит и повторит, а
 *     зависшая кнопка выглядит как сломанное приложение.
 *  3. Сбой ОДНОЙ пробы (сеть моргнула) не роняет весь путь — цикл идёт дальше
 *     с последним удачно прочитанным значением. Сбой ПЕРВОГО чтения бросается
 *     наружу, как и раньше: без nonce подписывать нечего. */
export async function awaitFreshForwarderNonce(
  address: string,
  forwarder: string,
  read: () => Promise<bigint>,
  opts: FreshNonceOptions = {},
): Promise<bigint> {
  const attempts   = opts.attempts   ?? NONCE_POLL_ATTEMPTS;
  const intervalMs = opts.intervalMs ?? NONCE_POLL_INTERVAL_MS;
  const now        = opts.now        ?? Date.now;

  // Сам цикл опроса — общий (`lib/pollForFact.ts`): те же три правила, что
  // описаны выше, теперь живут в одном месте на все случаи «правда приедет, но
  // не сразу». Здесь остаётся только то, что специфично для nonce: что считать
  // фактом и когда ждать вообще не нужно.
  //
  // `spent` вычисляется ЛЕНИВО, на первой же проверке, а не заранее: порядок
  // важен — запись читается ПОСЛЕ первого чтения с цепи, как и было.
  // `null` означает «сравнивать не с чем» (правило 1: первая транзакция
  // кошелька ничего не ждёт) — тогда любое прочитанное значение годится.
  let spent: bigint | null | undefined;
  const isFresh = (nonce: bigint): boolean => {
    if (spent === undefined) {
      const remembered = loadSpent(nonceKey(address, forwarder));
      spent = (!remembered || now() - remembered.at > NONCE_MEMORY_TTL_MS)
        ? null                 // записи нет или она протухла
        : remembered.nonce;
    }
    return spent === null || nonce > spent;
  };

  const { value: nonce, satisfied } = await pollForFact(read, isFresh, {
    attempts, intervalMs, sleep: opts.sleep,
  });

  // Правило 2.
  if (!satisfied) {
    console.warn(
      `[relay] счётчик форвардера ${forwarder} для ${address} не сдвинулся с ${spent} ` +
      `за ${attempts} проб (${(attempts - 1) * intervalMs} мс) — узел отстал или та транзакция ` +
      `не долетела до цепи; подписываем с ${nonce}`,
    );
  }
  return nonce;
}
