/**
 * Что страница /notifications должна предложить по поводу пушей.
 *
 * Правило владельца: включение живёт на странице уведомлений, ОТКЛЮЧЕНИЕ — в
 * меню кошелька, рядом с отключением чата (components/WalletMenu.tsx). Поэтому
 * подключённые пуши убирают элемент со страницы: выключать его там больше нечем,
 * а «Push notifications on» с кнопкой «Turn off» дублировало меню кошелька и
 * занимало место над лентой.
 *
 * ⚠️ Ровно один способ сломать это правило, и он неочевиден.
 *
 * `subscribed` НЕ означает «пуши доходят». Утром 1 августа 2026 (eae891c) убрали
 * суточную фоновую перерегистрацию — она звала enablePush(), а тот подписывает
 * сообщение кошельком, то есть раз в сутки САМА, без нажатия, выбрасывала
 * человека в приложение кошелька (на Android/Chrome + MetaMask это прямой путь в
 * незакрываемое 'personal_sign already pending'). Взамен протухание не чинится
 * молча, а ПОКАЗЫВАЕТСЯ: `stale` поднимается, когда регистрация на релеере
 * старше суток, и человеку предлагают включить заново нажатием.
 *
 * Значит состояние «подписка числится, но мертва» обязано и дальше показывать
 * способ включить. Прячем только когда подписка есть И ЖИВА. Спрятать заодно и
 * протухшую — это вернуть молчаливый отказ доставки, ради ухода от которого всё
 * и делалось.
 */
export type PushPrompt =
  /** Показывать нечего: либо браузер не умеет, либо подписка есть и жива. */
  | 'none'
  /** Подписки нет — предложить включить. */
  | 'enable'
  /** Подписка есть, но её регистрация протухла — предложить включить заново. */
  | 'renew'
  /** Разрешение отозвано в браузере — включить нечем, объяснить куда идти. */
  | 'blocked';

export interface PushPromptInput {
  /** Браузер вообще умеет Web Push (isPushSupported). */
  supported: boolean;
  /** Notification.permission. */
  permission: NotificationPermission;
  /** Живая подписка устройства И запись регистрации для ЭТОГО адреса. */
  subscribed: boolean;
  /** Регистрация старше суток (PushContext.stale). */
  stale: boolean;
}

export function pushPrompt({ supported, permission, subscribed, stale }: PushPromptInput): PushPrompt {
  if (!supported) return 'none';
  // Запрет браузера бьёт всё остальное: пока он стоит, никакое нажатие
  // подписку не создаст, поэтому кнопку показывать нечестно.
  if (permission === 'denied') return 'blocked';
  if (!subscribed) return 'enable';
  return stale ? 'renew' : 'none';
}
