import { keccak256, encodePacked, isAddress } from 'viem';

/** ⚠️ Новое поле МОЖЕТ быть переменной ширины (`bytes`/`string`) — но
 *  СРЕДИ ВСЕХ ПОЛЕЙ КОДИРОВАНИЯ ТАКОЕ ДОПУСТИМО НЕ БОЛЕЕ ОДНОГО. Заперто
 *  тестом на список типов `LINK_ENCODING_TYPES`, раунд 5 (не на число байт —
 *  раунд 4 запирал 148 и это было неверным правилом, см. ниже).
 *
 *  Причина не стилистическая. Вся индукция «доверия» в verifyChain
 *  (unverifiedContentAtSeq, раунд 3) держится на том, что linkHash
 *  инъективна ДО хеширования: два РАЗНЫХ звена не могут упаковаться в
 *  ОДНИ И ТЕ ЖЕ байты. `encodePacked` остаётся инъективной при РОВНО ОДНОМ
 *  поле переменной ширины, где бы оно ни стояло среди остальных: границы
 *  восстанавливаются по фиксированным полям вокруг (их ширина известна
 *  заранее из самого списка типов, а не из данных). Опасны ровно ДВА и
 *  больше динамических поля — тогда граница МЕЖДУ НИМИ плавает: "ab"+"cdef"
 *  и "abcd"+"ef" дают идентичную конкатенацию 0xabcdef (проверено
 *  эмпирически через encodePacked, не только рассуждением) — при ОДНОМ
 *  динамическом поле такой пары просто не существует. Раунд 4 требовал
 *  «любое новое поле обязано быть фиксированной ширины» — это неверно и
 *  запрещало бы подпись плана 3 по причине, которая к ней не относится
 *  (подпись — единственное вероятное новое поле, и она ровно одна).
 *
 *  Тогда «отпечаток сошёлся ⟹ то же самое звено» ломается молча — при
 *  полностью зелёных тестах, потому что сам keccak256 продолжает работать
 *  идеально, просто ему на вход пришли неоднозначные байты. Свойство
 *  хеша, которое здесь нужно, — стойкость ко ВТОРОМУ ПРООБРАЗУ (для
 *  конкретного известного отпечатка трудно найти ДРУГОЕ звено с тем же
 *  отпечатком), а не коллизионная стойкость (для произвольной пары) — но
 *  она бесполезна, если сама упаковка неоднозначна ещё до хеширования.
 *
 *  Этот же гейт НЕ ловит перестановку местами двух полей ОДИНАКОВОЙ
 *  ширины (`prevHash` ↔ `bodyHash`, оба `bytes32`) — список типов при
 *  такой перестановке не меняется вообще. От этого отдельно защищает
 *  золотой вектор `linkHash` (раунд 5, независимая проверка через ethers). */
export type ChainLink = {
  seq: number;
  prevHash: `0x${string}`;
  bodyHash: `0x${string}`;
  sender: `0x${string}`;
  sentAt: number;
};

/** Отпечаток «предыдущего» у самого первого звена. Отдельная константа, а не
 *  нули: нулевой хеш легко получить случайно, а генезис должен быть намеренным. */
export const GENESIS_HASH = keccak256(
  new TextEncoder().encode('hexseal.chat.chain.genesis.v1'),
);

/** Список типов кодирования звена — единственное место, которое решает,
 *  инъективна ли упаковка (см. предупреждение над ChainLink). Экспортирован
 *  для теста «не более одного поля переменной ширины» (раунд 5) — тест
 *  обязан проверять РЕАЛЬНЫЙ список типов linkPreimage, а не копию. */
export const LINK_ENCODING_TYPES = ['uint256', 'bytes32', 'bytes32', 'address', 'uint256'] as const;

/** Преимидж звена — байты, которые уходят в keccak256 внутри linkHash.
 *  Экспортирован отдельно от linkHash ради теста на список типов (раунд 5,
 *  было — ширина в байтах, раунд 4) — тест обязан измерять РЕАЛЬНЫЙ
 *  преимидж, которым пользуется linkHash, а не копию кодирования,
 *  независимо вычисленную в тесте (копия проверяла бы только то, что тест
 *  написан верно, не то, что делает сама функция). */
export function linkPreimage(link: ChainLink): `0x${string}` {
  return encodePacked(
    LINK_ENCODING_TYPES,
    [BigInt(link.seq), link.prevHash, link.bodyHash, link.sender, BigInt(link.sentAt)],
  );
}

/** Отпечаток звена. В него входят ВСЕ поля: подмена любого обязана рвать
 *  связь со следующим звеном, иначе вырезанное сообщение можно было бы
 *  заменить другим того же размера. */
export function linkHash(link: ChainLink): `0x${string}` {
  return keccak256(linkPreimage(link));
}

export function buildLink(
  prev: ChainLink | null,
  bodyHash: `0x${string}`,
  sender: `0x${string}`,
  sentAt: number,
): ChainLink {
  return {
    seq: prev ? prev.seq + 1 : 0,
    prevHash: prev ? linkHash(prev) : GENESIS_HASH,
    bodyHash,
    sender: sender.toLowerCase() as `0x${string}`,
    sentAt,
  };
}

/** expectedLastSeq отвечает на «сколько сообщений всего», expectedLastHash —
 *  на «что именно последнее». Поодиночке каждый неполон: expectedLastSeq не
 *  видит каскадную подделку (раннее звено тронуто, весь хвост пересчитан
 *  вперёд через buildLink — все смежные пары внутри самосогласованы,
 *  проверка связности из C2 ничего не находит), а expectedLastHash БЕЗ
 *  expectedLastSeq не отличает честную обрезку (хвост правда не показан) от
 *  подделки — отпечаток последнего ПОКАЗАННОГО звена всегда не совпадёт с
 *  истинным отпечатком дальнего звена, и без номера это неотличимо от
 *  подмены. Поэтому expectedLastSeq — обязательная часть якоря, а
 *  expectedLastHash — опциональное усиление поверх него. */
export interface ChainAnchor {
  expectedLastSeq: number;
  expectedLastHash?: `0x${string}`;
}

/** unverifiedContentAtSeq называет, что НЕ проверено — не то, что проверено.
 *  tailAnchored (раунд 1) называл положительный факт («хвост заверен»), и
 *  сфабрикованное последнее звено с совпавшим числом сообщений превращалось
 *  в tailAnchored:true — интерфейс арбитра прочёл бы это как «цепочка цела,
 *  хвост заверен». Поле, называющее непроверенное, соврать в эту сторону не
 *  может: пустой массив значит «нечего добавить», непустой сам себя
 *  показывает.
 *
 *  Правило состава — ДОВЕРИЕ, а не соседство (раунд 2 задавал соседство:
 *  «последнее звено плюс звено перед каждой дырой» — и это занижало: без
 *  внешнего якоря вся предъявленная цепочка читается как сочинение,
 *  согласованное само с собой, доказано тестом на каскадную подделку).
 *  Доверие распространяется только НАЗАД от внешне заякоренного отпечатка:
 *  - expectedLastHash задан и сошёлся → непроверенное = все показанные
 *    номера, КРОМЕ последнего сплошного куска (от последней дыры до
 *    конца) — сошедшийся хеш криптографически подтверждает все пять полей
 *    последнего звена (включая prevHash), а значит по индукции через уже
 *    проверенные связностью C2 пары — и всё, что ведёт к нему без дыр;
 *  - иначе → непроверенное = ВСЕ показанные номера, без исключений —
 *    количество (expectedLastSeq) не защищает контент, оно только считает.
 *  Присутствует на ok и gap; на broken/unordered/bad_anchor не нужен — там
 *  веры нет ничему из предъявленного (broken/unordered) или предъявление
 *  вообще не разбиралось (bad_anchor).
 *
 *  ⚠️ `bad_anchor` ЗАСЛОНЯЕТ остальные вердикты, а не сообщает о них.
 *  verifyChain(подделаннаяЦепочка, {}) вернёт bad_anchor — той же цепочке
 *  без опций функция может сказать broken (повезло) или ok:true (не
 *  повезло — см. ниже). `bad_anchor` — это НЕ заключение о цепочке, а
 *  отказ судить о ней из-за мусора в опциях: якорь непригоден, и его
 *  нужно ПОЛУЧИТЬ ГОДНЫМ, а не обойти.
 *
 *  Перезвать verifyChain(links) без опций МОЖНО, но результат — НЕ
 *  замена якорю, а ослабленная, нижняя граница проверки: без якоря
 *  ok:true означает только «в предъявленном не нашлось самопротиворечий»,
 *  а не «цепочка цела» — злоумышленник, зная это, предъявит и
 *  self-consistent подделку (раунд 3, «доверие идёт назад от якоря, а не
 *  соседство с дырой»), и именно от неё был должен защитить сломанный
 *  якорь. Разбирать вердикт без якоря как окончательный и предъявлять его
 *  арбитру как справку о здоровье цепочки НЕЛЬЗЯ НИКОГДА — только как
 *  сигнал «якорь сломан, нужен другой», отдельно от вопроса о самой
 *  цепочке. */
export type ChainVerdict =
  | { ok: true; unverifiedContentAtSeq: number[] }
  | { ok: false; reason: 'gap'; missingAfterSeq: number[]; unverifiedContentAtSeq: number[] }
  | { ok: false; reason: 'broken'; atSeq: number }
  | { ok: false; reason: 'unordered' }
  | { ok: false; reason: 'bad_anchor' };

const BYTES32_RE = /^0x[0-9a-fA-F]{64}$/;

function isBytes32Hex(value: unknown): value is `0x${string}` {
  return typeof value === 'string' && BYTES32_RE.test(value);
}

/** Гейт формы принимает A-F (регистронезависимый regexp у 32-байтных
 *  отпечатков) — сравнение обязано трактовать регистр так же, иначе та же
 *  по значению строка в другом регистре ложно даёт broken. */
function sameHash(a: `0x${string}`, b: `0x${string}`): boolean {
  return a.toLowerCase() === b.toLowerCase();
}

/** Number.isSafeInteger, а не Number.isInteger: encodePacked(['uint256'])
 *  бросает IntegerOutOfRangeError далеко до границы uint256 — уже на числах,
 *  которые JS не может представить точно (Number.isInteger(1e100) === true,
 *  но это не то целое число, которым кажется). Заодно закрывает зону 2^53,
 *  где x+1 === x. */
function isSafeNonNegativeInt(value: unknown): value is number {
  return typeof value === 'number' && Number.isSafeInteger(value) && value >= 0;
}

/** Звено «в форме» — ровно то, что не даст linkHash бросить исключение
 *  (encodePacked внутри него требует: адрес — проходящий isAddress, оба
 *  хеша — ровно 32 байта строкой, seq/sentAt — целые неотрицательные, иначе
 *  BigInt()/encodePacked бросают RangeError/IntegerOutOfRangeError). Не
 *  переиспользуем viem.size() для длины хеша: на нечётном числе hex-символов
 *  она округляет вверх и врёт, что 63 символа — это 32 байта, тогда как
 *  encodePacked всё равно бросает («bytes31.5»). Точный regexp — надёжнее.
 *
 *  isAddress(sender, {strict:false}), а не strict (по умолчанию): strict
 *  отвергает ПОЛНОСТЬЮ ВЕРХНИЙ регистр (легальное по EIP-55 представление
 *  «не чек-сумлено» — то же положение принимает полностью нижний регистр,
 *  но не верхний, асимметрия в самом viem, проверено эмпирически). linkHash
 *  регистро-НЕзависим для адреса (encodePacked нормализует к одному и тому
 *  же 20-байтному значению независимо от текстового регистра, ЕСЛИ вообще
 *  смог его принять) — гейт формы обязан трактовать регистр так же, как
 *  отпечаток (раунд 1, `sameHash`), иначе честная цепочка получает broken
 *  из-за текстового регистра одного поля. strict:false проверяет ТОЛЬКО
 *  форму (40 hex-символов), не чек-сумму — сама нормализация значения
 *  происходит ниже, в verifyChain, до любого вычисления хеша. */
function isWellFormedLink(link: unknown): link is ChainLink {
  if (typeof link !== 'object' || link === null) return false;
  const l = link as Record<string, unknown>;
  return (
    isSafeNonNegativeInt(l.seq) &&
    isBytes32Hex(l.prevHash) &&
    isBytes32Hex(l.bodyHash) &&
    typeof l.sender === 'string' && isAddress(l.sender, { strict: false }) &&
    isSafeNonNegativeInt(l.sentAt)
  );
}

/** Номер для отчёта о негодном звене. Если seq хоть как-то похож на число —
 *  сообщаем его как есть (дробный/отрицательный тоже валиден как значение
 *  atSeq: number, это по-прежнему осмысленный указатель на место поломки).
 *  Если seq вообще не число — сообщаем позицию в предъявленном массиве. */
function reportedSeqFor(link: unknown, index: number): number {
  if (typeof link === 'object' && link !== null) {
    const seq = (link as Record<string, unknown>).seq;
    if (typeof seq === 'number') return seq;
  }
  return index;
}

/** Проверяет предъявленную цепочку.
 *
 *  Звенья приходят от противной стороны спора — это не тот код, что строит
 *  buildLink. Форма проверяется ПЕРВЫМ делом, до какой-либо арифметики над
 *  seq и до вызова linkHash: искажённый seq (дробный, отрицательный,
 *  вообще не число) иначе тихо просочился бы в сравнения `seq <= prevSeq`
 *  и `seq !== prevSeq + 1`, которые не бросают на мусоре — просто дают
 *  случайный числовой результат. Это скрыло бы подделку под honest-омиссию
 *  (gap), а мусор — это фальсификация формы, ближе по духу к broken.
 *  Дальше: порядок → связность того, что проверяемо, → пропуски.
 *  Пропуск сам по себе не проверить (несмежные по seq звенья сравнивать не
 *  с чем), но пара, смежная и по позиции, и по seq, проверяема ВНУТРИ
 *  дырявой цепочки — и обязана быть проверена ДО возврата gap. Иначе одно
 *  намеренно опущенное сообщение покупало бы иммунитет от broken для всей
 *  остальной цепочки: подделку в паре (3,4) можно было бы прикрыть, вырезав
 *  сообщение 2. Разница между «скрыл» и «сфальсифицировал» — это разница
 *  между минусом в репутацию и полным недоверием к предъявленному; она не
 *  означает, что скрытое автоматически освобождает остальное от проверки. */
export function verifyChain(links: ChainLink[], opts?: ChainAnchor): ChainVerdict {
  // Форма ЯКОРЯ проверяется РАНЬШЕ формы links: мусор может прийти с обеих
  // сторон одновременно (verifyChain(null, 5)), и если бы Array.isArray
  // шла первой, мусорный якорь остался бы незамеченным, а обвинение в
  // подделке ушло бы предъявителю за чужую ошибку. Якорь хвоста приезжает
  // снаружи (план 4 решает, откуда он берётся — verifyChain знает только
  // значения), но мусор в НЁМ — не вина того, чью цепочку разбирают.
  // opts=5/"2"/null/[...] раньше молча игнорировался (fail-open в функции,
  // вся суть которой в недоверии ко входу) — теперь bad_anchor.
  if (opts !== undefined && (typeof opts !== 'object' || opts === null || Array.isArray(opts))) {
    return { ok: false, reason: 'bad_anchor' };
  }
  let anchor: number | undefined;
  let hashAnchor: `0x${string}` | undefined;
  if (opts !== undefined) {
    // expectedLastSeq обязателен, когда opts присутствует как объект — {}
    // тоже сюда попадает. Отпечаток в одиночку не отличает честную обрезку
    // от подделки (нужен номер, чтобы сказать «сколько») — молча трактовать
    // пустой объект как «якоря нет» значило бы вернуть тот самый fail-open,
    // который чинили находкой 3 прошлого раунда, просто на другом поле.
    // Читаем только СОБСТВЕННЫЕ поля, не цепочку прототипов: обычный
    // доступ opts.expectedLastSeq резолвится и через прототип —
    // Object.create({expectedLastSeq: 3}) не имеет ни одного собственного
    // поля, но opts.expectedLastSeq всё равно вернул бы 3, обходя замок
    // на {} из находки 3 прошлого раунда. Поле, унаследованное через
    // прототип, — то же самое «не задано», что и вообще отсутствующее.
    const rawExpectedLastSeq = Object.prototype.hasOwnProperty.call(opts, 'expectedLastSeq')
      ? (opts as unknown as Record<string, unknown>).expectedLastSeq
      : undefined;
    if (!isSafeNonNegativeInt(rawExpectedLastSeq)) {
      return { ok: false, reason: 'bad_anchor' };
    }
    anchor = rawExpectedLastSeq;
    const rawExpectedLastHash = Object.prototype.hasOwnProperty.call(opts, 'expectedLastHash')
      ? (opts as unknown as Record<string, unknown>).expectedLastHash
      : undefined;
    if (rawExpectedLastHash !== undefined) {
      if (!isBytes32Hex(rawExpectedLastHash)) {
        return { ok: false, reason: 'bad_anchor' };
      }
      hashAnchor = rawExpectedLastHash;
    }
  }

  // Мусором может быть не только звено внутри массива, но и сам массив —
  // JSON.parse чужого ответа с лёгкостью даёт {} или null вместо [].
  if (!Array.isArray(links)) return { ok: false, reason: 'broken', atSeq: -1 };

  if (links.length === 0) {
    // Пустой массив без якоря — предъявлять нечего, но врать не в чем
    // (брифовый тест). С ЛЮБЫМ якорем (по номеру ИЛИ по отпечатку) —
    // предъявлять нечего, а должно было быть: вся переписка утаена, это
    // пропуск, а не молчаливое "всё в порядке". Хеш-якорь обязан входить
    // в этот возврат наравне с номером — якорь, называющий конкретное
    // последнее звено, не должен давать справку о здоровье при полном
    // сокрытии переписки (согласованность с одним звеном против
    // несходящегося хеш-якоря, которое честно даёт broken).
    // unverifiedContentAtSeq пуст в обоих случаях — предъявлять нечего,
    // значит и называть нечего.
    // ⚠️ На HEAD (после находки I2 раунда 3) `hashAnchor !== undefined`
    // ВЛЕЧЁТ `anchor !== undefined` — hashAnchor присваивается только
    // внутри `if (opts !== undefined)` ПОСЛЕ успешной проверки
    // expectedLastSeq (теперь обязательного), так что вторая половина
    // условия сейчас недостижима: её снятие красит 0 из 76 тестов
    // (проверено эмпирически, раунд 4). Оставлена как защита на случай,
    // если этот инвариант когда-нибудь разойдётся (например, если
    // валидацию anchor/hashAnchor однажды разъединят) — тогда снятие
    // якоря по количеству молча перестанет ловить якорь по отпечатку в
    // этой ветке, и баг проявится не сразу.
    if (anchor !== undefined || hashAnchor !== undefined) {
      return { ok: false, reason: 'gap', missingAfterSeq: [-1], unverifiedContentAtSeq: [] };
    }
    return { ok: true, unverifiedContentAtSeq: [] };
  }

  // Нормализуем sender к нижнему регистру СРАЗУ после проверки формы, до
  // любого использования: gate выше принял и ВЕРХНИЙ регистр (валидная
  // форма), а encodePacked внутри linkHash по-прежнему бросает на
  // полностью верхнем регистре (не считает его «не чек-сумленным», в
  // отличие от нижнего) — если передать его дальше как есть, связность
  // ниже упала бы исключением на РОВНО ТОМ звене, которое gate только что
  // признал годным. Это не гипотетика: проверено мутацией (снятие
  // нормализации) — падает `InvalidAddressError` прямо из `linkHash`,
  // непойманным исключением наружу из verifyChain, то есть именно то
  // поведение, которое вся функция обязана исключать по своей главной
  // задаче. buildLink лоукейсит sender по той же причине (эта функция
  // просто применяет ту же нормализацию к чужим, не построенным нами
  // звеньям).
  const links2: ChainLink[] = [];
  for (let i = 0; i < links.length; i++) {
    if (!isWellFormedLink(links[i])) {
      return { ok: false, reason: 'broken', atSeq: reportedSeqFor(links[i], i) };
    }
    const l = links[i];
    links2.push(l.sender === l.sender.toLowerCase() ? l : { ...l, sender: l.sender.toLowerCase() as `0x${string}` });
  }
  links = links2;

  for (let i = 1; i < links.length; i++) {
    if (links[i].seq <= links[i - 1].seq) return { ok: false, reason: 'unordered' };
  }

  const lastSeq = links[links.length - 1].seq;

  // Предъявлено больше, чем говорит якорь, — сфабрикованный хвост поверх
  // настоящего конца переписки. Решается сразу, до связности: несоответствие
  // якорю — не про отпечатки, а про факт существования этих сообщений вообще.
  if (anchor !== undefined && lastSeq > anchor) {
    return { ok: false, reason: 'broken', atSeq: lastSeq };
  }

  const missingAfterSeq: number[] = [];
  // Индекс, с которого начинается ПОСЛЕДНИЙ сплошной кусок показанного
  // (от последней дыры до конца, либо от начала массива, если дыр нет).
  // Используется ниже для unverifiedContentAtSeq — доверие от заякоренного
  // по хешу последнего звена индуктивно распространяется назад ЧЕРЕЗ
  // проверенные смежные пары (C2 выше), но дальше дыры не дотягивается:
  // с другой её стороны сравнивать не с чем.
  let lastChunkStart = 0;
  if (links[0].seq !== 0) missingAfterSeq.push(-1);
  for (let i = 1; i < links.length; i++) {
    if (links[i].seq !== links[i - 1].seq + 1) {
      missingAfterSeq.push(links[i - 1].seq);
      lastChunkStart = i;
    }
  }
  // Хвост утаён (якорь говорит, что дальше ещё есть сообщения) — тот же
  // способ учёта, что и для дыр в середине: номер звена ПЕРЕД пропуском.
  if (anchor !== undefined && lastSeq < anchor) missingAfterSeq.push(lastSeq);

  // broken побеждает gap: через дыру связность не проверить (соседние по
  // ПОЗИЦИИ, но не по seq звенья сравнивать не с чем), но пара, смежная и по
  // seq тоже, проверяема ВНУТРИ дырявой цепочки — иначе одно намеренно
  // опущенное сообщение покупало бы иммунитет от broken для всей остальной
  // цепочки. Поэтому связность (что удалось проверить) идёт раньше выхода
  // по gap, а не после него.
  if (links[0].seq === 0 && !sameHash(links[0].prevHash, GENESIS_HASH)) {
    return { ok: false, reason: 'broken', atSeq: links[0].seq };
  }
  for (let i = 1; i < links.length; i++) {
    if (links[i].seq === links[i - 1].seq + 1 && !sameHash(links[i].prevHash, linkHash(links[i - 1]))) {
      return { ok: false, reason: 'broken', atSeq: links[i].seq };
    }
  }

  // Якорь по отпечатку — последняя линия обороны против каскадной подделки:
  // атакующий трогает раннее звено и пересчитывает весь хвост вперёд через
  // buildLink, отчего смежные пары выше становятся самосогласованы и ничего
  // не находят. Только итоговый отпечаток последнего звена расходится с
  // истинным. Пропускаем сравнение, если якорь по количеству УЖЕ доказал,
  // что показанное последнее звено — не настоящее последнее (хвост утаён,
  // это честно определённый gap выше, а не повод сравнивать отпечаток
  // заведомо другого звена с истинным и обвинять в broken).
  const knownTailDeficit = anchor !== undefined && lastSeq < anchor;
  let tailVerifiedByHash = false;
  if (hashAnchor !== undefined && !knownTailDeficit) {
    if (!sameHash(linkHash(links[links.length - 1]), hashAnchor)) {
      return { ok: false, reason: 'broken', atSeq: lastSeq };
    }
    tailVerifiedByHash = true;
  }

  // Правило состава — ДОВЕРИЕ, а не соседство. Соседство с дырой было
  // неверным правилом (раунд 2): без внешнего якоря НИЧЕГО из показанного
  // на самом деле не проверено — self-consistent подцепочка (проверено
  // C2/каскадная подделка выше) читается как настоящая, потому что
  // связность проверяет только внутреннюю согласованность звеньев ДРУГ С
  // ДРУГОМ, а не с реальностью. Единственный внешний якорь реальности —
  // сошедшийся expectedLastHash: он криптографически подтверждает ВСЕ
  // пять полей последнего звена (стойкость keccak256 ко ВТОРОМУ ПРООБРАЗУ —
  // для конкретного известного отпечатка трудно найти ДРУГОЕ звено с тем
  // же отпечатком; более слабое и более уместное здесь свойство, чем
  // коллизионная стойкость для произвольной пары), а значит и его
  // prevHash — а тот уже подтверждён связностью C2 как
  // отпечаток звена перед ним, и так далее назад по цепочке индукцией —
  // вплоть до последней дыры (дальше нечем индуцировать, дыра рвёт цепь
  // рассуждения так же, как рвёт саму hash-цепочку).
  const unverifiedContentAtSeq = tailVerifiedByHash
    ? links.slice(0, lastChunkStart).map((l) => l.seq)
    : links.map((l) => l.seq);

  if (missingAfterSeq.length > 0) return { ok: false, reason: 'gap', missingAfterSeq, unverifiedContentAtSeq };

  return { ok: true, unverifiedContentAtSeq };
}
