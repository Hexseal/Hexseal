/**
 * xmtpErrors.ts — разбор отказов инициализации мессенджера в КОД, а не в текст.
 *
 * ЗАЧЕМ. Раньше `XmtpContext` сам склеивал русскую строку на каждый класс
 * отказа и отдавал её наружу как `error`. Две беды сразу:
 *
 *  1. в английском (и остальных двенадцати) интерфейсах человек видел русский —
 *     строки не проходили через i18n вообще;
 *  2. текст на таймаут утверждал ровно одну причину — «проверь интернет, включи
 *     VPN». А самый частый вход в этот таймаут был совсем другой: незакрытый
 *     клиент XMTP держал OPFS, и следующая попытка не имела ни единого шанса
 *     подняться. Человек читал уверенный неправильный диагноз, шёл проверять
 *     интернет и возвращался к тому же таймауту — навсегда.
 *
 * ЧТО СТАЛО. Здесь отказ разбирается в машинный код, а формулировку выбирает
 * интерфейс через `t('xmtp_error.<код>')` — на языке человека. Модуль намеренно
 * не тянет ни React, ни i18n, ни SDK: его можно проверить тестами целиком.
 */

/** Маркер «хранилище мессенджера занято другой вкладкой этого браузера».
 *  Бросается ДО подъёма WASM/OPFS (см. `lib/xmtpTabLock.ts`) — именно чтобы
 *  вторая вкладка не плодила воркеры, которые всё равно некому закрыть. */
export const XMTP_TAB_BUSY = 'XMTP_TAB_BUSY';

export type XmtpErrorCode =
  /** Hexseal уже открыт в другой вкладке — там же и держится хранилище. */
  | 'tab_busy'
  /** Не уложились в отведённое время. Причин много, версия — не одна. */
  | 'timeout'
  /** Brave: Shields режут сеть/хранилище XMTP. Ставится контекстом, не разбором. */
  | 'brave'
  /** В кошельке висит незакрытый запрос подписи. */
  | 'wallet_pending'
  /** Исчерпан лимит установок XMTP (10/10). */
  | 'too_many_installations'
  /** Личность заведена в одной сети, подписываем из другой. */
  | 'wrong_chain'
  /** Нет защищённого контекста — без него OPFS недоступен в принципе. */
  | 'insecure_context';

/** Разбирает сырое сообщение об ошибке в код. `null` — класс неизвестен,
 *  показывать придётся сырой текст (см. `trimXmtpError`). */
export function classifyXmtpError(raw: string): XmtpErrorCode | null {
  const lower = raw.toLowerCase();
  if (raw === XMTP_TAB_BUSY)                 return 'tab_busy';
  if (raw === 'XMTP_TIMEOUT')                return 'timeout';
  if (raw === 'XMTP_NO_OPFS' || lower.includes('secure context')) return 'insecure_context';
  if (lower.includes('already pending') || lower.includes('pending for origin')) return 'wallet_pending';
  if (raw.includes('10/10') || raw.includes('registered 10')) return 'too_many_installations';
  if (lower.includes('wrong chain id'))      return 'wrong_chain';
  return null;
}

/** Сырой текст в пригодный для показа вид: первая строка до дампа.
 *  WASM-слой XMTP любит приложить к сообщению многострочный трейс через
 *  разделитель `=====` — целиком в однострочную плашку он не влезает и ничего
 *  человеку не сообщает. */
export function trimXmtpError(raw: string): string {
  return raw.split('=====')[0].split('\n')[0].trim();
}
