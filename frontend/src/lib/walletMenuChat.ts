/**
 * walletMenuChat.ts — что меню кошелька показывает про переписку.
 *
 * ─── ЗАМЕР С ЖИВОГО ТЕЛЕФОНА (9 августа) ────────────────────────────────────
 *
 * Чат работает, ключ на устройстве, ключ объявлен в справочнике. Меню в ту же
 * секунду:
 *
 *     Восстановить по коду        ← обычному кошельку не нужно и не сработает
 *     Подключить мессенджер       ← он УЖЕ подключён
 *
 * Второе хуже первого: человек видит «подключить» у работающего чата и решает,
 * что что-то не так.
 *
 * ─── ДВЕ ПРИЧИНЫ, И ОБЕ ЗДЕСЬ ЗАКРЫТЫ ───────────────────────────────────────
 *
 * 1. Меню читало `status` СВОЕГО экземпляра хука, а тот застревал в `error`,
 *    когда ключ заводили в другом месте страницы. Это лечится общим складом
 *    ключа (`chatSessionStore.ts`), и решение ниже принимается по ФАКТУ («ключ
 *    на устройстве есть»), а не по состоянию экземпляра.
 * 2. Решение о каждом пункте жило прямо в разметке шестью независимыми
 *    условиями. Здесь оно одно, и его можно перебрать таблицей: три состояния
 *    ключа × два рода кошелька.
 */

import type { KeyStanding } from '@/lib/chatAnnounce';
import type { WalletReach } from '@/lib/walletReach';

/** Род кошелька. `unknown` — сеанса нет, а без него род не определить: его
 *  устанавливает сама подпись (разбор — шапка `lib/chatSession.ts`). */
export type WalletKindKnown = 'eoa' | 'contract' | 'unknown';

export type MenuChatItem =
  /** «Подключаем переписку…» — заводится прямо сейчас. */
  | 'connecting'
  /** «Показать код восстановления». */
  | 'show-code'
  /** «Восстановить по коду». */
  | 'restore'
  /** «Подключить мессенджер». */
  | 'enable'
  /** «Отключить мессенджер». */
  | 'disable'
  /** «Переподключить кошелёк» — запросы на подпись не доходят. */
  | 'reconnect-wallet';

export interface MenuChatInput {
  /** Ключ переписки ЕСТЬ на этом устройстве. Общий факт, а не состояние
   *  экземпляра хука (см. `chatSessionStore.ts`). */
  hasKey: boolean;
  /** Ключ заводится прямо сейчас. */
  connecting: boolean;
  /** Род кошелька — известен только когда ключ есть. */
  walletKind: WalletKindKnown;
  /** Стояние ключа в справочнике. Меню его НЕ лечит (кнопка живёт в чате), но
   *  и не смеет предлагать «подключить» тому, у кого ключ есть. */
  standing: KeyStanding;
  /** Доходят ли до кошелька запросы на подпись. */
  reach: WalletReach;
}

/**
 * Что показать. Порядок в наборе не важен — его задаёт разметка.
 *
 * ⚠️ ГЛАВНОЕ ПРАВИЛО: «ПОДКЛЮЧИТЬ» — ТОЛЬКО КОГДА КЛЮЧА НЕТ. Ключ есть — чат
 * подключён, чем бы ни считал себя отдельный экземпляр хука. Ровно это меню и
 * врало на приборе.
 *
 * ⚠️ ВТОРОЕ ПРАВИЛО: КОД — ТОЛЬКО ТЕМ, У КОГО ОН МОЖЕТ БЫТЬ. Обычному кошельку
 * (в том числе делегированному EIP-7702 — у него подпись такая же) код не
 * нужен: его восстановление — сам кошелёк. Когда ключа нет, род НЕИЗВЕСТЕН, и
 * промолчать дороже: владелец кошелька-контракта не нашёл бы входа вовсе.
 * Признак «есть ли код на цепи» тут не годится — он ошибается на двух родах из
 * четырёх (замерено 6 августа), и пустой код это либо обычный кошелёк, либо
 * счётный смарт-кошелёк, которому код НУЖЕН.
 */
export function walletMenuChatItems(input: MenuChatInput): Set<MenuChatItem> {
  const items = new Set<MenuChatItem>();

  // Кошелёк не отвечает — самое важное во всём меню: пока это так, ни одно
  // действие с подписью не пройдёт, и человеку нужен именно этот выход.
  if (input.reach !== 'ok') items.add('reconnect-wallet');

  if (input.connecting) {
    items.add('connecting');
    return items;
  }

  if (input.hasKey) {
    items.add('disable');
    // Код есть только у кошелька-контракта. Обычному не показываем ни показ,
    // ни вход: у него кода нет и не будет.
    if (input.walletKind === 'contract') {
      items.add('show-code');
      items.add('restore');
    }
    return items;
  }

  // Ключа на устройстве нет: подключить — можно; род кошелька неизвестен,
  // значит дверь к коду оставляем открытой.
  items.add('enable');
  items.add('restore');
  return items;
}
