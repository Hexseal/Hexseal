/**
 * xmtpPairGroup.ts — правила выбора «той самой» парной группы и чтения её
 * превью. Вынесены из `lib/xmtp.ts` в отдельный модуль, потому что их обязаны
 * применять ДВА разных места одинаково, а раньше они применяли по-своему.
 *
 * ЧТО БЫЛО СЛОМАНО.
 *
 * 1. ФИЛЬТР ЛЕГИТИМНОСТИ РЕЗАЛ НАСТОЯЩИЕ ГРУППЫ. Ожидаемый состав парной группы
 *    — двое собеседников плюс бот релеера. Адрес бота узнаётся запросом к
 *    релееру, и при недоступном релеере он приходил `null` — то есть бот
 *    выпадал из «ожидаемых», а он состоит в КАЖДОЙ настоящей группе. Значит
 *    настоящие группы переставали быть легитимными все разом: переписка с
 *    историей открывалась как «Сообщений пока нет», а первая же отправка
 *    заводила ВТОРУЮ группу с тем же именем — и тред расходился навсегда.
 *    Теперь неизвестный бот — это не «бота нет», а «одного участника мы не
 *    знаем в лицо»: допускается ровно один лишний. Защита от подделки при этом
 *    остаётся: подделка с ДВУМЯ лишними отсекается всегда, а с одним — только
 *    пока адрес бота неизвестен, и в этом окне ничего лучше не существует.
 *
 * 2. СПИСОК И ТРЕД ВЫБИРАЛИ РАЗНЫЕ ГРУППЫ. При двух и более группах на пару
 *    (наследство от старой churn'а установок) боковой список брал группу с
 *    самым свежим сообщением, а тред — с наименьшим `id`. Человек видел в
 *    списке последнее сообщение, открывал — а его там нет. Правило выбора
 *    теперь ровно одно и живёт здесь: наименьший `id`. Именно он, а не «самая
 *    свежая»: обе стороны должны сойтись на ОДНОЙ группе независимо друг от
 *    друга, а `id` у обеих одинаковый — в отличие от того, что каждая из них
 *    видит последним сообщением.
 *
 * 3. ПРЕВЬЮ ЧИТАЛО ОКНО ИЗ ДЕСЯТИ СЫРЫХ СООБЩЕНИЙ. Квитанции о прочтении и
 *    служебные маркеры `deal_ctx` — тоже сообщения, и они это окно съедали.
 *    Живая переписка подписывалась «Сообщений пока нет», уезжала вниз списка и
 *    не подсвечивалась непрочитанной. Теперь окно расширяется страницами, пока
 *    видимое сообщение не найдётся.
 *
 * Модуль намеренно не импортирует `@xmtp/browser-sdk`: ему хватает структурных
 * типов, зато он проверяется тестами без wasm и без сети.
 */

/** Префикс имени парной группы. Имя строится `pairGroupName()` в `lib/xmtp.ts`
 *  и полностью описывает пару: `HSEAL-PAIR-<адрес A>-<адрес B>`, адреса
 *  отсортированы и в нижнем регистре. */
export const PAIR_PREFIX = 'HSEAL-PAIR-';

/**
 * Достаёт адрес собеседника ИЗ ИМЕНИ группы.
 *
 * Раньше боковой список выводил собеседника из состава участников — «первый,
 * кто не я». Но в группе есть третий, бот релеера, и порядок участников нам
 * никто не обещал: достаточно боту оказаться перед собеседником, чтобы в списке
 * чатов появилась переписка «с ботом». Имя же строится нами и содержит ровно ту
 * пару, ради которой группа существует.
 *
 * `null` означает «это не моя парная группа» — либо имя не парное, либо меня в
 * этой паре нет.
 */
export function pairPeerFromName(name: string, myAddress: string): string | null {
  if (!name.startsWith(PAIR_PREFIX)) return null;
  const parts = name.slice(PAIR_PREFIX.length).split('-');
  if (parts.length !== 2) return null;
  const [a, b] = [parts[0].toLowerCase(), parts[1].toLowerCase()];
  if (!a || !b) return null;
  const me = myAddress.toLowerCase();
  if (a === me) return b;
  if (b === me) return a;
  return null;
}

export interface PairExpectation {
  /** Мой адрес. */
  me: string;
  /** Адрес собеседника. */
  peer: string;
  /** Адрес бота релеера или `null`, если релеер сейчас недоступен. */
  bot: string | null;
}

/**
 * Легитимен ли состав группы для этой пары.
 *
 * Инвариант MLS: создатель группы всегда её участник — значит подделка с
 * посторонним внутри видна по составу и отсекается. Считаем «лишних»: тех, кого
 * в паре нет и кто не известен нам как бот.
 *
 * Известен адрес бота — лишних быть не должно вовсе. Неизвестен (релеер не
 * ответил) — ровно один лишний допускается, это и есть бот. Разница между
 * «отсекаем всё подряд» и «допускаем одного» здесь стоит целого треда: см.
 * пункт 1 в шапке файла.
 */
export function isLegitimatePairMembership(
  memberAddresses: readonly string[],
  expected: PairExpectation,
): boolean {
  const known = new Set([expected.me.toLowerCase(), expected.peer.toLowerCase()]);
  if (expected.bot) known.add(expected.bot.toLowerCase());
  const allowedExtras = expected.bot ? 0 : 1;

  let extras = 0;
  for (const addr of memberAddresses) {
    if (!known.has(addr.toLowerCase())) extras++;
  }
  return extras <= allowedExtras;
}

/**
 * Одно правило выбора канонической группы на все места сразу: наименьший `id`.
 *
 * Детерминированность здесь важнее свежести. Обе стороны считают это правило
 * независимо, у обеих должен получиться один ответ — иначе они пишут в разные
 * группы и не видят друг друга. `id` у группы одинаковый у всех участников,
 * «последнее сообщение» — нет.
 */
export function pickCanonicalGroup<T extends { id: string }>(groups: readonly T[]): T | null {
  if (groups.length === 0) return null;
  return groups.reduce((best, g) => (g.id < best.id ? g : best));
}

export interface PreviewScan<M, P> {
  /** Страница сообщений, НОВЕЙШИЕ ПЕРВЫМИ, старше курсора. */
  page: (beforeNs?: bigint) => Promise<readonly M[]>;
  /** Разбор сообщения в то, что можно показать. `null` — сообщение невидимое
   *  (квитанция о прочтении, маркер `deal_ctx`, служебное событие). */
  parse: (message: M) => P | null;
  /** Курсор сообщения для следующей страницы. */
  cursorOf: (message: M) => bigint | null | undefined;
  /** Размер страницы — по нему же понимаем, что страница последняя. */
  pageSize: number;
  /** Потолок страниц. Защита от переписки, у которой видимых сообщений нет
   *  вовсе (одни квитанции): без потолка такая группа пролистывалась бы до
   *  начала времён на каждой сборке списка чатов. */
  maxPages?: number;
}

/**
 * Ищет последнее ВИДИМОЕ сообщение, расширяя окно страницами.
 *
 * Раньше здесь стояло жёсткое «десять сырых сообщений», и этого не хватало:
 * квитанции о прочтении летят на каждое открытие чата, а маркер `deal_ctx` — на
 * каждую смену сделки. Пара активных дней — и последнее видимое сообщение
 * оказывалось за границей окна.
 */
export async function findLastVisibleMessage<M, P>(
  scan: PreviewScan<M, P>,
): Promise<{ message: M; parsed: P } | null> {
  const maxPages = scan.maxPages ?? 4;
  let cursor: bigint | undefined;

  for (let i = 0; i < maxPages; i++) {
    const page = await scan.page(cursor);
    if (page.length === 0) return null;

    for (const message of page) {
      const parsed = scan.parse(message);
      if (parsed !== null) return { message, parsed };
    }

    // Страница короче запрошенной — дальше сообщений нет.
    if (page.length < scan.pageSize) return null;
    const next = scan.cursorOf(page[page.length - 1]);
    // Без курсора следующий запрос вернул бы ту же страницу — это был бы
    // бесконечный цикл на ровном месте.
    if (next === null || next === undefined) return null;
    cursor = next;
  }
  return null;
}
