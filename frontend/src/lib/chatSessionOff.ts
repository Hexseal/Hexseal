/**
 * chatSessionOff.ts — что показать, когда переписка НЕ открылась (К-2).
 *
 * ⚠️ ЧЕМ ЭТО БЫЛО. Один экран на все причины, и надпись на нём —
 * «Мессенджер выключен», то есть про ДЕЙСТВИЕ ЧЕЛОВЕКА. Человек чаще всего
 * ничего не выключал: у него соседняя вкладка держит хранилище, или кошелёк
 * не подписал, или база не ответила. Прочесть такую надпись ему нечем, кроме
 * как «я что-то сломал» — и он перестаёт искать настоящую причину.
 *
 * ─── ДЕЙСТВИЕ — ПОЛОВИНА ДЕЛА ──────────────────────────────────────────
 *
 * Слова без действия оставляют человека там же, где нашли. И действие обязано
 * быть РАЗНЫМ: «повторить» на базе, занятой соседней вкладкой, не даст ничего,
 * сколько ни жми; у незнакомой версии записи действия нет вовсе, и предлагать
 * его значило бы врать.
 *
 * ─── ПОЧЕМУ НАДПИСИ ПЕРЕИСПОЛЬЗУЮТСЯ ───────────────────────────────────
 *
 * Часть ключей взята у окна восстановления (`restore_err_*`): там те же самые
 * беды описаны теми же словами, и заводить вторую формулировку значило бы
 * получить два текста про одно, которые разойдутся при первой же правке.
 */

import type { ChatSessionErrorCode } from './chatSession';

/**
 * Что человек может сделать. Закрытый набор, а не строка: действие решает,
 * какую кнопку рисовать, и «почти то же самое» здесь стоит бесполезного
 * нажатия.
 */
export type OffAction =
  /** Попробовать снова — беда мимолётная. */
  | 'retry'
  /** Ввести код восстановления: ключа на устройстве нет или он недоступен. */
  | 'restore'
  /** Закрыть другие вкладки сайта — база занята ими. */
  | 'close-tabs'
  /** Действия нет, и врать про него нельзя. */
  | 'none';

export interface OffScreen {
  titleKey: string;
  hintKey: string;
  action: OffAction;
  /**
   * Вторая строка: «ключ вернётся по подписи». Только там, где это ПРАВДА —
   * то есть где ключа на устройстве нет вовсе.
   *
   * ⚠️ ЗАМЕР С ЖИВОГО ТЕЛЕФОНА (9 августа). Ключ в справочнике есть, на
   * устройстве нет, кошелёк обычный — и экран предлагал ему код
   * восстановления, которого у него не бывает. Обычному кошельку (и
   * делегированному EIP-7702 — у него подпись такая же) ключ выводится ИЗ
   * ПОДПИСИ и возвращается тем же: подписал — прежняя переписка открылась.
   *
   * У беды с хранилищем этой строки быть НЕ ДОЛЖНО: там ключ может лежать
   * целым, и обещать его возврат по подписи значило бы врать.
   */
  sameKeyNote?: boolean;
}

/**
 * Причина → экран. Список ПОЛНЫЙ и явный: причина, забытая здесь, попадёт в
 * общий случай, а не молча получит чужие слова.
 */
export const OFF_SCREENS: Readonly<Record<string, OffScreen>> = {
  // ⚠️ НЕ ПОЛОМКА, и это самый частый случай из всех. Ключа на устройстве
  // нет, а заводить мы не просили: человек либо ещё не заходил в чат, либо
  // однажды отказался подписывать (К-3). Общий экран сказал бы «что-то
  // помешало открыть переписку» — то самое обвинение того, кто ни при чём,
  // ради избавления от которого делалась К-2, только другими словами.
  // Нажатие «включить» здесь и есть просьба завести ключ: `retry()` снимает
  // прежний отказ и взводит чат.
  session_absent: {
    titleKey: 'chat.messaging_off',
    hintKey: 'chat.messaging_off_hint',
    action: 'retry',
    sameKeyNote: true,
  },
  // Прочитать хранилище не смогли. Пустоту мы НЕ установили — ключ может
  // лежать там целым. Человеку с записанным кодом есть куда идти.
  storage_read_failed: {
    titleKey: 'chat.off_title',
    hintKey: 'chat.restore_err_storage_read',
    action: 'restore',
  },
  // База занята соседней вкладкой. Единственная беда во всём списке, у
  // которой есть точное человеческое действие.
  storage_blocked: {
    titleKey: 'chat.off_title',
    hintKey: 'chat.key_not_saved_blocked',
    action: 'close-tabs',
  },
  storage_open_timeout: {
    titleKey: 'chat.off_title',
    hintKey: 'chat.restore_err_storage_slow',
    action: 'retry',
  },
  // Запись незнакомой версии НЕ ТРОГАЮТ намеренно: для кошелька-контракта
  // выбросить её значит стереть личность навсегда. Действия у человека нет.
  storage_version_unknown: {
    titleKey: 'chat.off_title',
    hintKey: 'chat.off_version_unknown',
    action: 'none',
  },
  signature_malformed: {
    titleKey: 'chat.off_title',
    hintKey: 'chat.restore_err_signature',
    action: 'retry',
  },
  address_malformed: {
    titleKey: 'chat.off_title',
    hintKey: 'chat.restore_err_address',
    action: 'none',
  },
};

/** Ничего не сломалось — человек выключил чат сам. Единственный случай, где
 *  прежняя надпись говорила правду, и он её сохраняет. */
const TURNED_OFF: OffScreen = {
  titleKey: 'chat.messaging_off',
  hintKey: 'chat.messaging_off_hint',
  action: 'retry',
  sameKeyNote: true,
};

/** Причина есть, но мы её не предвидели. Общий экран лучше пустого. */
const UNEXPECTED: OffScreen = {
  titleKey: 'chat.off_title',
  hintKey: 'chat.off_unknown',
  action: 'retry',
};

export function offScreenFor(code: ChatSessionErrorCode | null | undefined): OffScreen {
  if (!code) return TURNED_OFF;
  return OFF_SCREENS[code] ?? UNEXPECTED;
}
