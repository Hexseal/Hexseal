/**
 * Склейка страниц бесконечного списка досок (заказы, услуги).
 *
 * Существует ради одного конкретного бага, который воспроизводится вообще без
 * транзакций: пролистать доску до второй страницы и нажать «Обновить».
 *
 * Накопление страниц жило прямо в эффекте:
 *
 *     useEffect(() => {
 *       if (page === 0) setAllJobs(pageJobs);
 *       else if (pageJobs.length > 0) setAllJobs(prev => [...prev, ...pageJobs]);
 *     }, [pageJobs]);
 *
 * Зависимость — САМ МАССИВ, а urql отдаёт новую ссылку на каждое выполнение
 * запроса, включая повторное по тем же переменным. Любое обновление на
 * странице ≥ 1 (кнопка «Обновить», перефокус вкладки, инвалидация кэша) снова
 * запускало ветку append и дописывало ту же страницу второй раз: дубли строк и
 * дубли React-ключей — а на одинаковых ключах React перестаёт различать
 * элементы списка и переиспользует состояние не тех карточек.
 *
 * Здесь склейка сделана чистой функцией: она идемпотентна по построению —
 * повтор той же страницы ничего не добавляет, потому что уже виденные `id`
 * отбрасываются. Дедупликация идёт и внутри самой входящей страницы: сабграф
 * при сдвиге окна (`skip`) на живых данных умеет вернуть запись, уже попавшую
 * в предыдущую страницу.
 */

/** Минимум, который нужен склейке: у записи есть стабильный `id`. */
export interface Identified {
  id: string;
}

/**
 * @param prev     уже накопленные записи
 * @param page     номер страницы, к которой относится `incoming` (0 — первая)
 * @param incoming записи, приехавшие за эту страницу
 *
 * Страница 0 ЗАМЕЩАЕТ накопленное (это же и сброс при смене фильтра), любая
 * следующая — дописывается без повторов.
 */
export function mergePages<T extends Identified>(
  prev: readonly T[],
  page: number,
  incoming: readonly T[],
): T[] {
  const dedupe = (items: readonly T[], seen: Set<string>): T[] => {
    const out: T[] = [];
    for (const item of items) {
      if (seen.has(item.id)) continue;
      seen.add(item.id);
      out.push(item);
    }
    return out;
  };

  if (page === 0) return dedupe(incoming, new Set<string>());

  // Пустая страница НЕ затирает накопленное: на хвосте списка сабграф отдаёт
  // пустой массив, и это не повод показывать пустую доску.
  if (incoming.length === 0) return [...prev];

  const seen = new Set(prev.map(item => item.id));
  return [...prev, ...dedupe(incoming, seen)];
}
