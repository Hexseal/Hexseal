/**
 * chatAnnounce.ts — объявлен ли наш ключ в справочнике, и что с этим делать.
 *
 * ─── ТИХАЯ ПОЛОМКА, РАДИ КОТОРОЙ ЭТОТ ФАЙЛ ЗАВЕДЁН ──────────────────────────
 *
 * Ключ переписки выводится из первой подписи и ложится в хранилище устройства.
 * Объявить его в справочнике можно ТОЛЬКО пропуском — `POST /keys` берёт адрес
 * из пропуска, а не из тела. Пропуск — вторая подпись.
 *
 * Значит есть промежуток, где ключ есть, а никто про него не знает. В этом
 * промежутке собеседник НЕ МОЖЕТ нам написать вовсе: запечатать сообщение
 * можно только на ключ из справочника. А человек видит обычный чат и считает,
 * что настроился.
 *
 * Живой замер 8 августа: установленное приложение владельца прошло подпись ключа
 * — и `GET /keys/<адрес>` отвечал 404. Ключ был. Объявлен не был. Человек ушёл.
 *
 * ─── ПОЧЕМУ ОТСРОЧКА ПРОПУСКА ИДЁТ ПО СВОЕМУ КЛЮЧУ, А НЕ ПО ЧУЖОМУ ──────────
 *
 * Соблазнительно рассуждать так: «собеседник ключа не объявил — значит писать
 * ему некуда и забирать нечего, пропуск не нужен». Первая половина верна, вторая
 * НЕТ, и это замерено на настоящем сервере
 * (`__stand__/chatAnnounceKey.test.ts`, последний замер): чтобы отправить нам
 * мешок, собеседнику нужны наш открытый ключ (лежит в справочнике, читается
 * открыто) и СВОЙ пропуск (подпись своего кошелька). Своего ключа в справочнике
 * для отправки не требуется нигде. Отложив пропуск по признаку «его нет в
 * справочнике», мы бы не забрали то, что он уже прислал.
 *
 * По СВОЕМУ ключу отсрочка безопасна, и доказательство короткое:
 *
 *   > пока нашего ключа в справочнике нет, запечатать НАМ нельзя ничего.
 *
 * Значит на складе для нас нет и не может быть ни одного мешка, и опрос ящика
 * забирать оттуда нечего. Ноль запросов пропуска — не экономия, а следствие.
 */

import { ChatDirectoryError, type ChatDirectoryErrorCode, type PeerChatKeys } from '@/hooks/useChatSession';
import type { ChatSession } from '@/lib/chatSession';
import { isSignatureDeferred, type SignatureGateVerdict } from '@/lib/chatSignatureGate';

/* ──────────────────────────── что знает справочник ────────────────────────── */

export type KeyStanding =
  /** Ещё не спрашивали. Ни утверждать, ни пугать нечем. */
  | 'unknown'
  /** В справочнике лежит РОВНО НАШ ключ. Всё в порядке. */
  | 'mine'
  /** Записи нет вовсе (404). Нам нельзя написать. */
  | 'absent'
  /** Запись есть, но ключ ЧУЖОЙ — объявлено с другого устройства. Нам нельзя
   *  написать НА ЭТО устройство: приходящее будет запечатано не на наш ключ. */
  | 'other_key'
  /** Справочник не ответил или ответил мусором. Мы НЕ ЗНАЕМ. */
  | 'unreachable';

/** Что уже пробовали сделать с объявлением. */
export type AnnounceAttempt = 'none' | 'busy' | 'failed';

export interface AnnounceInput {
  /** Ключ переписки лежит на устройстве. Без него объявлять нечего, и это
   *  ДРУГОЙ экран («включить мессенджер»), а не наш. */
  keyOnDevice: boolean;
  standing: KeyStanding;
  attempt: AnnounceAttempt;
  /** Вердикт порога подписи БЕЗ нажатия человека (`checkSignatureGate(false)`). */
  gate: SignatureGateVerdict;
}

/**
 * Три РАЗНЫХ множества, а не одно. Слипшись, они дали две живых потери данных —
 * разбор ниже, у каждой функции.
 *
 * ⚠️ ИСТОРИЯ ОШИБКИ, чтобы её не повторили. Сначала здесь было одно множество
 * `{absent, other_key}` на все три вопроса. Общее у этих двух стояний ровно одно:
 * на ЭТО устройство собеседник написать не может. Всё остальное у них разное, и
 * разница дорогая:
 *
 *   - при `absent` записи в справочнике НЕ БЫЛО НИКОГДА, значит запечатать нам
 *     было нечем и мешков для нас на складе быть не может. Терять нечего;
 *   - при `other_key` запись ЕСТЬ, просто ключ другого устройства. Объявив свой,
 *     мы ЗАМЕНИМ чужой — а на складе при этом могут лежать мешки, запечатанные
 *     на наш прежний ключ, и здесь они открываются.
 */

/** Собеседник не может написать на ЭТО устройство — значит человеку надо сказать. */
const CANNOT_REACH_THIS_DEVICE: ReadonlySet<KeyStanding> = new Set<KeyStanding>(['absent', 'other_key']);

/**
 * Объявить свой ключ можно молча, ничего не потеряв.
 *
 * ⚠️ ТОЛЬКО `absent`. При `other_key` объявление ЗАМЕНЯЕТ ключ другого
 * устройства: собеседники начнут запечатывать сюда, там новое приходить
 * перестанет, а прежние мешки останутся читаемыми только там. Это выбор человека
 * с предупреждением, а не «починка», и уж точно не то, что делают сами.
 *
 * Это был живой дефект, а не недостающая осторожность: на десктопе (порог `go`)
 * автоматика заменяла чужой ключ, и человек не видел даже кнопки.
 */
const SAFE_TO_ANNOUNCE_SILENTLY: ReadonlySet<KeyStanding> = new Set<KeyStanding>(['absent']);

/**
 * Мешков для нас на складе быть НЕ МОЖЕТ — опрос ящика бессмысленен.
 *
 * ⚠️ ТОЛЬКО `absent`, и только потому, что записи не было никогда. При
 * `other_key` мешки могут лежать и открываться здесь: мешок запечатывается на
 * тот ключ, который был в справочнике на момент отправки, а забирается ПО АДРЕСУ.
 * Заблокировав опрос, мы спрятали бы от человека переписку, которую он может
 * прочесть.
 */
const NOTHING_CAN_EXIST_FOR_US: ReadonlySet<KeyStanding> = new Set<KeyStanding>(['absent']);

/**
 * Наше стояние в справочнике по его ответу.
 *
 * ⚠️ `unreachable` НЕ РАВНО `absent`, и путать их дорого. `absent` — «нам нельзя
 * написать, надо объявиться»: он останавливает опрос ящика и показывает кнопку.
 * `unreachable` — «мы не знаем»: он не имеет права ни на то, ни на другое, иначе
 * моргнувший справочник запирал бы чат тому, кто объявлен давно. Этот урок в
 * проекте уже оплачен: до 8 августа отказ справочника выдавался человеку как
 * «собеседник ещё не заходил» — утверждение о человеке, которого не проверяли.
 */
export function standingFromDirectory(
  outcome: { ok: true; boxKey: Uint8Array } | { ok: false; error: unknown },
  ownBoxKey: Uint8Array,
): KeyStanding {
  if (!outcome.ok) {
    const code: ChatDirectoryErrorCode | null =
      outcome.error instanceof ChatDirectoryError ? outcome.error.code : null;
    return code === 'peer_unknown' ? 'absent' : 'unreachable';
  }
  return sameKey(outcome.boxKey, ownBoxKey) ? 'mine' : 'other_key';
}

/** Сравнение побайтовое и по длине. Не через hex-строку: лишнее превращение —
 *  лишнее место, где можно потерять регистр или префикс. */
function sameKey(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
  return true;
}

/* ─────────────────────────── два решения, чистыми ─────────────────────────── */

/**
 * Показывать ли человеку «Вам пока не могут писать» и кнопку.
 *
 * ⚠️ НЕ «когда ключ не объявлен», а «когда ключ не объявлен И САМИ МЫ ЭТОГО НЕ
 * СДЕЛАЕМ». Разница — весь десктоп: там это состояние тоже бывает, просто живёт
 * доли секунды между чтением справочника и своим же объявлением. Показав кнопку
 * в этот промежуток, мы получили бы мигающую надпись у человека, у которого всё
 * в порядке, — то есть починку хуже дефекта.
 */
export function announceNeedsPress(input: AnnounceInput): boolean {
  if (!input.keyOnDevice) return false;
  if (!CANNOT_REACH_THIS_DEVICE.has(input.standing)) return false;
  if (input.attempt === 'busy') return false;
  // Страница скрыта — показывать некому. Заодно это не даёт признаку взвестись
  // у свёрнутого приложения и остаться взведённым при возврате.
  if (input.gate === 'page_hidden') return false;
  // Попытка была и не вышла — кнопка нужна даже там, где автоматика разрешена:
  // автоматика уже отработала и сама не повторится (см. `announceMayAuto`), и
  // без кнопки человек остался бы вовсе без выхода.
  if (input.attempt === 'failed') return true;
  // ⚠️ ЧУЖОЙ КЛЮЧ — ВСЕГДА, а не только после ухода к кошельку. Автоматики здесь
  // нет по построению (замена не делается молча), значит без этой строки
  // состояние стало бы невылечиваемым на десктопе: сами не делаем и выбора не
  // предлагаем. И выбор тут настоящий — код восстановления против замены.
  if (!SAFE_TO_ANNOUNCE_SILENTLY.has(input.standing)) return true;
  return input.gate !== 'go';
}

/**
 * Можно ли объявить ключ САМИМ, без нажатия.
 *
 * Ровно дополнение к функции выше в той части, где обе могли бы сказать «да»:
 * замок `chatAnnounce.test.ts` перебирает все 90 сочетаний и требует, чтобы
 * пересечения не было ни в одном. Иначе человек видел бы кнопку и одновременно
 * получал окно кошелька без нажатия.
 */
export function announceMayAuto(input: AnnounceInput): boolean {
  if (!input.keyOnDevice) return false;
  // Молча — только там, где терять нечего. Разбор — у `SAFE_TO_ANNOUNCE_SILENTLY`.
  if (!SAFE_TO_ANNOUNCE_SILENTLY.has(input.standing)) return false;
  // Только первая попытка идёт сама. Повтор — по нажатию: иначе отказ
  // `POST /keys` крутился бы каждый тик, и «долбят нарочно» устраивали бы мы
  // сами себе, своему же серверу и своему же кошельку.
  if (input.attempt !== 'none') return false;
  return input.gate === 'go';
}

/**
 * Стоит ли опрашивать ящик — то есть брать пропуск.
 *
 * ⚠️ `unknown` ТОЖЕ НЕ СТОИТ, и это находка замера, а не осторожность. Первая
 * версия пускала опрос на `unknown` («ещё не спрашивали») — и требование «ноль
 * запросов пропуска» ломалось на повторном заходе с телефона: подписи в этот раз
 * нет, порог говорит «можно», справочник ещё не прочитан, и опрос успевал
 * попросить пропуск ДО того, как выяснится, что объявлять-то нечего. Замерено:
 * `mailboxWorthPollingFor` отдавал `true` до первого ответа справочника.
 *
 * Ждать нечего: чтение справочника — один открытый запрос без подписи, десятки
 * миллисекунд, и оно уже идёт.
 *
 * ⚠️ ЗАТО `unreachable` СТОИТ, И ЭТО НАМЕРЕННО — ОТКАЗ В СТОРОНУ РАБОТЫ. Опрос
 * блокируется только тогда, когда мы ПОЛОЖИТЕЛЬНО ЗНАЕМ, что написать нам
 * нельзя (`absent`/`other_key`). Не знаем — работаем как раньше. Иначе один
 * зависший или отказавший запрос к справочнику означал бы чат, который молчит
 * навсегда, и это было бы хуже лишнего пропуска.
 */
export function mailboxWorthPolling(standing: KeyStanding): boolean {
  if (standing === 'unknown') return false;
  return !NOTHING_CAN_EXIST_FOR_US.has(standing);
}

/**
 * Чем закончилась неудавшаяся попытка объявить ключ: «не удалось» или «ещё не
 * время».
 *
 * ⚠️ ЭТА ФУНКЦИЯ ВЫНЕСЕНА СЮДА ПОСЛЕ ТОГО, КАК МУТАЦИЯ НАШЛА ДЫРУ. Различие
 * жило внутри хука обычным `if` с абзацем объяснения — и мутация «считать отказ
 * порога неудачей» прошла ЗЕЛЁНОЙ на 54 замерах. То есть ветка была, объяснение
 * было, а сторожил её никто. Класс известный: правка, которую ничто не мерит.
 *
 * Цена промаха — ровно требование «десктоп не стал длиннее». Отказ порога
 * означает «страница скрыта» или «кошелёк уводил её из глаз» — оба состояния
 * ВРЕМЕННЫЕ. Записав это в `failed`, мы навсегда закрыли бы автоматику
 * (`announceMayAuto` пускает только `attempt === 'none'`), и десктоп, у которого
 * видимость моргнула один раз при восстановлении вкладки, получил бы кнопку,
 * которой там быть не должно.
 */
export function attemptAfterFailure(err: unknown): AnnounceAttempt {
  return isSignatureDeferred(err) ? 'none' : 'failed';
}

/* ────────────────────────────── чтение и запись ───────────────────────────── */

/**
 * Что справочник знает про НАШ адрес. Пропуска не требует — открытый ключ на то
 * и открытый (правило 4 Задачи 2), и это замерено: ноль окон кошелька, ноль
 * запросов пропуска.
 *
 * Читатель приходит аргументом, а не импортом, чтобы этот модуль не зависел от
 * хука (а хук зависит от него — цикл получился бы взаимный).
 */
export async function readOwnStanding(
  address: `0x${string}`,
  ownBoxKey: Uint8Array,
  fetchKeys: (address: `0x${string}`, signal?: AbortSignal) => Promise<PeerChatKeys>,
  signal?: AbortSignal,
): Promise<KeyStanding> {
  try {
    const keys = await fetchKeys(address, signal);
    return standingFromDirectory({ ok: true, boxKey: keys.boxKey }, ownBoxKey);
  } catch (err) {
    // Уход со страницы — не ответ справочника. Записать это «недоступен»
    // значило бы наказать следующую попытку за то, что предыдущую остановили.
    if ((err as { name?: string })?.name === 'AbortError') throw err;
    return standingFromDirectory({ ok: false, error: err }, ownBoxKey);
  }
}

export interface AnnounceDeps {
  address: `0x${string}`;
  session: ChatSession;
  /** Человек нажал кнопку. Пробрасывается ДО САМОГО ПОРОГА, а не сочиняется по
   *  дороге: подставив здесь `true` из автоматики, мы вернём подпись в спящую
   *  страницу, и замеры `chatPhoneSignature.test.ts` покраснеют. */
  humanAsked: boolean;
  getPass: (opts: { humanAsked: boolean }) => Promise<string>;
  publish: (pass: string, session: ChatSession, signal?: AbortSignal) => Promise<void>;
  signal?: AbortSignal;
}

/**
 * Объявить свой ключ: взять пропуск и положить обе открытые половины.
 *
 * Порядок неизбежен и обратного не имеет: пропуск первым, потому что адрес для
 * записи сервер берёт из него.
 *
 * Отказ порога (`ChatSignatureDeferred`) пробрасывается КАК ЕСТЬ, не
 * превращается в «не удалось»: это не поломка, а «ещё не время», и вызывающий
 * обязан различать — иначе состояние станет `failed`, и кнопка появится там, где
 * надо было просто подождать видимости страницы.
 */
export async function announceOwnKey(deps: AnnounceDeps): Promise<void> {
  const pass = await deps.getPass({ humanAsked: deps.humanAsked });
  await deps.publish(pass, deps.session, deps.signal);
}
