/**
 * Арифметика платного вызова арбитра — считается здесь, в одном месте, не в
 * разметке. Тот же принцип, что и в соседнем `splitPot.ts`: деньги, посчитанные
 * в двух местах (контракт — своё, фронт — своё), расходятся молча, и на этой
 * ветке так уже случалось дважды. Обе функции ниже раньше жили инлайн —
 * `computeArbiterReward` в `arbiter/page.tsx`, `canFundDispute` в
 * `deal/[address]/page.tsx` — и не были покрыты ничем.
 */

/**
 * Доля арбитра в сборе за спор, в bps. Эталон — `ARBITER_SHARE_BPS` в
 * `src/facets/ArbiterRegistryFacet.sol`; у неё нет геттера на диамонде
 * (`private constant`), прочитать её с цепи нельзя ничем.
 *
 * Это единственное место во фронте, где доля названа числом, и она НЕ «вторая
 * правда»: тест в `disputeBounty.test.ts` читает сам файл фасета, вытаскивает
 * оттуда значение и падает, если оно разошлось с этой строкой. Запрет на
 * вторую копию существовал ради того, чтобы расхождение не случилось МОЛЧА;
 * красный `npm test` — не молчание.
 *
 * Нужна ровно в одной ветке `computeArbiterReward` — когда `quoteDisputeTopUp`
 * вернул 0 и тем самым стёр собственную долю (см. ниже). Во всех остальных
 * случаях доля по-прежнему решается из уравнения контракта, а не отсюда.
 */
export const ARBITER_SHARE_BPS = 8_000n;

/**
 * Суммарная награда арбитра за спор: собственная доля (80% сбора) плюс
 * доплата стороны, если она есть.
 *
 * Собственная доля по возможности НЕ берётся из ARBITER_SHARE_BPS, а решается
 * из уравнения самого контракта:
 *
 *     quoteDisputeTopUp(agreement) == ownShare < floor ? floor - ownShare : 0
 *
 * Значит при topUp > 0: ownShare = floor - topUp — точное значение без единой
 * продублированной константы.
 *
 * ИНВАРИАНТ (доказан ревью алгебраически, закреплён тестом ниже): после того
 * как доплата внесена, награда равна порогу НА МОМЕНТ ОПЛАТЫ и не меняется,
 * если порог потом подвинули (пока он не опустился ниже исходной ownShare —
 * тот более редкий случай, где topUp сам обнуляется, оставлен как есть,
 * см. `docs/OPEN-ITEMS.md`/триаж ревью). Доказательство: пусть в момент
 * оплаты floor = F0, собственная доля fee-based = S (S < F0, зафиксирована
 * disputeFee() сделки — сумма спора после открытия спора не меняется).
 * bounty, внесённый через fundDispute, равен topUp_на_тот_момент = F0 - S.
 * После смены порога на F1 (S всё ещё < F1) свежий topUp пересчитывается как
 * F1 - S, а bounty остаётся прежним (F0 - S) — контракт его не трогает.
 * Тогда:
 *
 *     computeArbiterReward(F1, F1 - S, F0 - S)
 *       = (F1 - (F1 - S)) + (F0 - S)
 *       = S + F0 - S
 *       = F0
 *
 * F1 сократился алгебраически — результат не зависит от того, каким стал
 * порог, только от того, каким он был в момент оплаты.
 *
 * ВТОРАЯ ВЕТКА — `topUp == 0`. Котировка тут стирает ownShare (отдаёт 0
 * вместо разницы), потому что котёл и так даёт арбитру не меньше порога.
 * Уравнение выше в этом состоянии не решается: из `topUp == 0` следует лишь
 * `ownShare >= floor`, а не точное число. Раньше функция в этом случае
 * возвращала `undefined` — и награда пропадала ровно на крупных спорах, где
 * она максимальна и где она сама по себе достаточна: спор на $1000 (сбор $30,
 * арбитру $24) показывал пустоту, а мелкий на $100 — $2.40.
 *
 * Поэтому здесь берётся ещё один вход — `disputeFee`, СБОР САМОЙ СДЕЛКИ,
 * прочитанный с цепи (`Agreement.disputeFee()`), а не пересчитанный из котла:
 * формула сбора (3% с потолком $500) живёт в `Agreement`, и её копия во
 * фронте разошлась бы точно так же, как копия доли. Умножение на долю —
 * единственное, что остаётся сделать здесь.
 *
 * Результат сверяется с тем, что контракт про это состояние УТВЕРЖДАЕТ:
 * `topUp == 0` возможно только при `ownShare >= floor`. Если посчитанная доля
 * оказалась меньше порога, значит ARBITER_SHARE_BPS выше разошлась с фасетом —
 * тогда fail-closed (`undefined`), а не число, которому цепь противоречит.
 *
 * Возвращает `undefined` также когда `disputeFee` не прочитан (чтение в
 * процессе, либо старый клон `Agreement` без селектора `disputeFee` — у него и
 * `quoteDisputeTopUp` отревертит, так что это состояние достижимо).
 *
 * `bounty` прибавляется в обеих ветках. При `topUp == 0` он обычно 0 (доплата
 * возможна только пока `topUp > 0`, иначе `fundDispute` ревертит
 * `TopUpNotNeeded`), но не всегда: если после оплаты владелец диамонда опустил
 * порог НИЖЕ собственной доли, свежий `topUp` схлопывается в 0 при живом
 * `bounty`. Раньше в этом состоянии награда исчезала с экрана вместе с уже
 * оплаченной доплатой — теперь показывается целиком.
 */
export function computeArbiterReward(
  floor: bigint,
  topUp: bigint,
  bounty: bigint,
  disputeFee?: bigint,
): bigint | undefined {
  if (topUp > 0n) return (floor - topUp) + bounty;

  if (disputeFee === undefined) return undefined;
  const ownShare = (disputeFee * ARBITER_SHARE_BPS) / 10_000n;
  if (ownShare < floor) return undefined;
  return ownShare + bounty;
}

/**
 * Пять условий показа кнопки доплаты за арбитра, одной чистой функцией.
 * Каждое закрыто своей ошибкой контракта — показать кнопку в обход любого
 * значит предложить транзакцию, которая гарантированно отревертит и потратит
 * газ релеера впустую:
 *
 *   1. isDisputedStatus  — статус сделки не DISPUTED → NotDisputed
 *   2. isParty           — не сторона сделки        → NotParty
 *   3. !disputeClaimed   — спор уже заклеймлен       → DisputeAlreadyClaimed
 *   4. disputeBounty === 0n
 *                        — доплата уже внесена       → BountyAlreadyFunded
 *                        (quoteDisputeTopUp не вычитает уже внесённую
 *                        доплату и продолжает возвращать то же число после
 *                        успешного fundDispute() — без этой отдельной
 *                        проверки кнопка осталась бы видна и после оплаты)
 *   5. disputeTopUp > 0n — доплата не нужна           → TopUpNotNeeded
 *
 * Непрочитанные данные (ещё `undefined`, чтение в процессе) — fail-closed:
 * кнопка скрыта, а не показана "оптимистично". Показать её на основе
 * неполных данных означает тот же риск отревертить, что и любое из пяти
 * условий выше.
 */
export function canFundDispute(params: {
  isDisputedStatus: boolean;
  isParty: boolean;
  disputeClaimed: boolean;
  disputeBounty: bigint | undefined;
  disputeTopUp: bigint | undefined;
}): boolean {
  const { isDisputedStatus, isParty, disputeClaimed, disputeBounty, disputeTopUp } = params;
  if (!isDisputedStatus) return false;
  if (!isParty) return false;
  if (disputeClaimed) return false;
  if (disputeBounty === undefined || disputeBounty > 0n) return false;
  if (disputeTopUp === undefined || disputeTopUp <= 0n) return false;
  return true;
}
