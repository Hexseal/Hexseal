/**
 * xmtpBotMembership.ts — «а бот-то в группе вообще есть?»
 *
 * ЧТО БЫЛО СЛОМАНО. Парная группа собирается из троих: двое собеседников и бот
 * релеера, который ведёт журнал переписки — ту самую доказательную базу, по
 * которой арбитр решает, кому уходит эскроу. Сборка выглядела так:
 *
 *     const allMembers = botAddress ? [...memberAddresses, botAddress] : [...];
 *     const canMsg = await client.canMessage(identifiers);
 *     const reachable = identifiers.filter(id => canMsg.get(id.identifier) === true);
 *
 * Для СОБЕСЕДНИКА рядом стоял громкий отказ с объяснением, почему молчать
 * нельзя. Для БОТА такой защиты не было вовсе. Если адрес бота не прочитался
 * (релеер моргнул — `getBotAddress()` возвращает `null` по трёхсекундному
 * таймауту) или `canMessage` вернул для него не `true`, бот просто выпадал из
 * `reachable`, и группа создавалась без него. НАВСЕГДА: состав парной группы
 * больше нигде не пересматривался. Переписка этой пары не попадала в журнал ни
 * одним сообщением, а узнать об этом можно было только при споре — когда уже
 * поздно.
 *
 * ПОЧЕМУ НЕ ОТКАЗ В СОЗДАНИИ. Для собеседника отказ верен: сообщение,
 * отправленное в группу без него, не дойдёт никогда — это поломка САМОГО
 * разговора. Отсутствие бота ничего в разговоре не ломает: люди прекрасно
 * поговорят и без журнала. Запрещать им общаться из-за того, что у нас не
 * получается вести протокол, — значит менять полную поломку на полную же, но
 * ещё и не свою. Отказ здесь был бы хуже болезни.
 *
 * ЧТО СТАЛО. Молчаливое выпадение убрано двумя вещами сразу.
 *
 *  1. САМОПОЧИНКА. Состав проверяется не только при создании, а при КАЖДОМ
 *     открытии переписки, и недостающий бот добавляется, если он достижим.
 *     «Навсегда» перестаёт существовать: группа, собранная в момент, когда
 *     релеер моргнул, чинится сама при следующем заходе в чат, и журнал
 *     начинает вестись с этого места.
 *  2. ГРОМКОСТЬ. Когда починить не вышло — бот известен, но недостижим —
 *     исход `missing` доезжает до интерфейса и переписка честно подписывается
 *     «журнал для этой пары неполон». Это не ошибка и ничего не блокирует, но
 *     и не молчание: человек знает, что при споре арбитр увидит не всё, ПОКА
 *     это ещё можно исправить.
 *
 * `unknown` — отдельный исход, а не разновидность `missing`, и разница
 * принципиальная. Он означает «адрес бота неизвестен» (релеер не ответил) либо
 * «состав группы не прочитался» (порченая churn'ом группа бросает
 * SecretReuseError — ровно та ошибка, которую соседний код глушит, чтобы не
 * гасить чат целиком). Ни в том, ни в другом случае у нас нет доказательства,
 * что журнала нет: скорее всего бот в группе есть, просто мы не смогли
 * посмотреть. Пугать человека по такому поводу — значит приучить его не верить
 * предупреждению, которое однажды окажется настоящим.
 *
 * Модуль намеренно не импортирует @xmtp/browser-sdk: ему хватает структурных
 * типов из `xmtpDelivery.ts`, зато его можно проверить тестами без wasm и без
 * сети.
 */

import type { PeerIdentifier, ReachabilityProbe, RepairableGroup } from './xmtpDelivery';

export type BotMembership =
  /** Бот в группе — журнал ведётся. */
  | 'present'
  /** Его не было, но он достижим и только что добавлен — журнал ведётся с этого места. */
  | 'added'
  /** Его нет и добавить не вышло — журнал этой пары неполон, и это надо СКАЗАТЬ. */
  | 'missing'
  /** Проверить не удалось: доказательств, что журнала нет, у нас тоже нет. */
  | 'unknown';

/**
 * Проверяет, что бот релеера состоит в группе, и чинит, если может.
 *
 * @param botId идентификатор бота или `null`, если релеер не отдал адрес.
 */
export async function ensureBotInGroup<TId extends PeerIdentifier>(
  group: RepairableGroup<TId>,
  client: ReachabilityProbe<TId>,
  botId: TId | null,
): Promise<BotMembership> {
  // Адрес бота неизвестен — сравнивать не с чем. Это НЕ «бота нет».
  if (!botId) return 'unknown';

  const botLc = botId.identifier.toLowerCase();

  let members: ReadonlyArray<{ accountIdentifiers?: ReadonlyArray<{ identifier?: string } | undefined> | undefined }>;
  try {
    members = await group.members();
  } catch {
    return 'unknown';
  }

  const hasBot = members.some(m =>
    (m?.accountIdentifiers?.[0]?.identifier?.toLowerCase() ?? '') === botLc,
  );
  if (hasBot) return 'present';

  // Бота в группе нет. Дальше любой отказ — это `missing`, а не `unknown`: чем
  // бы ни кончилась попытка добавить, прямо сейчас журнал этой пары не ведётся.
  try {
    const canMsg = await client.canMessage([botId]);
    if (canMsg.get(botId.identifier) !== true) return 'missing';
    await group.addMembersByIdentifiers([botId]);
  } catch {
    return 'missing';
  }

  // Добавление прошло; отдельная синхронизация — уже удобство, её провал
  // членства не отменяет.
  try { await group.sync(); } catch { /* некритично */ }
  return 'added';
}

/**
 * `true`, если при таком исходе переписку надо подписать «журнал неполон».
 *
 * Только `missing`. `added` — починились, `present` — и не ломалось,
 * `unknown` — не знаем, а пугать наугад нельзя (см. шапку файла).
 */
export function journalIsIncomplete(state: BotMembership): boolean {
  return state === 'missing';
}
