import type { ChatSession } from '@/lib/chatSession';

const _sessions = new Map<string, ChatSession>();
const _listeners = new Set<() => void>();

function tell(): void {
  for (const fn of _listeners) {
    try { fn(); } catch { /* один плохой слушатель не ломает остальных */ }
  }
}

/**
 * Подписка на появление и исчезновение ключа. Зовётся из каждого экземпляра
 * хука: узнать обязаны ВСЕ, кто спрашивал, а не только тот, кто заводил.
 */
export function subscribeChatSession(fn: () => void): () => void {
  _listeners.add(fn);
  return () => { _listeners.delete(fn); };
}

/** Ключ для адреса, если он на устройстве есть. */
export function publishedChatSession(address: string | undefined): ChatSession | null {
  if (!address) return null;
  return _sessions.get(address.toLowerCase()) ?? null;
}

/**
 * Ключ открыт — сказать всем.
 *
 * Молчит, если ровно этот сеанс уже опубликован: иначе каждый экземпляр,
 * подхвативший чужой сеанс, рассылал бы новость по кругу.
 */
export function publishChatSession(address: string, session: ChatSession): void {
  const key = address.toLowerCase();
  if (_sessions.get(key) === session) return;
  _sessions.set(key, session);
  tell();
}

/** Ключ снят с устройства (человек выключил чат) — сказать всем. */
export function forgetPublishedSession(address: string): void {
  const key = address.toLowerCase();
  if (!_sessions.has(key)) return;
  _sessions.delete(key);
  tell();
}

/** Только для замеров. */
export function _resetChatSessionStoreForTest(): void {
  _sessions.clear();
  _listeners.clear();
}
