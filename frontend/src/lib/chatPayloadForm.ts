/**
 * chatPayloadForm.ts — форма содержимого конверта чата: тип `ChatPayload`,
 * вычистка опасных имён ключей и гейт/санация формы после расшифровки.
 *
 * Выделено из `chatEnvelope.ts` ОТДЕЛЬНЫМ модулем (закрывающий круг ревью
 * координатора, задача 3 плана «Клиент чата»): найдено, что правку В-5
 * («гейты формы возвращают вердикт сами, не через перехват» — см.
 * `chatEnvelope.ts`, `unpackEnvelope`) невозможно честно запереть тестом
 * БЕЗ подмены самого гейта — а подменить функцию, вызываемую как локальная
 * ссылка ВНУТРИ ТОГО ЖЕ модуля (`vi.spyOn` на собственный namespace-импорт
 * файла) ненадёжно: живая ESM-привязка гарантирована только МЕЖДУ модулями,
 * не для self-import. Глобальная подмена встроенных функций (`Object.keys`
 * и т.п.) рассматривалась и отклонена — слишком грубо, задевает посторонний
 * код в том же тесте. Отдельный модуль даёт ЧЕСТНУЮ, узко нацеленную
 * подмену — `vi.spyOn(chatPayloadFormModule, 'sanitizePayload')` — тем же
 * приёмом, что уже доказанно работает для `chatCrypto.ts` (В-1/В-2, тот же
 * отчёт).
 *
 * НЕ ЗНАЕТ: про шифрование, сеть, React — только форма уже РАСШИФРОВАННЫХ
 * данных. `unknown` на входе, `ChatPayload | null` на выходе.
 */

export interface ChatPayload {
  text?: string;
  /**
   * Вложение. Первые пять полей были с самого начала; остальные добавлены
   * Задачей 6 (находка В-3 независимой проверки): без них большой файл
   * приезжал БИТЫМ. Отправка кладёт в конверт только то, что здесь названо,
   * а прежний путь через XMTP вёз все девять — панель получателя шла не той
   * веткой расшифровки, теряла превью картинок и не могла обновить
   * протухший адрес скачивания.
   *
   * Все новые поля НЕОБЯЗАТЕЛЬНЫ: сообщение, собранное до этой правки,
   * обязано читаться как прежде.
   *
   * ⚠️ 10 АВГУСТА 2026 (§5 замысла «предъявление переписки арбитру»): ключ
   * вложения переехал ПОД ЗАМОК. `keyHex`/`ivHex` стали НЕОБЯЗАТЕЛЬНЫМИ и
   * ЛЕГАСИ — их несут только сообщения, отправленные ДО этой правки, и они
   * обязаны читаться. Новая сборка кладёт `sealedKey`.
   *
   * Зачем: разовый ключ сообщения выдаётся арбитру целиком (перешифровать
   * нельзя — подпись накрывает зашифрованные байты). Пока ключ вложения лежал
   * ОТКРЫТОЙ СТРОКОЙ в том же содержимом, выдача разового ключа отдавала и
   * файл. Отрезать ключ на предъявлении невозможно: правка содержимого рвёт
   * подпись. Значит замок обязан стоять ЗАРАНЕЕ, на отправке.
   */
  file?: {
    url: string;
    name: string;
    size: number;
    /**
     * ⚠️ ЛЕГАСИ, только чтение. Открытый ключ AES-256 вложения, 64 hex-цифры
     * без префикса. Новая сборка его НЕ ПРОИЗВОДИТ и на провод не выпускает
     * (`packEnvelope`); поле живёт ради сообщений до 10 августа 2026.
     */
    keyHex?: string;
    /** ⚠️ ЛЕГАСИ, только чтение. См. `keyHex`. 24 hex-цифры (12 байт). */
    ivHex?: string;
    /**
     * Вложенный замок на ключ вложения: hex ДВУХ слотов `crypto_box_seal`
     * над `key‖iv` (44 байта) — сначала на собеседника, потом на себя, ровно
     * та же раскладка и та же проба «A, потом B», что у слотов самого
     * конверта. Ширина — `SEALED_ATTACHMENT_KEY_HEX_LEN`.
     *
     * ⚠️ Слоты запечатаны на ТЕ ЖЕ два открытых ключа, что и слоты конверта.
     * Отсюда свойство по построению: конверт открылся ⟹ этот замок открылся.
     * Нового состояния «письмо читается, вложение нет» для честных сообщений
     * не появляется.
     */
    sealedKey?: string;
    /** Ключ файла на складе. Единственное, чем можно обновить протухший
     *  `url`: сам `url` запечатан в конверте и правке не подлежит. */
    fileKey?: string;
    /** Тип содержимого. Без него нет ни превью картинки, ни правильного
     *  типа при сохранении. */
    mime?: string;
    /** Файл загружен нарезанным (больше 20 МБ). Без этого признака панель
     *  идёт ОБЫЧНОЙ веткой расшифровки, и файл не собирается. */
    chunked?: boolean;
    chunkCount?: number;
    /** Размер куска открытого текста (`CHUNK_SIZE`, 8 МБ). */
    chunkSize?: number;
  };
  /** Метка сделки — ВНУТРИ запечатанного, не снаружи (см. докстринг
   *  `chatEnvelope.ts` и тест «метка сделки не встречается в байтах
   *  конверта»). Форма — адрес Agreement-контракта (`0x` + 40 hex-символов),
   *  как везде в проекте (`dealCtx.agreementAddr`, `DisputeLog
   *  dealId=agreement` в `app/arbiter/page.tsx`) — НЕ bytes32.
   *  `sanitizePayload` проверяет форму ПОЛНОСТЬЮ (см. `DEAL_ID_RE`) — но при
   *  несовпадении отбрасывает ТОЛЬКО это поле, не всё сообщение (исправлено
   *  после ревью координатора: ослабленная проверка «только префикс»
   *  пропускала произвольные строки — путь в будущий адрес запроса арбитра
   *  и ключ хранилища). */
  dealId?: `0x${string}`;
}

/**
 * Форма `dealId` — см. JSDoc у `ChatPayload.dealId`. Проверяется ПОЛНОСТЬЮ:
 * префикс `0x` + ровно 40 hex-символов сегодняшнего адреса.
 *
 * ⚠️ ИСПРАВЛЕНО после ревью координатора — прежнее решение (проверять
 * только префикс `0x`, принимая любую длину/содержимое) было ошибочным.
 * Независимая проверка провела строку через модуль насквозь и проследила,
 * куда она попадёт при подключении: dealId становится частью адреса
 * запроса на странице арбитра и ключом хранилища
 * (`app/arbiter/page.tsx`/`disputeLogPass.ts`, план 4). Ослабленная
 * проверка пропускала `0x`, `0xZZZZ` (невалидный hex), строку на сто тысяч
 * символов, `0x../../../../storage/files` (попытка обхода пути), разметку,
 * нулевой байт — сегодня безвредно (модуль ещё никем не подключён), но
 * ровно то, что стало бы инъекцией в день подключения.
 *
 * Правильная форма — не «строго ИЛИ ослабленно», а ОБА СРАЗУ: полная
 * проверка формы здесь (см. `sanitizePayload` ниже — при НЕСОВПАДЕНИИ
 * отбрасывается ТОЛЬКО ПОЛЕ dealId, не всё сообщение). Тогда подстановка
 * невозможна (форма проверена полностью), и смена формата метки в будущем
 * не съедает переписку (страдает только сама метка, не текст/вложение).
 */
const DEAL_ID_RE = /^0x[0-9a-fA-F]{40}$/;

/**
 * Ширина hex-строки `sealedKey`: ДВА слота `crypto_box_seal` по 92 байта
 * (48 накладных расходов запечатывания + 44 байта `key‖iv`) = 184 байта =
 * 368 hex-цифр.
 *
 * ⚠️ ЖИВЁТ ЗДЕСЬ, А НЕ В `chatEnvelope.ts`, и это не вкус. Гейт формы (этот
 * модуль) и производитель (`chatEnvelope.ts`) обязаны знать ОДНО И ТО ЖЕ
 * число; импорт в обратную сторону завёл бы цикл — `chatEnvelope` уже
 * импортирует этот модуль. Дублировать число в двух файлах — ровно тот класс
 * дефекта, против которого в проекте стоят гейты раскладки.
 *
 * ⚠️ ЕДИНСТВЕННЫЙ ИСТОЧНИК ЭТОГО ЧИСЛА ВО ВСЁМ ПЛАНЕ (договор v2, исправление 2):
 * объявляется здесь, **экспортируется** отсюда, Задачи 5-8 его ИМПОРТИРУЮТ и своего
 * не заводят. Второе объявление разойдётся с этим ровно так же, как разошлись
 * base64 у Задачи 5 и hex у Задачи 6 — обе зелёные, стык мёртв.
 *
 * ⚠️ И ЭТО ЕДИНСТВЕННОЕ hex-ПОЛЕ ПЛАНА. Все «строковые» байтовые поля контейнера
 * предъявления — base64 без `0x`, через `b64FromBytes`/`bytesFromB64` из
 * `presentation.ts`. `sealedKey` — исключение, потому что лежит ВНУТРИ
 * запечатанного содержимого рядом с `keyHex`/`ivHex`, которые строчным hex живут с
 * самого начала (`fileCrypto.ts:5-7`). Смешивать нельзя ни в одну сторону; на
 * попытку стоит замок — случай `base64 вместо hex` в тесте формы.
 */
export const SEALED_ATTACHMENT_KEY_HEX_LEN = 368;

const SEALED_ATTACHMENT_KEY_RE = new RegExp(`^[0-9a-f]{${SEALED_ATTACHMENT_KEY_HEX_LEN}}$`);

/** Опасные имена ключей — открывают путь к загрязнению прототипа у
 *  БУДУЩЕГО потребителя, который сольёт разобранный payload с умолчаниями
 *  через `{...defaults, ...payload}`/`Object.assign` (В-7, ревью
 *  координатора). `JSON.parse` НЕ трогает реальный `[[Prototype]]` объекта
 *  (`__proto__` в JSON становится обычным СВОИМ свойством, не спецсимволом,
 *  как в литерале `{__proto__: x}`) — прототип модуля не загрязняется САМ
 *  ПО СЕБЕ, но политика «незнакомые поля не стираем» сохраняла бы и это
 *  свойство, готовое отравить цель слияния у потребителя, которого сегодня
 *  ещё нет, но который появится. */
const DANGEROUS_KEYS = new Set(['__proto__', 'constructor', 'prototype']);

/**
 * Рекурсивно вычищает `DANGEROUS_KEYS` из разобранного JSON — объекты и
 * массивы любой глубины (не только верхний уровень и не только `file`;
 * общий проход, не зависящий от того, что именно `ChatPayload` знает
 * сегодня — тот же принцип устойчивости к будущей форме, что и у
 * `DEAL_ID_RE`/сохранения незнакомых полей). Всегда строит НОВЫЙ объект/
 * массив (не мутирует вход) — безопасно передавать результат дальше на
 * мутацию (`sanitizePayload` ниже удаляет `dealId` из уже склонированного
 * объекта). Примитивы возвращаются как есть. Экспортирована — проверяема
 * напрямую, без сборки целого конверта.
 */
export function stripDangerousKeys(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(stripDangerousKeys);
  }
  if (value !== null && typeof value === 'object') {
    const clean: Record<string, unknown> = {};
    for (const key of Object.keys(value as Record<string, unknown>)) {
      if (DANGEROUS_KEYS.has(key)) continue;
      clean[key] = stripDangerousKeys((value as Record<string, unknown>)[key]);
    }
    return clean;
  }
  return value;
}

/* ───────────────────── имя вложения из чужих рук ──────────────────────── */

/**
 * Символы, которые в имени файла не несут смысла и служат ровно одному —
 * показать человеку не то, что лежит.
 *
 *  - U+202A…U+202E, U+2066…U+2069 — переключение и изоляция направления
 *    письма. Классический приём: `счёт<RLO>fdp.exe` рисуется как
 *    `счётexe.pdf`. Настоящее расширение при этом `.exe`.
 *  - U+200E, U+200F, U+061C — метки направления, то же самое послабее.
 *  - U+200B…U+200D, U+FEFF — нулевой ширины: невидимы, разрывают расширение
 *    для любой проверки «оканчивается на .exe», не меняя вида.
 *  - C0/C1 и DEL — управляющие. Перевод строки в имени разрывает его на два
 *    в любом однострочном месте, `U+001B` — начало escape-последовательности
 *    терминала (имя попадает в журналы).
 *
 * (11 августа 2026) Класс записан ЭКРАНИРОВАННО намеренно — сырых управляющих
 * байтов в исходнике быть не должно. До этой правки они лежали здесь как есть,
 * и файл считался ДВОИЧНЫМ. Замер: `grep -rl UNSAFE_NAME_CHARS frontend/src/lib`
 * возвращал ПУСТО, то есть проверка «единственный источник» молча не видела файл,
 * где источник и объявлен; молчали все формы -c, -l, -n, -rl.
 * Смысл класса не изменился ни на символ: в chatFileName.test.ts каждый
 * враждебный символ проверяется поштучно и там уже экранирован.
 * Замок против возврата сырых байтов — sourceHasNoRawControlBytes.test.ts.
 */
const UNSAFE_NAME_CHARS = /[\u0000-\u001F\u007F-\u009F\u061C\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/g;

/**
 * Потолок длины имени. Двести — заведомо больше любого человеческого имени
 * файла и заведомо меньше того, чем можно сломать вёрстку строки сообщения
 * (замерено на ста тысячах символов). Расширение переживает обрезку: по нему
 * человек и решает, открывать ли.
 */
const MAX_FILE_NAME_LEN = 200;

/** Имя, которое подставляется, когда от присланного не осталось ничего
 *  годного. Пустая строка была бы хуже: строка без имени выглядит как
 *  поломка отображения, а не как странное имя у отправителя. */
const FALLBACK_FILE_NAME = 'file';

/**
 * Вычищает имя вложения.
 *
 * ⚠️ ПОЧЕМУ ЧИСТКА, А НЕ ОТКАЗ ВСЕМУ СООБЩЕНИЮ. Остальные гейты этого модуля
 * на испорченном ЗНАКОМОМ поле возвращают `null`. Здесь это было бы хуже:
 * форма у имени в порядке (строка и есть строка), испорчено СОДЕРЖИМОЕ, и
 * отказ означал бы, что вложение у получателя ПРОПАЛО — то есть дыра в
 * переписке за то, что отправитель назвал файл странно. Дыру собеседник не
 * отличит от утаивания (`docs/OPEN-ITEMS.md`), а странное имя не стоит такого
 * обвинения.
 *
 * Экспортирована: чистка имени — самостоятельное правило со своей ценой, и
 * проверяться оно должно прямо, а не через сборку целого конверта.
 */
export function sanitizeFileName(raw: string): string {
  // Сначала путь: всё до последнего разделителя — не имя. Атрибут скачивания
  // браузеры и так режут, но имя едет ещё и на экран, и в будущий путь
  // сохранения, и полагаться на чужую вежливость тут не на что.
  const base = raw.split(/[/\\]/).pop() ?? '';
  const cleaned = base.replace(UNSAFE_NAME_CHARS, '').trim();
  // `.` и `..` — не имена: в любом пути это ссылки на каталог.
  if (cleaned === '' || cleaned === '.' || cleaned === '..') return FALLBACK_FILE_NAME;
  if (cleaned.length <= MAX_FILE_NAME_LEN) return cleaned;

  // Обрезка с сохранением расширения. Расширением считается только короткий
  // хвост после последней точки — иначе «имя» из ста тысяч символов без
  // единой точки съело бы весь потолок под «расширение».
  const dot = cleaned.lastIndexOf('.');
  const ext = dot > 0 && cleaned.length - dot <= 12 ? cleaned.slice(dot) : '';
  return cleaned.slice(0, MAX_FILE_NAME_LEN - ext.length) + ext;
}

/**
 * Гейт формы разобранного payload — та же дисциплина, что `isBagSummary`/
 * `isWellFormedLink` в соседних модулях: данные из сети, вере не подлежат.
 * Проверяет ТОЛЬКО известные поля; любые лишние (СЕМАНТИЧЕСКИ безопасные —
 * опасные уже вычищены `stripDangerousKeys` до вызова) — не повод
 * отказывать (см. докстринг `chatEnvelope.ts` про незнакомые поля).
 *
 * `null` — структурная порча (не объект, `text`/`file` не той формы):
 * отказ ВСЕМУ сообщению, восстанавливать нечего. `dealId` — ОСОБЫЙ случай:
 * при несовпадении формы (см. `DEAL_ID_RE`) отбрасывается ТОЛЬКО ОНО,
 * остальной payload возвращается как есть (В-7-соседняя находка ревью —
 * dealId ЗНАКОМОЕ поле с подвижной формой, а не незнакомое поле целиком,
 * терять из-за него текст/вложение сообщения не за что).
 *
 * Мутирует и возвращает СВОЙ аргумент (`v`) — вызывающая сторона обязана
 * передавать сюда уже склонированный `stripDangerousKeys` результат, не
 * исходный объект из `JSON.parse`.
 *
 * НЕ бросает ни на каком `unknown` входе — проверено (закрывающий круг
 * ревью): единственный способ заставить эту функцию бросить — испортить её
 * саму (регресс, снимающий короткое замыкание перед вызовом строкового
 * метода на нестроковом значении). Именно поэтому `unpackEnvelope`
 * (`chatEnvelope.ts`) зовёт её ВНЕ `try/catch` (В-5) — бросок отсюда это
 * НАШ баг, а не чужие испорченные данные, и обязан быть виден.
 */
export function sanitizePayload(value: unknown): ChatPayload | null {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return null;
  const v = value as Record<string, unknown>;

  if (v.text !== undefined && typeof v.text !== 'string') return null;

  if (v.file !== undefined) {
    if (typeof v.file !== 'object' || v.file === null || Array.isArray(v.file)) return null;
    const f = v.file as Record<string, unknown>;
    if (
      typeof f.url !== 'string' ||
      typeof f.name !== 'string' ||
      typeof f.size !== 'number' || !Number.isFinite(f.size) || f.size < 0
    ) {
      return null;
    }

    // ── Ключ вложения: ОДНА из двух форм, «ни одной» — отказ ──────────────
    //
    // Легаси (до 10 августа 2026): keyHex + ivHex открытыми строками. Новая:
    // sealedKey, вложенный замок. Требование замысла §5 — «прежние сообщения
    // читаются и не падают», и ровно это, а не «принимать вложение без
    // ключа»: до правки keyHex/ivHex были ОБЯЗАТЕЛЬНЫ, и сообщение без них
    // отвергалось целиком. Ослабить это значило бы пустить панель третьей
    // ветвью (`attachmentDecryptPlan` → `mode: 'plain'`) и потянуть
    // шифротекст прямо в <img src> — то есть показать человеку мусор вместо
    // отказа.
    //
    // Форма легаси-полей осталась прежней (только `typeof === 'string'`) —
    // намеренно: их производил старый код, и ужесточение здесь выкинуло бы
    // живые старые сообщения. Форма `sealedKey` проверяется ПОЛНОСТЬЮ
    // (алфавит и длина): это НАШ формат, и слабая проверка ключа уже названа
    // пробелом (справочник конверта, Б-8) — повторять её не за чем.
    if (f.keyHex !== undefined && typeof f.keyHex !== 'string') return null;
    if (f.ivHex  !== undefined && typeof f.ivHex  !== 'string') return null;
    // Половина пары — отказ: ключ без вектора (и наоборот) расшифровать
    // нечем, а уронить молча одно вложение значило бы дыру в переписке,
    // которую собеседник не отличит от утаивания.
    if ((f.keyHex === undefined) !== (f.ivHex === undefined)) return null;
    if (f.sealedKey !== undefined &&
        (typeof f.sealedKey !== 'string' || !SEALED_ATTACHMENT_KEY_RE.test(f.sealedKey))) return null;
    if (f.keyHex === undefined && f.sealedKey === undefined) return null;

    // Поля нарезки и опознания (Задача 6, В-3). Необязательные, но если
    // ПРИСУТСТВУЮТ — форма проверяется так же строго, как у старших:
    // `chunked: "yes"` вместо булева повёл бы панель не той веткой
    // расшифровки, а `chunkCount: "5"` дал бы NaN в арифметике сборки.
    if (f.fileKey !== undefined && typeof f.fileKey !== 'string') return null;
    if (f.mime !== undefined && typeof f.mime !== 'string') return null;
    if (f.chunked !== undefined && typeof f.chunked !== 'boolean') return null;
    if (f.chunkCount !== undefined &&
        (typeof f.chunkCount !== 'number' || !Number.isSafeInteger(f.chunkCount) || f.chunkCount < 0)) return null;
    if (f.chunkSize !== undefined &&
        (typeof f.chunkSize !== 'number' || !Number.isSafeInteger(f.chunkSize) || f.chunkSize < 0)) return null;

    // ⚠️ ЧИСТКА ИМЕНИ СТОИТ НА ПУТИ, А НЕ РЯДОМ С НИМ. Форма имени проверена
    // выше (строка), но строка может показывать не то, что лежит: символом
    // переворота направления письма `счёт.exe` рисуется как `счёт.pdf`.
    // Разбор — в докстринге `sanitizeFileName`. Экспортированная функция,
    // которую никто не зовёт, защитой не является.
    f.name = sanitizeFileName(f.name);
  }

  if (v.dealId !== undefined && (typeof v.dealId !== 'string' || !DEAL_ID_RE.test(v.dealId))) {
    delete v.dealId;
  }

  return v as ChatPayload;
}

/* ────────────────────── вид арбитра: §5 замысла ───────────────────────── */

/**
 * Вложение в том виде, в каком его видит АРБИТР: имя, размер, тип, признак
 * нарезки — и больше ничего.
 *
 * ⚠️ ПОЛЕЙ КЛЮЧА И АДРЕСА ЗДЕСЬ НЕТ ВОВСЕ — не `undefined`, а отсутствуют в
 * типе. Разница несущая: `keyHex?: string` компилировал бы
 * `decryptToObjectUrl(f.url, f.keyHex, f.ivHex)`, и запрет держался бы на
 * том, что никто не написал этот вызов. Здесь его НЕЛЬЗЯ написать: у типа нет
 * ни ключа, ни адреса, а без адреса арбитр не узнаёт даже, ГДЕ лежит файл.
 * Форма вместо проверки — правило проекта, купленное замером «0 красных из
 * 1826» на перестановке ключей мимо клейма типа.
 */
export interface RedactedFilePayload {
  name: string;
  size: number;
  mime?: string;
  chunked?: boolean;
}

/** Содержимое сообщения в виде арбитра. Слова — целиком (решение владельца
 *  §3: «от „я ему говорил" до „да ты фигню намутил" разница колоссальная»),
 *  вложение — только фактом. */
export interface RedactedPayload {
  text?: string;
  file?: RedactedFilePayload;
  dealId?: `0x${string}`;
}

/**
 * Вид арбитра ПЛЮС признак честности, и они возвращаются ВМЕСТЕ намеренно.
 *
 * ⚠️ ЗАЧЕМ СТРУКТУРОЙ, А НЕ ДВУМЯ ВЫЗОВАМИ. Признак «у этого сообщения ключ
 * вложения открыт» — единственное, чем экран может не соврать: у сообщений до
 * 10 августа 2026 ключ лежит открытой строкой, и обещание «арбитр не откроет
 * вложения» для них ЛОЖНО. Отдельный предикат `isLegacyExposed(payload)`
 * можно забыть позвать; поле в структуре, которую и так приходится принять
 * ради самого содержимого, забыть нельзя — вид без признака просто не
 * достать.
 */
export interface Redaction {
  payload: RedactedPayload;
  /** `true` — ключ вложения ЭТОГО сообщения открыт (старая форма). Экран
   *  обязан оговорить это словами, а не молчать.
   *
   *  ⚠️ Договор v2 (исправление 9) сделал парное поле
   *  `PresentedMessage.legacyAttachmentExposed` ОБЯЗАТЕЛЬНЫМ, а не `?`, — то
   *  есть признак, полученный здесь, теперь нельзя потерять по дороге к
   *  арбитру: сборка `PresentedMessage` без него не скомпилируется. */
  legacyAttachmentExposed: boolean;
}

/* ── ТИП-ЗАМОК: в виде арбитра НЕТ полей ключа и адреса ───────────────────── */
/**
 * ⚠️ ЖИВЁТ ЗДЕСЬ, А НЕ В ТЕСТЕ, И ЭТО ЗАМЕРЕНО, а не выбрано по вкусу.
 * `frontend/tsconfig.json` исключает тестовые файлы (`*.test.ts`, `*.test.tsx`)
 * из программы — исключение намеренное и подписано в самом tsconfig, — а vitest
 * типы не считает вовсе.
 * (Маску со звёздочкой здесь не пишу нарочно: последовательность «звёздочка,
 * слэш» закрыла бы этот блочный комментарий на середине фразы.)
 * Значит `@ts-expect-error`, поставленный в `*.test.ts`, не проверяется НИЧЕМ:
 * мутация «добавить `keyHex?: string` в `RedactedFilePayload`» дала бы **ноль
 * красных на обеих проверках** — код есть, никто им не пользуется. Фикстура
 * запрета обязана лежать там, куда `npm run type-check` смотрит, то есть в
 * этом файле.
 *
 * Читается так: появится в `RedactedFilePayload` хоть одно из перечисленных
 * имён — `Lacks<…>` станет `false`, `AssertTrue<false>` нарушит ограничение
 * `T extends true`, и `npm run type-check` покраснеет строкой
 * «Type 'false' does not satisfy the constraint 'true'».
 *
 * `export type`, а не локальный алиас, намеренно: экспорт употреблён по
 * определению, и правило «неиспользуемое имя» его не выкинет из файла чьей-то
 * уборкой.
 */
export type AssertTrue<T extends true> = T;
export type Lacks<T, K extends string> = [Extract<keyof T, K>] extends [never] ? true : false;

/** Ни ключа, ни вектора, ни замка, ни адреса, ни ключа склада: без адреса
 *  арбитр не узнаёт даже, ГДЕ лежит файл, а без ключа — чем его открыть. */
export type ArbiterViewLacksKeyFields = AssertTrue<
  Lacks<RedactedFilePayload, 'keyHex' | 'ivHex' | 'sealedKey' | 'url' | 'fileKey'>
>;

/** То же на верхнем уровне вида: байтовых полей у него нет ВОВСЕ — поэтому
 *  вопрос «hex или base64» (договор v2, исправление 2) к моей выдаче не
 *  относится физически, а не по договорённости. */
export type ArbiterViewTopLacksKeyFields = AssertTrue<
  Lacks<RedactedPayload, 'keyHex' | 'ivHex' | 'sealedKey' | 'signature'>
>;

/**
 * Строит вид арбитра РАЗРЕШИТЕЛЬНЫМ списком — перечислением того, что ему
 * положено, а не вычёркиванием запрещённого.
 *
 * ⚠️ ЗАЧЕМ ИМЕННО ТАК. Гейт формы этого модуля намеренно СОХРАНЯЕТ незнакомые
 * поля (чтобы будущая версия формата не съедалась старой сборкой). Значит в
 * `payload` может лежать что угодно, включая ключ под именем, которого мы
 * сегодня не знаем. Запретительный список (`delete f.keyHex`) надо было бы не
 * забыть дополнить при каждом новом поле — а разрешительный не пропустит
 * новое поле сам по себе, без чьей-либо памяти.
 *
 * Признак считается по ПРОВОДНОМУ виду содержимого: `keyHex` у арбитра
 * присутствует ровно тогда, когда он был открыт в самом сообщении. Путь
 * арбитра (`openEnvelopeWithOneTimeKey`) пары ключей не имеет и вернуть ключ
 * на место не может — то есть отличить «открыт» от «под замком» здесь можно
 * по построению, а не по чьему-то слову.
 */
export function redactPayload(payload: ChatPayload): Redaction {
  const out: RedactedPayload = {};
  if (payload.text !== undefined) out.text = payload.text;
  if (payload.dealId !== undefined) out.dealId = payload.dealId;

  let legacyAttachmentExposed = false;
  const f = payload.file;
  if (f) {
    const file: RedactedFilePayload = { name: f.name, size: f.size };
    if (f.mime !== undefined) file.mime = f.mime;
    if (f.chunked !== undefined) file.chunked = f.chunked;
    out.file = file;
    legacyAttachmentExposed = typeof f.keyHex === 'string';
  }

  return { payload: out, legacyAttachmentExposed };
}
