/**
 * attachmentFailure.ts — «файл не открылся» это ТРИ разных события.
 *
 * ЧТО БЫЛО. Протухшее вложение, битый ключ и отказ склада в доступе
 * показывались одной подписью «Ошибка расшифровки». Первое — нормальный,
 * заранее объявленный срок хранения (релеер чистит `/storage/files/` через
 * семь дней), человеку надо просто попросить прислать заново. Второе —
 * настоящая поломка шифртекста/ключа. Третье появилось 10 августа 2026,
 * когда `GET /files/:key` на релеере стал требовать пропуск склада и
 * принадлежность паре (§5 замысла): пропуск живёт 12 часов и обновляется
 * подписью кошелька по человеческому действию, так что человек, вернувшийся
 * на следующий день и не заходивший в чат, получает 401 на файл, с которым
 * всё в порядке. Один и тот же текст «ошибка расшифровки» на все три случая
 * заставлял чинить то, что не ломалось, — ровно тот дефект, ради которого
 * этот модуль и заведён изначально.
 *
 * КАК ОТЛИЧАЕМ:
 *
 *  • ответ файлового сервера 404/410 → `expired` (`decryptToObjectUrl` кладёт
 *    статус прямо в текст ошибки: `Failed to fetch file: 404`);
 *  • сообщению больше срока хранения → `expired`, тогда файла на диске нет
 *    гарантированно, чем бы ни кончился запрос. Этот признак нужен потому,
 *    что до сервера можно вообще не доехать (офлайн, релеер лежит), а правда
 *    о файле от этого не меняется. Проверяется ПЕРЕД статусом доступа: если
 *    сообщению заведомо больше срока хранения, файла нет уже независимо от
 *    того, что ответил склад;
 *  • ответ 401/403 → `no_access`: склад отказал в доступе (пропуска нет, он
 *    протух, или это чужой пропуск), но про сам файл ничего не известно —
 *    чинится не расшифровкой, а новым заходом в чат;
 *  • всё остальное → `decrypt_failed`.
 */

/** Срок хранения чат-вложений на релеере. Держится в трёх местах и обязан
 *  совпадать: `relayer/app.js` (`FILE_TTL_MS`), тексты локалей и вот это
 *  значение. Расхождение уже случалось — интерфейс обещал 18 дней при реальных
 *  семи. */
export const ATTACHMENT_TTL_MS = 7 * 24 * 60 * 60 * 1000;

export type AttachmentFailure =
  /** Срок хранения истёк — файла нет и не будет, чинить нечего. */
  | 'expired'
  /** Склад отказал в доступе — пропуска нет/протух/чужой. Файл, возможно,
   *  цел; лечится новым заходом в чат, а не расшифровкой. */
  | 'no_access'
  /** Файл есть, доступ подтверждён, но открыть не вышло — вот это настоящая ошибка. */
  | 'decrypt_failed';

export interface AttachmentFailureContext {
  /** Время сообщения с вложением, мс. */
  sentAt?: number;
  now?: number;
  ttlMs?: number;
}

/** HTTP-статусы, которыми файловый сервер отвечает на «этого файла здесь нет». */
const GONE_STATUSES = [404, 410];

/** HTTP-статусы «доступ не подтверждён»: `requireBagPass` (401 — пропуска нет
 *  или протух) и «не твой файл» (403 — пропуск чужой, см. `not_your_file` в
 *  relayer/app.js). Ни один не говорит о судьбе самого файла — только о том,
 *  что предъявить право на него сейчас нечем. */
const NO_ACCESS_STATUSES = [401, 403];

export function classifyAttachmentFailure(
  err: unknown,
  ctx: AttachmentFailureContext = {},
): AttachmentFailure {
  const message = err instanceof Error ? err.message : typeof err === 'string' ? err : '';
  if (GONE_STATUSES.some(s => message.includes(String(s)))) return 'expired';

  // ПЕРЕД разбором статуса доступа: если сообщению уже заведомо больше срока
  // хранения, файла нет гарантированно, независимо от того, что успел
  // ответить склад (мог отказать в доступе раньше, чем дошёл до проверки
  // существования файла).
  const ttl = ctx.ttlMs ?? ATTACHMENT_TTL_MS;
  const now = ctx.now ?? Date.now();
  if (ctx.sentAt !== undefined && ctx.sentAt > 0 && now - ctx.sentAt > ttl) return 'expired';

  if (NO_ACCESS_STATUSES.some(s => message.includes(String(s)))) return 'no_access';

  return 'decrypt_failed';
}

/**
 * Стоит ли повторять запрос вложения через `refreshDownloadUrl`, увидев
 * `classified` первым отказом.
 *
 * Вынесено чистой функцией по той же причине, что и `attachmentDecryptPlan`
 * в `ChatPanel.tsx`: решение живёт внутри `.catch()` обработчика в панели, а
 * там его нечем проверить без браузера — эта копия и есть то, что реально
 * зовёт `ImageBubble`/`FileCard`, а не пересказ той же логики в тесте.
 *
 * `no_access` (401/403) НЕ повторяем: у повтора один способ помочь — если
 * ссылка сама протухла (легаси-хранилище), а «зашитый в устройство пропуск
 * протух или чужой» повтором той же ссылки не лечится вовсе — пропуск не
 * появится за миллисекунды между двумя попытками. Повтор здесь только
 * удваивает нагрузку на склад и задерживает верную надпись на экране.
 * `expired`/`decrypt_failed` сохраняют старое поведение: ссылка могла
 * протухнуть по-настоящему, и обновлённую стоит попробовать.
 */
export function shouldRetryAttachmentFetch(classified: AttachmentFailure): boolean {
  return classified !== 'no_access';
}
