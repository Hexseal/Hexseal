/**
 * chatParseCache.ts — потолок кэша разбора и правило вытеснения.
 *
 * Вынесено из `chatConversation.ts` отдельным модулем не ради красоты: правило
 * вытеснения — это то место, где «ускорение» однажды уже стало торможением, и
 * проверяемо оно должно быть ПРЯМО, без сборки пяти тысяч настоящих мешков
 * вокруг него.
 *
 * ─── ЧТО ЗДЕСЬ ЧИНИТСЯ (К-3 враждебной проверки) ────────────────────────
 *
 * Кэш разбора существует потому, что `receiveBags` зовётся на КАЖДОМ тике
 * опроса и разбирает ВЕСЬ накопленный набор — цепочка проверяется целиком,
 * вердикт по половине переписки не вердикт. Дорогого в мешке ровно два места:
 * проверка подписи звена и расшифровка конверта.
 *
 * Прежнее правило было «вытесняем САМОЕ СТАРОЕ» (Map хранит порядок вставки —
 * удалить первый ключ). На кольцевом обходе это вырождается ПОЛНОСТЬЮ, и не
 * постепенно, а обрывом:
 *
 *   набор 5000 при потолке 5000 → попаданий 100 %
 *   набор 5001 при потолке 5000 → попаданий РОВНО НОЛЬ
 *
 * Потому что разбор идёт по набору в одном и том же порядке. Мешок №1 не
 * помещается, вытесняет №2 (самый старый) — а №2 нужен следующим же шагом.
 * И так по кругу: каждый мешок вытесняет ровно тот, который потребуется через
 * шаг. Классическое вырождение FIFO/LRU на циклическом доступе.
 *
 * ЗАМЕР ДО ПРАВКИ (боевой потолок 5000):
 *   4999: холодный 2511 мс, повторный  255 мс
 *   5000: холодный 2461 мс, повторный  244 мс
 *   5001: холодный 2438 мс, повторный 2456 мс  — ДОРОЖЕ холодного
 *  20000: холодный 9738 мс, повторный 9804 мс  — ДОРОЖЕ холодного
 *
 * ─── ЧТО ЗАПОМИНАТЬ, КОГДА ЗАПОМНИТЬ ВСЁ НЕЛЬЗЯ ─────────────────────────
 *
 * Кэш меньше набора — значит вопрос не «сколько», а ЧТО держать. Верхний
 * предел известен точно: при кольцевом обходе попаданий не может быть больше,
 * чем ПОТОЛОК/НАБОР, — просто потому, что столько записей и помещается. Всё
 * остальное решает правило вытеснения.
 *
 * Худший ответ — «вытесняем то, что трогали раньше всех». При кольцевом обходе
 * это ровно та запись, которая понадобится СЛЕДУЮЩЕЙ: FIFO указывает на
 * худшую жертву из возможных, и попаданий выходит РОВНО НОЛЬ.
 *
 * Случайная жертва про порядок обхода не знает и худшую выбрать не может.
 * Но одной случайности мало, и это ЗАМЕРЕНО, а не выведено: набор 20 000 при
 * потолке 5000 дал всего 2,3 % попаданий вместо возможных 25 %. Причина —
 * кэш перемалывает сам себя: каждый промах кого-то вытесняет, за круг промахов
 * тысячи, и записи не доживают до своего следующего использования.
 *
 * Поэтому вытеснению добавлен ПРИЁМ НЕ ВСЕГДА: когда кэш полон, новая запись
 * попадает в него лишь изредка (одна из восьми). Кэш перестаёт перемалывать
 * себя, устанавливается устойчивое подмножество — и доля попаданий подходит к
 * своему потолку ПОТОЛОК/НАБОР:
 *
 *   набор  5001, потолок 5000 → ~99,98 % попаданий (замерено: 1 промах из 5001)
 *   набор 20 000, потолок 5000 → ~20 % при возможных 25 %
 *
 * ⚠️ ЦЕНА ПРИЁМА НЕ ВСЕГДА НАЗВАНА. Если набор сменился ЦЕЛИКОМ (открыли
 * другую переписку) и кэш при этом ПОЛОН, новый набор прогревается не за один
 * проход, а примерно за восемь. Случай узкий: полон кэш бывает только когда
 * прежняя переписка сама по себе была длиной в пять тысяч мешков; во всех
 * остальных вытеснения нет вовсе, и приём безусловный. Размен сознательный:
 * восемь тиков прогрева против нуля попаданий навсегда.
 *
 * ⚠️ ПОЧЕМУ НЕ «ПОДНЯТЬ ПОТОЛОК». Это передвинуло бы обрыв, а не убрало его:
 * на потолке 20 000 то же самое случилось бы на 20 001. Правило вытеснения —
 * причина, потолок — только место, где она проявляется.
 *
 * ⚠️ ПОЧЕМУ СЛУЧАЙНОСТЬ ЗДЕСЬ ВОСПРОИЗВОДИМАЯ. Жертва выбирается собственным
 * счётчиком (xorshift32), а не `Math.random()`: замер, который каждый раз даёт
 * другое число, нельзя ни сравнить с прошлым, ни предъявить. От порядка
 * ОБХОДА этот счётчик независим ровно так же, как настоящая случайность, — а
 * это единственное, что от него требуется. Секретом он не является и защищать
 * ничего не должен: кэш не меняет ни одного вердикта (заперто отдельно —
 * `chatParseCache.test.ts`, подделка под тем же ключом и чужой сеанс).
 */

/**
 * Потолок записей на кэш. Кэш живёт на модуле, то есть на вкладку; без потолка
 * длинная переписка держала бы в памяти всё, что когда-либо разбиралось.
 *
 * ⚠️ ЦЕНА ПОТОЛКА НАЗВАНА ЧЕСТНО и теперь она другая. Раньше это был обрыв:
 * за потолком кэш переставал давать что-либо вовсе. Теперь это плавное
 * снижение доли попаданий (потолок/набор) — переписка на двадцать тысяч
 * мешков разбирается повторно примерно на четверть дешевле, а не наравне с
 * холодным.
 */
export const PARSE_CACHE_MAX = 5_000;

/**
 * Одна из скольких новых записей принимается, когда кэш ПОЛОН (см. шапку —
 * «приём не всегда»). Восемь: замерено, что при наборе вчетверо больше потолка
 * это даёт около 20 % попаданий из возможных 25, а прогрев после полной смены
 * набора занимает примерно столько же проходов. Единица (принимать всегда)
 * даёт 2,3 % — кэш перемалывает сам себя.
 */
export const ADMIT_ONE_OF = 8;

/**
 * Кэш с потолком и СЛУЧАЙНОЙ жертвой.
 *
 * `max` — параметр, а не константа внутри: свойство «доля попаданий падает
 * плавно» проверяется на маленьких потолках за миллисекунды, и заставлять
 * замер строить пять тысяч настоящих мешков ради него значило бы не проверять
 * его вовсе.
 */
export class BoundedParseCache<V> {
  private readonly map = new Map<string, V>();
  /** Ключи в порядке вставки — нужны, чтобы выбрать жертву за одно действие.
   *  Дыры не образуются: выбывший заменяется последним (`swap-remove`). */
  private readonly keys: string[] = [];
  private seed: number;

  constructor(readonly max: number = PARSE_CACHE_MAX, seed = 0x9e3779b9) {
    if (!Number.isSafeInteger(max) || max < 1) {
      throw new TypeError(`BoundedParseCache: потолок должен быть целым ≥ 1, получено ${max}`);
    }
    this.seed = seed >>> 0 || 1;
  }

  get size(): number { return this.map.size; }

  get(key: string): V | undefined { return this.map.get(key); }

  /**
   * Кладёт и возвращает значение.
   *
   * ⚠️ ЗНАЧЕНИЕ ВОЗВРАЩАЕТСЯ ВСЕГДА, ДАЖЕ ЕСЛИ ЗАПИСЬ НЕ ПРИНЯТА. Вызывающий
   * пользуется результатом сразу (`.ok`, `.payload`) — «не запомнили» не
   * должно превращаться в «не посчитали». Это единственная причина, по которой
   * `put` вообще что-то возвращает.
   *
   * Повторная запись существующего ключа НЕ вытесняет никого: размер от неё не
   * растёт, и вытеснение было бы платой ни за что (прежняя редакция вытесняла
   * и в этом случае тоже).
   */
  put(key: string, value: V): V {
    if (this.map.has(key)) {
      this.map.set(key, value);
      return value;
    }
    if (this.map.size >= this.max) {
      // Приём НЕ ВСЕГДА — см. шапку модуля. Без этого кэш перемалывает сам
      // себя и на наборе вчетверо больше потолка даёт 2,3 % вместо 20 %.
      if (this.nextRandom() % ADMIT_ONE_OF !== 0) return value;
      this.evictRandom();
    }
    this.keys.push(key);
    this.map.set(key, value);
    return value;
  }

  clear(): void {
    this.map.clear();
    this.keys.length = 0;
  }

  /** xorshift32 — три сдвига, никакой библиотеки. Нужен ровно один разряд
   *  качества: независимость от порядка обхода набора. */
  private nextRandom(): number {
    let x = this.seed;
    x ^= x << 13; x >>>= 0;
    x ^= x >>> 17;
    x ^= x << 5;  x >>>= 0;
    this.seed = x || 1;
    return this.seed;
  }

  private evictRandom(): void {
    const i = this.nextRandom() % this.keys.length;
    const victim = this.keys[i];
    // Место жертвы занимает последний ключ — так массив не дырявится и не
    // требует сдвига. Отдельной карты «ключ → место» здесь НЕТ намеренно:
    // жертва выбирается по МЕСТУ, а не по имени, значит искать место по имени
    // не нужно ни разу. Такая карта в первой редакции была — и не читалась
    // ни разу, то есть стоила памяти и ничего не делала.
    const last = this.keys.pop() as string;
    if (i < this.keys.length) this.keys[i] = last;
    this.map.delete(victim);
  }
}
