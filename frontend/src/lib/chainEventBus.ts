/**
 * Раздатчик пачек логов с ОБЩЕГО фильтра цепи.
 *
 * ЗАЧЕМ. Фильтр на диамонде в приложении ровно один — его взводит
 * `hooks/useNotifications.ts`. Читателей у пачки два: разводка уведомлений и
 * слежение за сменой арбитра (`lib/disputeArbiter.ts`). Второй фильтр рядом
 * стоил бы ещё `60000 / такт` запросов в минуту с каждой открытой вкладки, а
 * бюджет уже выбран: `hooks/chainPollBudget.test.ts` держит потолок в два цикла
 * и восемь запросов в минуту, и стоит он там после замера с живого телефона —
 * 8 100 обращений в час с ОДНОЙ вкладки (`docs/OPEN-ITEMS.md`, пункт 38).
 *
 * Поэтому пачка не запрашивается второй раз, а РАЗДАЁТСЯ. Цена раздачи — ноль
 * обращений к цепи.
 *
 * ⚠️ ЧТО ЗДЕСЬ ЕДЕТ: пачка **сырых** логов, как её отдал viem, без разбора и без
 * отбора. Каждый читатель отбирает своё сам — разводка по `eventName` и адресу
 * кошелька, слежение по адресу сделки и адресу арбитра. Раздатчик ничего не
 * понимает про содержимое нарочно: понимающий раздатчик стал бы третьим местом,
 * где решают «моё / не моё», и разъехался бы с двумя первыми.
 *
 * ⚠️ ЧЕГО ЗДЕСЬ НЕТ: памяти. Пачка отдаётся тем, кто подписан В ЭТОТ МОМЕНТ, и
 * не хранится. Подписавшийся позже пропущенного не получит — и это не потеря:
 * догон делает владелец фильтра (`useNotifications` идёт с курсором в
 * `localStorage`), а добранные логи едут сюда же обычной пачкой.
 */

/** Получатель пачки. Тот же вид, что у `ChainWatchIO.watch` в `chainWatchGate`. */
export type ChainLogSink = (logs: unknown[]) => void;

const sinks = new Set<ChainLogSink>();

/**
 * Подписаться на пачки. Возвращает отписку.
 *
 * Зовёт: `arbiterChangeWatchIO` (`lib/disputeArbiter.ts`) — внутри `watch` своего
 * `ChainWatchIO`, то есть отписка приезжает в `runChainWatch` как снятие
 * слежения и срабатывает на сворачивание вкладки.
 */
export function subscribeChainLogs(sink: ChainLogSink): () => void {
  sinks.add(sink);
  return () => { sinks.delete(sink); };
}

/**
 * Раздать пачку всем подписанным.
 *
 * Зовёт: `handleChainLogs` (`hooks/useNotifications.ts`) — на КАЖДУЮ пачку, и
 * живую, и добранную догоном.
 *
 * ⚠️ ОТКАЗ ОДНОГО ПОЛУЧАТЕЛЯ НЕ ОТМЕНЯЕТ ОСТАЛЬНЫХ И НЕ РОНЯЕТ ЗВАВШЕГО.
 * Раздача идёт по копии набора: получатель вправе отписаться прямо в
 * обработчике (так делает `runChainWatch`, когда вкладку прячут), а изменение
 * набора во время обхода потеряло бы соседа. Бросок получателя гасится здесь —
 * иначе одна сломанная подписка утащила бы за собой уведомления, которые к ней
 * отношения не имеют.
 */
export function publishChainLogs(logs: unknown[]): void {
  if (!Array.isArray(logs) || logs.length === 0) return;
  for (const sink of [...sinks]) {
    try {
      sink(logs);
    } catch (error) {
      console.warn('[hexseal] получатель пачки логов бросил исключение:', error);
    }
  }
}

/** Сколько получателей подписано. Только для замеров — боевого читателя нет. */
export function chainLogSinkCount(): number {
  return sinks.size;
}
