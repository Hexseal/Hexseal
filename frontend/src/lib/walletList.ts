/**
 * walletList.ts — какие кошельки показывать, отдельно для мобильного и десктопа.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ
 *
 * RainbowKit 2.2.8 (единственное изменение того релиза) перевёл коннектор
 * MetaMask на MetaMask SDK. Сам SDK помечен апстримом как более не
 * поддерживаемый, версии с починкой не существует, а уйти с него совсем можно
 * только через wagmi 3.x — это отдельная работа, не эта.
 *
 * На Android/Chrome + приложение MetaMask этот путь ломается так:
 *   • SDK открывает диплинк в кошелёк, Android при этом спокойно выгружает
 *     фоновую вкладку (отличить выгрузку программно нельзя — `document
 *     .wasDiscarded` на Android не реализован);
 *   • origin у запроса подписи оказывается UUID'ом, а не доменом
 *     («already pending for origin 626e382b-…»), и запрос залипает в кошельке
 *     насовсем: отменить его MetaMask не умеет, помогает только полное
 *     закрытие приложения кошелька.
 * Заведено у апстрима: RainbowKit #2530, MetaMask Mobile #17112 и #33818.
 *
 * Починить это у себя нельзя — можно только не ходить туда. На мобильном
 * убираем MetaMask из списка: остаётся `walletConnectWallet`, то есть транспорт
 * WalletConnect мимо всего мёртвого SDK. MetaMask при этом никуда не девается —
 * он есть внутри самого WalletConnect-модала, просто добирается до него другой
 * дорогой. Плюс на мобильном остаётся `injectedWallet` — он ловит случай
 * «сайт открыт во встроенном браузере MetaMask», где провайдер инжектирован и
 * никакого диплинка вообще не происходит.
 *
 * ДЕСКТОП НЕ ТРОГАЕМ: там MetaMask инжектированный, диплинков нет, всё
 * работает — лишать его смысла нет.
 */

export type WalletGroup<W> = { groupName: string; wallets: W[] };

/** Мобильная ли это среда. Аргумент — `navigator.userAgent`; на сервере (SSR)
 *  его нет, и функция обязана вернуть false: конфиг wagmi собирается один раз
 *  на модуле, и «серверный» набор всё равно никогда не подключает кошелёк.
 *
 *  Проверяем UA, а не ширину экрана: значение имеет не размер окна, а то,
 *  уходит ли подключение диплинком в отдельное приложение кошелька. Узкое окно
 *  на десктопе — это по-прежнему инжектированный MetaMask, и ломать его нечем. */
export function isMobileUserAgent(ua: string | undefined | null): boolean {
  if (!ua) return false;
  return /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(ua);
}

/** Убирает из групп кошельки, которым нечего делать на мобильном, и выкидывает
 *  группы, опустевшие после этого. На десктопе возвращает исходные группы как
 *  есть — тем же объектом, без копирования.
 *
 *  Сравнение по ссылке (`includes`): элементы здесь — фабрики кошельков
 *  RainbowKit, то есть стабильные импортированные функции. */
export function buildWalletGroups<W>(
  groups: readonly WalletGroup<W>[],
  isMobile: boolean,
  excludedOnMobile: readonly W[],
): WalletGroup<W>[] {
  if (!isMobile) return groups.map(g => ({ ...g, wallets: [...g.wallets] }));
  return groups
    .map(g => ({ ...g, wallets: g.wallets.filter(w => !excludedOnMobile.includes(w)) }))
    .filter(g => g.wallets.length > 0);
}
