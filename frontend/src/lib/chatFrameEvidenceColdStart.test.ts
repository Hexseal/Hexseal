import { describe, it, expect } from 'vitest';
import { verifyFrameEvidence, type FrameVerdict } from './chatConversation';
import type { ChainLink } from './chatChain';

/**
 * ОДНО измерение, отдельным файлом — и это не прихоть, а условие честности.
 *
 * `chatFrameEvidence.test.ts` (T14) печатает «первый кадр (холодный модуль)»,
 * но врёт себе: `beforeEach` там зовёт `honestFrame()`, а та САМА делает
 * `await import('libsodium-wrappers')` + `await sodium.ready` (для подписи) —
 * и делает это по разу на КАЖДЫЙ из 1000 кадров, построенных ДО того, как T14
 * включает таймер. К моменту первого `judge()` модуль либо уже прогрет чужим
 * `import`, либо это внутри того же теста, но всё равно ДО таймера. Измерено:
 * T14 в изоляции (`npm test -- src/lib/chatFrameEvidence.test.ts -t T14`,
 * без единого другого теста в файле) печатает `0-1 мс` — то же самое число,
 * что и в общем прогоне. Настоящая цена первого вызова, снятая ЗДЕСЬ, где до
 * таймера ничего `libsodium-wrappers` не трогает, — около 12-16 мс за прогон
 * (см. `console.info` ниже за фактическим числом текущего прогона).
 *
 * Значит план (шаг 6: «первый кадр на холодном модуле — сказать вслух, если
 * дороже ста миллисекунд») T14 выполнить не может: там нечего мерить, число
 * уже подделано порядком вызовов внутри теста. Мерит эту цену — только этот
 * файл.
 *
 * ⚠️ ПОЧЕМУ ЭТОТ ФАЙЛ ДЕЙСТВИТЕЛЬНО ХОЛОДНЫЙ, А НЕ ТОЖЕ ВРЁТ:
 *  - ни один импорт наверху не тянет `libsodium-wrappers` — ни прямо, ни
 *    транзитивно (`chatConversation.ts` грузит её ЛЕНИВО, внутри
 *    `frameVerifier()`, а не на уровне модуля — иначе `import` этого файла
 *    уже заплатил бы цену за нас);
 *  - vitest изолирует граф модулей ПО ФАЙЛУ (не по тесту, но и не по всему
 *    прогону) — при `pool: 'threads', isolate: true` (умолчание, в
 *    `vitest.config.mjs` не переопределено) каждый тестовый файл получает
 *    свежий реестр `import`, поэтому предыдущие файлы `libsodium-wrappers` за
 *    нас не грели;
 *  - байты кадра здесь МУСОР, и это осознанный выбор, а не небрежность:
 *    `verifyFrameEvidence` ждёт готовности верификатора ПЕРВОЙ строкой,
 *    ДО разбора кадра (`chatConversation.ts:718-722` на момент написания) —
 *    цена загрузки библиотеки платится независимо от того, честный кадр или
 *    мусор. Настоящего кадра (значит и `honestFrame()`, значит и лишнего
 *    `import`) для этого измерения просто не нужно.
 */
describe('холодный старт verifyFrameEvidence — БЕЗ прогрева чужим кодом', () => {
  it('T-COLD: первый вызов в процессе, где библиотеку ещё никто не трогал', async () => {
    const junkLink: ChainLink = {
      seq: 0,
      prevHash: `0x${'00'.repeat(32)}` as `0x${string}`,
      bodyHash: `0x${'00'.repeat(32)}` as `0x${string}`,
      sender: `0x${'00'.repeat(20)}` as `0x${string}`,
      sentAt: 0,
    };
    const junkBytes = new Uint8Array(300).fill(0xab);

    const started = Date.now();
    const verdict: FrameVerdict = await verifyFrameEvidence(junkBytes, junkLink, junkBytes, junkBytes);
    const coldMs = Date.now() - started;

    console.info(`[замер] verifyFrameEvidence: НАСТОЯЩИЙ холодный первый вызов (ничего до таймера `
      + `библиотеку не грело) ${coldMs} мс`);

    // Мусорные байты — malformed, как и должно быть; это не про вердикт,
    // а про то, что мы всё-таки прошли через ожидание готовности верификатора.
    expect(verdict).toEqual({ ok: false, reason: 'malformed' });

    // ⚠️ Потолок — 200 мс. Не 2 секунды и не микросекунды: щедрый настолько,
    // чтобы не мигать от шума прогона (реальная цена сегодня — единицы-
    // десятки мс, замерено этим же тестом много раз подряд, разброс 12-16 мс),
    // но достаточно тесный, чтобы поймать РЕАЛЬНУЮ будущую просадку — например,
    // ту самую «300 мс от смены сборщика», которую называла постановка задачи
    // как пример регрессии, обязанной покраснеть. Что этот потолок умеет
    // краснеть — доказано отдельно, не верой: искусственная задержка ~300 мс
    // перед `await import('libsodium-wrappers')` внутри `frameVerifier()`
    // (chatConversation.ts) даёт `coldMs` ≈ 300+ мс и красный `expect` —
    // проверено во время правки, число приведено в `task-4-report.md`,
    // раздел «Задача 4в-1».
    expect(coldMs).toBeLessThan(200);
  });
});
