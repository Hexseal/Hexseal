/**
 * chatListPhase.ts — что показывает колонка списка, одним решением.
 *
 * ─── ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ ─────────────────────────────────────────────────
 *
 * В разметке `app/chat/page.tsx` жило ШЕСТЬ независимых условий: заготовки
 * строк, ожидание подписи, «ключ не объявлен», отказ склада, «мессенджер
 * выключен», «переписок нет». Каждое читало свой набор признаков, и они
 * пересекались — заготовки рисовались ПОВЕРХ строк, отказ убирал строки совсем.
 * Замер до правки: скелетон показан 10 раз из 10 тиков при непустом списке,
 * строки исчезали с экрана от одного `rate_limited`.
 *
 * Шесть условий, каждое со своим набором признаков, нельзя проверить: их
 * сочетаний 2⁶. Одно решение с семью исходами — можно, и оно здесь.
 *
 * ─── ГЛАВНОЕ ПРАВИЛО ────────────────────────────────────────────────────────
 *
 *   > Заготовки строк, пустое состояние и экраны отказа — ТОЛЬКО когда
 *   > показывать нечего. Есть что показать — показываем это, а новость об
 *   > отказе идёт строкой рядом, не вместо.
 *
 * Иначе получается то самое мигание, на которое невозможно смотреть: список
 * есть, потом его нет, потом он снова есть.
 *
 * ─── И ВТОРОЕ ПРАВИЛО, ОПЛАЧЕННОЕ ОТДЕЛЬНО (9 августа) ──────────────────────
 *
 *   > Пустой список и НЕСПРОШЕННЫЙ склад — разные состояния, и слова у них
 *   > разные. «Переписок пока нет» — это УТВЕРЖДЕНИЕ, и произносить его можно
 *   > только после ответа склада.
 *
 * Их было слито два в одно, и человек двенадцать секунд читал утверждение о
 * пустоте, пока список ехал. Разбор дороги — у поля `everAnswered`.
 */

/** Чего именно ждёт окно кошелька — у причин разные слова. */
export type SignatureReason = 'pass' | 'key' | null;

export interface ListPhaseInput {
  /** Есть ли ХОТЬ ОДНА строка, которую можно показать прямо сейчас: мешки плюс
   *  собеседники по сделкам из цепи. ⚠️ Не «мешки»: строки из цепи рисуются
   *  наравне, и считать их «нечем показать» — та самая ошибка, из-за которой
   *  заготовки лезли поверх настоящих строк. */
  hasRows: boolean;
  /**
   * Склад отвечал ХОТЬ РАЗ за жизнь вкладки — строками или отказом.
   *
   * ⚠️ ЗДЕСЬ РАНЬШЕ СТОЯЛ `loading` («заход в полёте прямо сейчас»), И ЭТО БЫЛ
   * ДРУГОЙ ВОПРОС. Заход снимается в `finally` даже тогда, когда он не
   * состоялся вовсе — порог подписи отложил его молча
   * (`ChatSignatureDeferred`), — и колонка честно докладывала «Переписок пока
   * нет» про склад, которого никто не спрашивал. Живой замер: двенадцать секунд
   * этих слов на телефоне, после которых человек уходит.
   *
   * ⚠️ И ОБРАТНО `loading` ВЕРНУТЬ НЕЛЬЗЯ, даже «в дополнение». Он поднимается
   * на КАЖДОМ заходе при пустых строках (`listStarted`), то есть заготовки
   * мелькали бы каждые тридцать секунд у любого, у кого переписок нет: замер до
   * правки — 11 вспышек за десять тиков. Владелец про это: на такие прыжки
   * невозможно смотреть.
   *
   * Признак ОДНОНАПРАВЛЕННЫЙ (false → true, обратно никогда в пределах адреса и
   * вкладки) — поэтому «признак загрузки покажется не больше одного раза» есть
   * свойство построения, а не наша аккуратность.
   */
  everAnswered: boolean;
  /** Окно кошелька открыто прямо сейчас. */
  signatureReason: SignatureReason;
  /** Наш ключ не объявлен, и лечится это нажатием. */
  keyNotAnnounced: boolean;
  /** Сеанс чата: 'loading' — заводится, 'error' — не открылся, 'ready' — есть. */
  sessionStatus: 'loading' | 'ready' | 'error';
  /** Код отказа последнего захода за списком. */
  error: string | null;
}

export type ListPhase =
  /** Ждём человека у окна кошелька. */
  | 'signature'
  /** «Вам пока не могут писать» + кнопка. */
  | 'announce'
  /** Заготовки строк: склада ещё не спрашивали (либо ответа не было), и показать
   *  пока нечего. */
  | 'skeleton'
  /** Чат выключен или сеанс не открылся. */
  | 'off'
  /** Склад отказал, и показать нечего. */
  | 'error'
  /** Всё в порядке, переписок просто нет. */
  | 'empty'
  /** Строки. Единственный исход, при котором список виден. */
  | 'rows';

/**
 * Единственное решение.
 *
 * ⚠️ ПЕРВАЯ ПРОВЕРКА — САМАЯ ВАЖНАЯ, и она про строки. Любой экран вместо
 * непустого списка — это разрушение того, что человек уже видел; ни одна из
 * причин ниже того не стоит. Новость об отказе при непустом списке доносит
 * `listStaleNotice`, отдельной строкой.
 */
export function listPhase(i: ListPhaseInput): ListPhase {
  if (i.hasRows) return 'rows';
  if (i.signatureReason) return 'signature';
  if (i.keyNotAnnounced) return 'announce';
  // ⚠️ ОТКАЗ ПРОВЕРЯЕТСЯ РАНЬШЕ ЗАГОТОВОК, и это не косметика. Отказ — ЭТО
  // ОТВЕТ склада, и повторная попытка не имеет права прятать его за
  // пульсирующими полосками: заготовки говорят «сейчас будет», а человек уже
  // знает, что не будет, и ждёт от нас кнопки. Замер до правки: экран отказа
  // накрыт заготовками, пока идёт повтор.
  if (i.error) return 'error';
  // Сеанс не открылся — тоже ответ, только про ключ. Иначе «ещё не спрашивали»
  // (ниже) держало бы заготовки навсегда там, где спрашивать вообще нечем.
  if (i.sessionStatus === 'error') return 'off';
  // Заготовки — только пока ЖДУТ СЕТЬ и ответа не было НИ ОДНОГО. Ждут человека
  // (две ветки выше) — заготовки врут: они говорят «сейчас будет», а сами по
  // себе они не будет.
  if (!i.everAnswered || i.sessionStatus === 'loading') return 'skeleton';
  // Единственное место, где можно УТВЕРЖДАТЬ, что переписок нет: склад спрошен и
  // ответил «ничего».
  return 'empty';
}

/**
 * Что сказать РЯДОМ со строками — узкой полосой над списком.
 *
 * ⚠️ ОТДЕЛЬНОЕ РЕШЕНИЕ, А НЕ ПОЛЕ ИСХОДА. Исход отвечает «что ВМЕСТО списка»,
 * это — «что ВМЕСТЕ со списком». Свести их значило бы снова получить экран
 * вместо переписок; развести — значит не потерять новость.
 *
 * ⚠️ И ЭТО НЕ УКРАШЕНИЕ. «Ключ не объявлен» раньше показывалось только при
 * пустом списке — то есть человеку, у которого есть хоть одна строка (например,
 * собеседник по сделке из цепи), кнопки не доставалось ВОВСЕ. А состояние у него
 * ровно то же: писать ему не может никто.
 *
 * Полоса не мигает по построению: ни один из трёх признаков не меняется от
 * фонового тика — окно кошелька, стояние ключа и код отказа живут дольше захода.
 */
export type ListNotice = 'signature' | 'announce' | 'stale' | null;

export function listNotice(i: ListPhaseInput): ListNotice {
  // Пустой список говорит о себе сам, целым экраном (`listPhase`). Полоса
  // поверх этого экрана была бы вторым сообщением об одном.
  if (!i.hasRows) return null;
  if (i.signatureReason) return 'signature';
  if (i.keyNotAnnounced) return 'announce';
  if (i.error) return 'stale';
  return null;
}
