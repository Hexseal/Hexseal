'use client';

import { useEffect, useRef } from 'react';

/**
 * След в журнале для ОТДЕЛЬНЫХ провалившихся вызовов внутри `useReadContracts`.
 *
 * ЗАЧЕМ. У wagmi `allowFailure` по умолчанию `true`: пакетное чтение считается
 * успешным целиком, даже если часть вызовов внутри него ревертнула — такие
 * приходят как `{ status: 'failure', result: undefined }`. Списки в
 * `components/MyListings.tsx` отбрасывают их обычным `.filter(x => !!x.svc)`,
 * а флаг `isError` рядом отражает только провал ЗАПРОСА целиком и в этом случае
 * остаётся ложным. Итог: сущность, которая не читается, неотличима от
 * несуществующей — «услуг вы ещё не публиковали» вместо «услугу не удалось
 * прочитать».
 *
 * Почему это не теоретическая придирка: ровно так этот проект уже ломался.
 * Апгрейд `termsHash` → `terms` сменил тип поля в занятом слоте, и
 * `getOpenJobs()` начал ревертить `Panic(0x22)` на живой Base Sepolia. Разбор —
 * `docs/CONTRACT_GUIDE.md` и `script/check-storage-structs.sh`, который с тех
 * пор этот класс на стороне контрактов и сторожит. На стороне фронта такой
 * реверт по-прежнему выглядит как пустой список: у листинга есть внесённая
 * комиссия и живой эскроу, а человеку показывают, что он ничего не публиковал.
 *
 * ЧТО ЭТО МЕНЯЕТ, А ЧТО НЕТ. Только журнал. Отрисовка не тронута: список
 * по-прежнему показывает то, что прочиталось. Показывать ли человеку разницу
 * между «пусто» и «не прочиталось» и что именно рисовать в этом случае —
 * продуктовое решение, оно вынесено отдельно.
 */
export function useWarnFailedReads(
  results: readonly { status: 'success' | 'failure' }[] | undefined,
  label: string,
): void {
  // Ключ последнего уже записанного набора провалов: без него запись
  // повторялась бы на каждом перерендере (а их у списков много — раскрытие
  // строк, тики таймеров, обновления по шине).
  const lastRef = useRef<string>('');

  useEffect(() => {
    if (!results) return;
    const failed: number[] = [];
    results.forEach((r, i) => { if (r.status === 'failure') failed.push(i); });
    const key = failed.join(',');
    if (key === lastRef.current) return;
    lastRef.current = key;
    if (failed.length === 0) return;
    console.warn(
      `[${label}] ${failed.length} из ${results.length} чтений не удались ` +
      `(индексы ${key}) — эти строки молча выпали из списка, и на экране это ` +
      `неотличимо от «их нет».`,
    );
  }, [results, label]);
}
