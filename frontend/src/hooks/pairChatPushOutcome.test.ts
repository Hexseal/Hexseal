/**
 * pairChatPushOutcome.test.ts — исход уведомления не выбрасывается молча.
 *
 * ОБСТАНОВКА. Уведомления теперь требуют пропуск склада: человек БЕЗ
 * заведённого сеанса чата отправить уведомление не может, и `notifyPush`
 * возвращает `no-pass`, не делая запроса вовсе. Оба пути отправки в
 * `usePairChat.ts` этот исход ВЫБРАСЫВАЛИ — сообщение уходило, собеседнику о
 * нём не сообщали, отправитель не узнавал ничего.
 *
 * ⚠️ ЧТО ЭТОТ ЗАМОК ПРОВЕРЯЕТ, А ЧТО НЕТ — СКАЗАНО ПРЯМО.
 *
 * Он НЕ проверяет, что исход доезжает до состояния: сама обвязка живёт в
 * React-хуке, а отрисовать хук в этом окружении нечем (ни jsdom, ни
 * @testing-library — разбор в шапке `usePairChat.ts`). Обвязка поэтому сведена
 * к трём строкам, и это осознанный размен, а не недосмотр.
 *
 * Он проверяет ДРУГОЕ и ровно то, что тут ломалось: что мест вызова ОДНО.
 * Путей отправки два (текст и вложение), и станет больше. Ровно на этом
 * однажды потерялась метка сделки: комментарий обещал, что она ставится, а
 * новый путь про неё не знал, и весь аппарат её проверки оказался мёртвым.
 * Второй вызов `notifyPush` в обход обёртки — это тот же класс, и он краснеет
 * здесь.
 *
 * Разбор по исходному тексту, а не по поведению — тот же приём и та же
 * причина, что у `noXmtpImports.test.ts`.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = readFileSync(
  fileURLToPath(new URL('./usePairChat.ts', import.meta.url)),
  'utf8',
);

/** Строки кода без комментариев: обещание в комментарии — не вызов. */
function codeLines(src: string): string[] {
  return src
    .split('\n')
    .filter(l => !/^\s*(\/\/|\*|\/\*)/.test(l));
}

describe('уведомление собеседнику: исход не теряется', () => {
  it('вызов notifyPush в хуке РОВНО ОДИН — обёртка', () => {
    // Что красит: новый путь отправки, зовущий `notifyPush` напрямую. Именно
    // так теряется исход — не в существующем коде, а в следующем.
    const calls = codeLines(SOURCE).filter(l => /\bnotifyPush\s*\(/.test(l));
    expect(calls, `вызовов notifyPush: ${calls.length}\n${calls.join('\n')}`).toHaveLength(1);
  });

  it('исход этого вызова КУДА-ТО девается, а не выбрасывается', () => {
    // Что красит: возврат к `notifyPush(...)` голым выражением. Тогда строка
    // не содержит ни `.then`, ни `await`, ни присваивания — то есть промис
    // висит, а исход не читает никто.
    const [call] = codeLines(SOURCE).filter(l => /\bnotifyPush\s*\(/.test(l));
    const tail = SOURCE.slice(SOURCE.indexOf(call), SOURCE.indexOf(call) + 400);
    expect(tail).toMatch(/\.then\(|await\s+notifyPush|=\s*await/);
  });

  it('обёртка зовётся ОБОИМИ путями отправки — текстом и вложением', () => {
    // Что красит: снятие вызова с одного из путей. Отправив файл, человек не
    // узнал бы, что уведомление не ушло, — а отправив текст, узнал бы.
    const uses = codeLines(SOURCE).filter(l => /\bnotifyPeer\s*\(\s*\)/.test(l));
    expect(uses.length).toBeGreaterThanOrEqual(2);
  });

  it('исход выдаётся наружу хука, а не остаётся внутри', () => {
    // Что красит: убрать `pushOutcome` из возвращаемого объекта. Панель тогда
    // физически не может ничего показать, сколько бы хук ни считал.
    expect(SOURCE).toMatch(/^\s*pushOutcome,\s*$/m);
  });
});
