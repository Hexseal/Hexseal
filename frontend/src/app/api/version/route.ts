import { NextResponse } from 'next/server';

/**
 * GET /api/version — какая версия сайта выкачена ПРЯМО СЕЙЧАС.
 *
 * ⚠️ ЗАЧЕМ. В манифесте `launch_handler: focus-existing`: открытие ярлыка
 * возвращает существующее окно, а не перезагружает страницу; куски кода с хешем в
 * имени живут вечно. Значит установленное приложение, открытое до выкатки, крутит
 * прежний код сколько угодно — 8 августа это стоило нам часов, потому что правки
 * были выкачены, а телефон работал по-старому и выглядел как непочиненный.
 *
 * ⚠️ НОМЕР ЗДЕСЬ И НОМЕР В СТРАНИЦЕ — ОДНА И ТА ЖЕ ВКОМПИЛИРОВАННАЯ СТРОКА.
 * `NEXT_PUBLIC_BUILD_ID` подставляется В КОД на сборке (`next.config.ts`, поле
 * `env`), поэтому перезапуск сервера её не меняет. Это не мелочь: считай номер
 * здесь заново (`Date.now()`, случайное значение, что угодно) — и он разошёлся бы
 * с номером страницы у ВСЕХ, а страница, увидев разницу, пошла бы
 * перезагружаться. Получилось бы не «работает старый код», а «не работает
 * ничего». Разбор и вторая защита от петли — `lib/appVersion.ts`.
 *
 * Ответ обязан миновать любой кэш: спросив через кэш, страница получила бы тот же
 * старый номер, что и старый код, и починка не сработала бы никогда.
 */
export async function GET() {
  return NextResponse.json(
    { buildId: process.env.NEXT_PUBLIC_BUILD_ID ?? '' },
    {
      headers: {
        'Cache-Control': 'no-store, must-revalidate',
        // Cloudflare слушает и это, независимо от правил в панели.
        'CDN-Cache-Control': 'no-store',
      },
    },
  );
}
