import { describe, it, expect } from 'vitest';
import { usdcExact as relayerUsdcExact } from '../app.js';
// Расширение `.ts` в импорте — намеренно и обязательно: релеер это обычный ESM
// без резолвинга TypeScript, и `.js` здесь не найдёт ничего. Транспиляцию берёт
// на себя vitest (esbuild), ему указывают реальный файл.
import { usdcExact as frontendUsdcExact } from '../../frontend/src/lib/splitPot.ts';

/**
 * ОДНА ФУНКЦИЯ, ДВЕ КОПИИ, ДВА ЯЗЫКА
 *
 * `usdcExact` печатает пользователю сумму, которую контракт УЖЕ заплатил, и
 * существует дважды:
 *
 *  • `relayer/app.js` — в теле OS-пуша (`disputeSplitPushMsg`), на ethers v6;
 *  • `frontend/src/lib/splitPot.ts` — в ленте уведомлений и в баннере сделки,
 *    на viem.
 *
 * Обе стороны говорят про ОДНУ выплату и стоят рядом: пуш приходит в трей,
 * лента открывается в том же телефоне. Разойдясь, они предъявят пользователю
 * два разных числа за одну и ту же транзакцию — и это худшая форма расхождения,
 * потому что доверия не остаётся ни к одному из них.
 *
 * Свести копии в одну нельзя дёшево: релеер — обычный ESM на ethers и не
 * собирается, а `splitPot.ts` тянет viem; общий модуль означал бы либо ethers во
 * фронте, либо сборку в релеере. Пока их две, единственная защита — проверять,
 * что они СОГЛАСНЫ, а не что каждая по отдельности «выглядит правильно».
 *
 * Расходятся они не в надуманных местах. `ethers.formatUnits(1000000n, 6)`
 * отдаёт "1.0", `viem.formatUnits` — "1": разное число знаков ДО дополнения, и
 * совпадение итога держится ровно на `padEnd(2, '0')` в обеих. Уберут его с
 * одной стороны — увидит этот тест, а не пользователь.
 *
 * ГДЕ ОН ЛЕЖИТ И ПОЧЕМУ ЗДЕСЬ. Импортировать надо в ту сторону, где дешевле
 * загрузка: `splitPot.ts` — чистый модуль на две функции без единого побочного
 * эффекта, а `relayer/app.js` при импорте поднимает express-приложение,
 * ethers-провайдер и расписания, и без `test/setup.js` (моки ethers/web-push,
 * переменные окружения) не грузится вовсе. Тянуть релеер в конфиг фронта
 * значило бы повторить там весь этот setup; тянуть `splitPot.ts` сюда — один
 * `import`.
 */

/**
 * Значения, на которых копии обязаны совпасть. Каждое — не «ещё одно число», а
 * отдельный способ разойтись.
 */
const VALUES = [
  0n,                          // ноль: ethers печатает "0.0", viem — "0"
  1n,                          // пыль: один юнит, 0.000001 USDC
  16n,                         // половина нечётного котла в 33 юнита
  17n,                         // и вторая его половина — строки обязаны быть РАЗНЫЕ
  100_000n,                    // 0.1 — дробь короче двух знаков
  1_000_000n,                  // ровно 1: ethers "1.0" против viem "1"
  1_500_000n,                  // 1.5 — один знак после запятой у обеих
  25_000_001n,                 // шесть знаков, последний значащий
  200_000_000n,                // круглые 200 USDC
  200_000_001n,                // они же плюс юнит
  123_456_789_012_345n,        // крупное: 123456789.012345
  999_999_999_999_999_999n,    // заведомо больше Number.MAX_SAFE_INTEGER
];

describe('usdcExact — две копии на разных языках печатают одно и то же', () => {
  for (const value of VALUES) {
    it(`${value} юнитов: релеер и фронт сходятся`, () => {
      const fromRelayer = relayerUsdcExact(value);
      const fromFrontend = frontendUsdcExact(value);
      expect(fromRelayer).toBe(fromFrontend);
      // И ни одна из них не сорвалась в экспоненту или в пустую дробь: у обеих
      // должна быть точка и минимум два знака после неё.
      expect(fromRelayer).toMatch(/^\d+\.\d{2,}$/);
    });
  }

  // Пример из живого дележа, где округление до двух знаков соврало бы обеим
  // сторонам сразу: 33 юнита делятся 16/17, и `.toFixed(2)` дал бы «0.00» и там,
  // и там. Строки обязаны отличаться — в обеих копиях одинаково.
  it('половины нечётного котла остаются различимыми у обеих копий', () => {
    expect(relayerUsdcExact(16n)).not.toBe(relayerUsdcExact(17n));
    expect(frontendUsdcExact(16n)).not.toBe(frontendUsdcExact(17n));
    expect(relayerUsdcExact(16n)).toBe(frontendUsdcExact(16n));
    expect(relayerUsdcExact(17n)).toBe(frontendUsdcExact(17n));
  });

  // Значения ниже — те, что уже проверены поимённо в disputeSplitPush.test.js и
  // splitPot.test.ts. Здесь они закрепляют, что СОВПАДЕНИЕ достигнуто на
  // правильном ответе, а не на одинаковой ошибке в обеих копиях.
  it('совпадают на заведомо верном ответе, а не на общей ошибке', () => {
    expect(relayerUsdcExact(200_000_000n)).toBe('200.00');
    expect(frontendUsdcExact(200_000_000n)).toBe('200.00');
    expect(relayerUsdcExact(17n)).toBe('0.000017');
    expect(frontendUsdcExact(17n)).toBe('0.000017');
  });
});
