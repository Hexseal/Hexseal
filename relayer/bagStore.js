function assertPositiveFiniteNumber(name, value) {
  if (!Number.isFinite(value) || value <= 0) {
    fail('assertBagStoreReady', `${name}=${JSON.stringify(process.env[name])} is not a positive finite number (parsed as ${value})`);
  }
}

// CLOCK_SKEW_ALLOWANCE_MS=0 — легитимное значение (запрет любого будущего
// вообще, без допуска), в отличие от четырёх TTL/размера выше, для которых
// 0 всегда бессмысленен (мешок с нулевым сроком жизни/нулевым потолком
// размера — не настройка, а фактическое выключение функции). Тот же
// diagnostic-message стиль, отдельная функция вместо <= 0 → < 0.
function assertNonNegativeFiniteNumber(name, value) {
  if (!Number.isFinite(value) || value < 0) {
    fail('assertBagStoreReady', `${name}=${JSON.stringify(process.env[name])} is not a non-negative finite number (parsed as ${value})`);
  }
}

// Call once at boot, after dotenv has run (Задача 3's job) — same reason as
// assertBagPassReady() in bagPass.js. Refreshes config from process.env
// FIRST (И-3, пятый раунд) — so a value that only became correct after
// dotenv.config() ran in app.js's body is picked up here, not stuck at
// whatever process.env happened to hold when this module was first
// imported. Only after that does it validate: a garbage value would
// otherwise silently become NaN/Infinity/0 and every check downstream that
// compares against it (bagExpiryAt, recordBag's size ceiling) goes quietly
// wrong — NaN <= now is always false, so nothing ever expires; 'big' → NaN
// → 50MB "meshki" sail straight through the size ceiling.
//
// Also creates DIR_BAGS (moved here from module scope, for the same
// ordering reason plus one more: a plain import of this module — e.g. from
// a test — should never have the side effect of creating a directory on
// disk before anything has decided the store is actually going to be used).
export function assertBagStoreReady() {
  // C1 (шестой раунд): _loadBagMeta() зовётся на уровне модуля — то есть ДО
  // dotenv.config() — из "импортного" STORAGE_DIR. _refreshConfig() ниже
  // переставляет BAG_META_PATH на боевой корень, но сама по себе НЕ
  // перечитывает индекс оттуда — без этой проверки в памяти оставалось бы
  // то, что было загружено (обычно пусто) из старого пути, и первая же
  // запись сохранила бы этот почти-пустой in-memory индекс ПОВЕРХ настоящего
  // боевого файла, стирая реальные переписки. Перечитываем ТОЛЬКО если путь
  // реально изменился — иначе повторный вызов assertBagStoreReady() с тем
  // же STORAGE_DIR не по делу перечитывал бы диск и рисковал бы затереть
  // память, если бы (гипотетически) на диске лежало что-то более старое,
  // чем уже накопленное в этом процессе состояние.
  const previousBagMetaPath = BAG_META_PATH;
  _refreshConfig();
  if (BAG_META_PATH !== previousBagMetaPath) {
    _loadBagMeta();
  }
  assertPositiveFiniteNumber('BAG_TTL_MS', BAG_TTL_MS);
  assertPositiveFiniteNumber('BAG_UNREAD_TTL_MS', BAG_UNREAD_TTL_MS);
  assertPositiveFiniteNumber('BAG_MAX_AGE_MS', BAG_MAX_AGE_MS);
  assertPositiveFiniteNumber('MAX_BAG_SIZE', MAX_BAG_SIZE);
  assertNonNegativeFiniteNumber('CLOCK_SKEW_ALLOWANCE_MS', CLOCK_SKEW_ALLOWANCE_MS);
  // Задача 5: BAG_ADOPTION_LOOKBACK_MS больше не проверяется здесь — ручка
  // убрана (И-2, пятый закрывающий раунд, см. докстринг у бывшего
  // объявления выше). Буфер (GRACE), наоборот, 0 — легитимная настройка
  // ("без буфера"), не "выключено". APPEAL_REVIEW_WINDOW_DAYS/
  // FINALIZE_DELAY_HOURS здесь не валидируются — они плоские `const` (И3),
  // process.env не читают вообще, значения не от пользователя, а от
  // исходника, который проверяет гейт script/check-appeal-window.sh на
  // этапе CI, не рантайм.
  assertNonNegativeFiniteNumber('BAG_DEAL_GRACE_MS', BAG_DEAL_GRACE_MS);
  _warnIfBagMaxAgeTooSmallForAppeal();
  fs.mkdirSync(DIR_BAGS, { recursive: true });
}

// I-D (третий закрывающий раунд ревью, находка координатора): BAG_MAX_AGE_MS
// режет УЖЕ УСЫНОВЛЁННЫЙ срок — ceiling в bagExpiryAt() ниже это
// `uploadedAt + BAG_MAX_AGE_MS`, и ничто не мешает ему оказаться МЕНЬШЕ,
// чем реально нужно, чтобы дожить до конца апелляции. Замер координатора:
// 60 дней превращались в 25 при BAG_MAX_AGE_MS=6д. Тот же класс дыры, ради
// которой закрыли env-переопределение APPEAL_REVIEW_WINDOW_DAYS/
// FINALIZE_DELAY_HOURS (I3), но через ЗАКОННУЮ ручку: assertPositiveFiniteNumber
// выше пропускает её, смотрит только "положительное конечное число", гейт
// её не видит (не копия константы контракта, обычный env-таймаут), в лог
// ничего не идёт.
//
// Дёшево: предупреждаем при старте, НЕ бросаем — маленький BAG_MAX_AGE_MS
// может быть намеренным выбором на тестовом окружении (или сознательным
// решением "мы принимаем этот риск"), это не повод ронять процесс, только
// повод узнать об этом заранее, а не молча терять доказательства позже.
//
// DISPUTE_WINDOW НЕ входит в расчёт точно — читается с цепи для каждого
// агримента отдельно (может отличаться между клонами реализации), при
// старте процесса недоступен без RPC-вызова, а стартовая проверка не
// должна зависеть от доступности сети. Консервативная ОЦЕНКА — тот же
// порядок величины, что APPEAL_REVIEW_WINDOW_DAYS: комментарий в самом
// контракте прямым текстом говорит "APPEAL_REVIEW_WINDOW = 4 days —
// столько же, сколько DISPUTE_WINDOW даёт арбитру" (ArbiterRegistryFacet.sol:147).
// Это ОЦЕНКА, не точный расчёт — если реальный DISPUTE_WINDOW когда-нибудь
// разойдётся с этим предположением, порог предупреждения будет неточным
// (в любую сторону), но само предупреждение остаётся честной приблизительной
// проверкой, а не тихим нулём.
function _warnIfBagMaxAgeTooSmallForAppeal() {
  const estimatedDisputeWindowMs = APPEAL_REVIEW_WINDOW_DAYS * DAY_MS; // оценка, см. докстринг выше
  const minimumForAppealMs = estimatedDisputeWindowMs + FINALIZE_DELAY_MS
    + APPEAL_REVIEW_WINDOW_DAYS * DAY_MS + BAG_DEAL_GRACE_MS;
  if (BAG_MAX_AGE_MS < minimumForAppealMs) {
    console.warn(
      `[bags] BAG_MAX_AGE_MS=${BAG_MAX_AGE_MS}мс (~${(BAG_MAX_AGE_MS / DAY_MS).toFixed(1)}д) меньше оценочного ` +
      `минимума ~${minimumForAppealMs}мс (~${(minimumForAppealMs / DAY_MS).toFixed(1)}д: окно спора (оценка) + ` +
      `окно финализации + окно апелляции + запас) — усыновлённый мешок физически не может дожить до конца ` +
      `апелляции спора, потолок BAG_MAX_AGE_MS обрежет срок раньше. Если это осознанный выбор — можно ` +
      `игнорировать; если нет — увеличь BAG_MAX_AGE_MS.`
    );
  }
}

// Форма адреса — та же проверка, что ETH_ADDR_RE в bagPass.js: нижний
// регистр, затем строгий /^0x[0-9a-f]{40}$/. Не проверяет чек-сумму EIP-55 —
// это не подтверждение владения ключом (то делает подпись/пропуск на слое
// выше), а просто защита от мусора в поле.
function assertAddress(fn, value) {
  const addr = typeof value === 'string' ? value.toLowerCase() : null;
  if (!addr || !ETH_ADDR_RE.test(addr)) fail(fn, `invalid address: ${JSON.stringify(value)}`);
  return addr;
}

// Задача 5: не lower-casing — pairId — уже-построенный опаковый идентификатор
// (выход _pairIdFromAddresses()/app.js:pairIdFromAddresses()), не сырой
// адрес; в отличие от assertAddress() выше, здесь нет "приведи и прими" —
// неверный регистр отвергается как есть, тем же принципом, что и BAG_KEY_RE
// (форма, произведённая самим кодом, а не то, что можно нормализовать).
function assertPairId(fn, value) {
  if (typeof value !== 'string' || !PAIR_ID_RE.test(value)) {
    fail(fn, `invalid pairId: ${JSON.stringify(value)}`);
  }
  return value;
}

// Number.isSafeInteger, не Number.isInteger — тот же класс бага, что в
// issueBagPass (Задача 1): Number.isInteger(1e21) === true, а
// '1000' + 5 склеивается в строку вместо сложения. isSafeInteger отсекает и
// строки (не число вовсе), и дробные, и огромные значения разом.
function assertSafeInt(fn, label, value) {
  if (!Number.isSafeInteger(value)) fail(fn, `invalid ${label}: ${JSON.stringify(value)}`);
  return value;
}

// Мелочь (координатор, пятый закрывающий раунд ревью): дедлайны/окна,
// приезжающие с цепи (Agreement.getDetails().deadlineDays_ и т.п.) —
// протокольно uint256, отрицательными на настоящем ABI-декодировании быть
// не могут, но этот модуль не полагается на "не может быть" молчаливо —
// тот же принцип, что у остальных assert*-хелперов файла: любое значение,
// пришедшее снаружи (в т.ч. через несовместимый/поддельный клон на другом
// конце staticcall), проверяется явно, а не доверяется по умолчанию.
// Отрицательная "продолжительность" молча УКОРАЧИВАЕТ формулу (складывается
// со знаком минус) — координатор нашёл именно это: отрицательный
// deadlineDays_ давал укороченный срок без единой строки в логе. assertSafeInt
// уже пропускает отрицательные числа (валидные safe integers), так что
// требование "не отрицательное" — отдельная, более узкая проверка.
function assertNonNegativeSafeInt(fn, label, value) {
  assertSafeInt(fn, label, value);
  if (value < 0) fail(fn, `${label} is negative: ${JSON.stringify(value)} — malformed chain data, not a legitimately shortened deadline`);
  return value;
}

// null/undefined — легитимное "ещё не наступило" (мешок не прочитан / не
// усыновлён сделкой). Всё остальное обязано быть тем же safe integer, что и
// обязательные временные поля.
function assertNullableSafeInt(fn, label, value) {
  if (value === null || value === undefined) return null;
  return assertSafeInt(fn, label, value);
}

function assertNonEmptyString(fn, label, value) {
  if (typeof value !== 'string' || value.length === 0) fail(fn, `invalid ${label}: ${JSON.stringify(value)}`);
  return value;
}

// Мелочь (b): firstFetchedAt на сто дней раньше uploadedAt даёт срок
// смерти раньше рождения — правило 2 (firstFetchedAt + BAG_TTL_MS) может
// оказаться меньше момента, когда мешок вообще появился, и мешок сносится
// в тот же миг, в который был загружен. Прочитано не раньше загрузки — не
// строгое неравенство: firstFetchedAt === uploadedAt (прочитан в ту же
// миллисекунду) годен.
function assertFetchNotBeforeUpload(fn, uploadedAt, firstFetchedAt) {
  if (firstFetchedAt != null && firstFetchedAt < uploadedAt) {
    fail(fn, `firstFetchedAt (${firstFetchedAt}) is before uploadedAt (${uploadedAt})`);
  }
}

// И-3 (шестой раунд): мешок с uploadedAt = сейчас+100 лет переживал бы
// любую чистку и истёк бы только через сто лет — потолок BAG_MAX_AGE_MS
// ограничивает только вклад ВЕТКИ УСЫНОВЛЕНИЯ (min(dealDeadline,
// uploadedAt + BAG_MAX_AGE_MS) в bagExpiryAt), а base правил 2/3 считается
// ПРЯМО от uploadedAt — потолок туда не заглядывает вообще. Если Задача 3
// возьмёт uploadedAt из тела запроса, срок хранения обходится НАВСЕГДА —
// прямое нарушение обещания "сервер физически не может стать архивом".
// Небольшой допуск (не полноценная политика — просто технический зазор на
// рассинхрон часов клиента и сервера, а не способ легитимно принять
// будущее); в прошлом uploadedAt ничем не ограничен — это никогда не было
// проблемой (мешок просто живёт с момента, который заявлен).
//
// Мелочь (шестой раунд): величина допуска сама по себе теперь
// env-конфигурируема (CLOCK_SKEW_ALLOWANCE_MS — export let, объявлена и
// вычисляется в _refreshConfig() выше, у остальных четырёх сроков/лимитов)
// — раньше была захардкожена прямо здесь module-scope константой, ЕДИНСТВЕННЫЙ
// срок/лимит в файле, нарушавший правило задачи "все сроки/лимиты —
// env-конфигурируемы с явным умолчанием".

// Мелочь (координатор, раунд решения владельца о потолке): экспортирована
// (была module-internal) — fundedAt_ читается и валидируется в app.js, не
// внутри dealDeadlineFromCreation()/dealDeadlineFromDispute() (funded — не
// параметр формулы, см. докстринг adoptPairBags()), значит проверка "не из
// будущего" для неё обязана жить на том же боундари, где значение впервые
// попадает в JS — в app.js, а не спрятана внутри чужой функции, которая её
// вообще не видит.
export function assertNotFromFuture(fn, label, value, nowMs) {
  if (value > nowMs + CLOCK_SKEW_ALLOWANCE_MS) {
    fail(fn, `${label} (${value}) is too far in the future relative to now (${nowMs})`);
  }
}

// Тот же алгоритм, что у pairIdFromAddresses в app.js (сортировка нижних
// регистров, склейка через '-'), продублирован здесь намеренно, а не
// импортирован: обе стороны — чистые функции только от двух адресов, без
// разделяемого состояния — а импорт из app.js завёл бы цикл (см. заголовок
// файла). Дублирование чистой функции не безопасно само по себе: если
// однажды алгоритм в app.js поменяют, эта копия разойдётся молча, и мешки
// начнут ключеваться по одной паре, а споры — искаться по другой. Экспорт
// с подчёркиванием — не часть публичного интерфейса склада (bagKeyFor уже
// зовёт её напрямую и наружу этого не выставляет), а точка входа для
// test/bagStore.test.js, который сверяет её на входах с
// pairIdFromAddresses из app.js и обязан покраснеть при расхождении.
export function _pairIdFromAddresses(a, b) {
  // Мелочь (h): раньше делала String(a).toLowerCase() без проверки формы —
  // pairIdFromAddresses(null, BOB) в app.js бросает (null.toLowerCase()
  // несёт TypeError), а эта версия молча превращала null в строку 'null' и
  // возвращала "успешный", но мусорный pairId вроде '0xb0b1…-null'.
  // assertAddress — та же проверка, что используют все остальные функции
  // этого модуля; для уже провалидированных lowercase-адресов (обычный
  // внутренний вызов из recordBag) это no-op.
  const x = assertAddress('_pairIdFromAddresses', a);
  const y = assertAddress('_pairIdFromAddresses', b);
  return [x, y].sort().join('-');
}

// ─── Метаиндекс: загрузка/сохранение ───────────────────────────────────────

// I1: bag-meta.json может парситься как JSON и всё равно быть отравлен —
// например uploadedAt: 'oops' (структурно валиден, семантически нет).
// cleanupBags() раньше бросал НА СЕРЕДИНЕ прохода по _bagMeta на первой же
// такой записи: файл предыдущего, уже просроченного мешка к этому моменту
// уже удалён, а сохранение индекса в конце — нет, так что на диске индекс
// продолжает перечислять снесённое, listBagsFor отдаёт мешки без файлов, и
// каждая следующая чистка бросает на том же месте снова — ядовитая запись
// не вычищается никогда. Проверяется здесь, на границе загрузки, той же
// формой, что recordBag() требует на записи (переиспользует те же
// assert*-хелперы через try/catch → bool, чтобы не задваивать правила
// валидности в двух местах).
function isValidBagMetaEntry(key, meta) {
  try {
    if (!meta || typeof meta !== 'object') return false;
    const recipient = assertAddress('_loadBagMeta', meta.recipient);
    // Второй тур закрывающего ревью Задачи 4: sender==='' И pairId==='' —
    // ВМЕСТЕ, не по отдельности — легитимный маркер "отправитель
    // неизвестен", который ставит _recoverBagMetaFromDisk() при
    // восстановлении индекса из имён файлов на диске (у имени файла нет
    // sender — только recipient и uploadedAt; pairId без настоящего
    // sender не вычислить). Без этого исключения восстановленная запись
    // переживала СВОЮ ЖЕ первую перезагрузку (файл, который
    // _recoverBagMetaFromDisk() только что честно записал на диск, валиден
    // как JSON и грузится по обычному пути), но тут же отбраковывалась
    // ЭТИМ валидатором как "битая" — а следствие куда хуже одной потерянной
    // записи: _bagMetaLoadOk встаёт в true (файл же распарсился), гейт
    // метлы снимается, а запись из индекса пропала — тот же класс дыры,
    // что чинил весь этот раунд, только с одной перезагрузки отсрочкой.
    // Воспроизведено вживую при написании теста на полную цепочку.
    //
    // Проверка ИМЕННО парой, не по отдельности: запись с настоящим
    // sender, но пустым pairId (или наоборот) — рассогласование полей,
    // такая же порча данных, как раньше, и обязана отбраковываться как
    // раньше (см. тест I1 "негодный по форме sender/recipient/pairId/...").
    // Мутация "проверять sender/pairId по отдельности" красит тот тест.
    const senderUnknown = meta.sender === '' && meta.pairId === '';
    if (!senderUnknown) {
      assertAddress('_loadBagMeta', meta.sender);
      assertNonEmptyString('_loadBagMeta', 'pairId', meta.pairId);
    }
    assertBagKey('_loadBagMeta', key, recipient);
    if (assertSafeInt('_loadBagMeta', 'size', meta.size) < 0) return false;
    assertSafeInt('_loadBagMeta', 'uploadedAt', meta.uploadedAt);
    if (meta.firstFetchedAt != null) assertSafeInt('_loadBagMeta', 'firstFetchedAt', meta.firstFetchedAt);
    if (meta.dealDeadline != null) assertSafeInt('_loadBagMeta', 'dealDeadline', meta.dealDeadline);
    // C1 (координатор, критическая находка): dealFunded как ПОЛЕ ЗАПИСИ
    // убран целиком — он и был источником дыры (свойство мешка, а не
    // свойство конкретного продления, см. докстринг adoptPairBags()).
    // Записи, записанные на диск в промежутке, пока поле существовало,
    // могут всё ещё нести его — просто больше никем не читается
    // (bagExpiryAt()/adoptPairBags() про него не знают), безопасный
    // мёртвый груз, валидировать незачем.
    assertFetchNotBeforeUpload('_loadBagMeta', meta.uploadedAt, meta.firstFetchedAt);
    return true;
  } catch (e) {
    // C1 (четвёртый раунд): ошибка ПРОГРАММИСТА (наш код сломан — TDZ,
    // null pointer, что угодно из категории "это не должно быть возможно")
    // — не то же самое, что ошибка ДАННЫХ (uploadedAt: 'oops' — fail()
    // всегда бросает плоский Error). Единственный реальный прецедент —
    // BAG_KEY_RE в temporal dead zone на момент этого самого вызова —
    // проявлялся именно так: ReferenceError, пойманный этим catch,
    // тихо засчитывался как "запись битая", и индекс терялся целиком на
    // каждом перезапуске с непустыми данными. fail() и все assert*-хелперы
    // этого файла бросают только плоский Error — если поймали что-то ещё,
    // это баг в НАШЕМ коде, а не в чужих данных, и он обязан быть громким.
    if (e instanceof ReferenceError || e instanceof TypeError) throw e;
    return false;
  }
}

// Третий тур закрывающего ревью Задачи 4 (chat-transport-storage) — «режим
// недоверия». Полностью заменяет оба предыдущих раунда (карантин + немедленный
// персист реконструкции), которые координатор воспроизвёл вживую как небезопасные:
// окно между "унесли битый файл в сторону" и "записали восстановленное" —
// это ~840мс на 100 000 мешков (реально измерено), и ЛЮБОЙ обрыв в этом окне
// (сбой процесса, кончившееся место, второй процесс, нечитаемый DIR_BAGS)
// оставляет ПОЛНОЕ ОТСУТСТВИЕ файла описи — а отсутствие читается как
// «свежая установка», не как «был битый». Доверие восстанавливалось молча,
// метла получала полную свободу против неполного индекса.
//
// Новое правило проще и строго безопаснее ровно потому, что ничего не пишет:
//   • битый файл описи НИКОГДА не трогается (не переименовывается, не
//     удаляется) — он и есть признак «войти в режим недоверия» на каждом
//     следующем запуске, пока человек не разберётся;
//   • реконструкция с диска — ТОЛЬКО в памяти, никогда не персистится;
//   • новые мешки (recordBag/markFetched) в режиме недоверия ТОЖЕ не
//     персистятся (см. эти функции ниже) — иначе тот же класс дыры: первая
//     запись перезаписала бы отсутствующий файл собой одним;
//   • ничего не удаляется — ни метла сирот, ни основной цикл истечения
//     срока в cleanupBags() (единый гейт в начале функции, не два разных);
//   • выход из режима — только когда _loadBagMeta() честно, штатно прочитала
//     индекс. Никакой автоматики через запись, время или счётчик попыток.
let _bagMetaLoadOk = true;

// Диск (DIR_BAGS) отдельно от описи — независимая причина войти в режим
// недоверия, даже если сама опись прочиталась штатно. «Пустой» (readdirSync
// вернул []) — не то же самое, что «нечитаемый» (readdirSync бросил): первое
// значит "мешков действительно нет", второе значит "мы не знаем, есть они
// или нет" (не примонтированный том, гонка с mkdir, права). Раньше эти два
// случая были склеены одним глухим `catch {}` в реконструкции — и «склад не
// прочитался» тихо становился «мешков ноль», что при персисте (которого
// больше нет) стирало бы всё реально лежащее на диске.
function _isDiskReadable() {
  if (!fs.existsSync(DIR_BAGS)) return true; // каталога ещё нет вовсе — легитимно пусто (до первого mkdirSync)
  try {
    fs.readdirSync(DIR_BAGS);
    return true;
  } catch {
    return false;
  }
}

// Один обход склада, а не два. Раньше "описи нет" сначала звала
// _countDiskBags() (посчитать — есть ли вообще что-то, для решения
// "доверять ли"), а если решение было "нет" — _loadBagMeta() ЕЩЁ РАЗ звала
// отдельную _reconstructInMemory() (восстановить содержимое). Оба обходят
// ОДНИ И ТЕ ЖЕ каталоги получателей. Замерено координатором: 445мс против
// 411мс на 60 000 мешков — ветка "описи нет" дороже ветки "опись битая"
// ровно на стоимость второго обхода. Слито в одну функцию: обход происходит
// один раз, результат — оба числа сразу (сырой счёт файлов ДЛЯ решения
// "доверять ли" и реконструированные записи ДЛЯ памяти, если решение —
// "нет"). rawFileCount считает ЛЮБОЙ файл в подкаталогах получателей, не
// только те, что проходят BAG_KEY_RE — сама неоднозначность "тут что-то
// есть, а описи нет" уже повод не доверять, независимо от того, мусор это
// или настоящие мешки. reconstructed — то же, чем раньше была
// _reconstructInMemory(): имя файла мешка само несёт адресата и время
// загрузки (bagKeyFor: "<recipient>/<uploadedAt>-<uuid>.bin") — единственное,
// что можно узнать без индекса.
//
// Единственный путь в индекс мимо проверок recordBag() — значит те же
// проверки нужны и здесь, а не только форма ключа: `fs.lstatSync` (НЕ
// `statSync` — не следовать за симлинком, иначе симлинк на файл СНАРУЖИ
// DIR_BAGS с подходящим именем становится скачиваемым через GET /bags/:key;
// та же причина, по которой sweepOrphanFiles/removeEmptyRecipientDirs ниже
// в этом же раунде переведены с statSync на lstatSync для каталогов
// получателей — координатор замерил живой побег метлы сирот сквозь
// симлинк-каталог, эта функция была защищена от него с самого начала),
// `.isFile()` (не каталог, не что-то ещё), потолок MAX_BAG_SIZE (файл,
// который не мог быть легитимно записан через recordBag(), не имеет права
// попасть в индекс и отсюда), метка времени не из будущего (тем же
// допуском, что и assertNotFromFuture — без этого злоумышленник с локальным
// доступом к ФС мог бы вписать себе метку на 33658 год и получить мешок,
// который никогда не истечёт). Итоговый кандидат прогоняется через
// isValidBagMetaEntry() — тот же путь, что и любая запись из штатно
// прочитанной описи.
//
// Логирование НЕ здесь — вызывающий (_loadBagMeta) решает, входить ли в
// режим недоверия вообще; функция может быть вызвана и тогда, когда
// результат в итоге не понадобится (склад пуст, доверие остаётся), и в
// этом случае молчать обязательно (см. тест "файла нет вовсе — легитимное
// пустое состояние, НЕ считается потерей индекса").
function _scanDiskBags(nowMs) {
  const reconstructed = Object.create(null);
  let recoveredCount = 0;
  let skippedGarbage = 0;
  let rawFileCount = 0;
  let recipients = [];
  try { recipients = fs.readdirSync(DIR_BAGS); } catch {}

  for (const recipient of recipients) {
    const recipientDir = path.join(DIR_BAGS, recipient);
    let files;
    try {
      const st = fs.lstatSync(recipientDir);
      if (!st.isDirectory()) continue; // включая симлинк на каталог — lstat его не проходит isDirectory()
      files = fs.readdirSync(recipientDir);
    } catch { continue; }

    rawFileCount += files.length;

    for (const file of files) {
      const key = `${recipient}/${file}`;
      if (!BAG_KEY_RE.test(key)) { skippedGarbage++; continue; }

      const filePath = path.join(recipientDir, file);
      let st;
      try { st = fs.lstatSync(filePath); } catch { skippedGarbage++; continue; }
      if (!st.isFile()) { skippedGarbage++; continue; } // симлинк/каталог/сокет — никогда не следовать
      if (st.size > MAX_BAG_SIZE) { skippedGarbage++; continue; }

      // recipient и метка времени — прямо из формы ключа (см. bagKeyFor):
      // "<recipient>/<uploadedAt-epoch-ms>-<uuid>.bin". BAG_KEY_RE уже
      // подтвердила форму целиком, так что первый '-' после '/' — граница
      // между цифрами времени и uuid, однозначно (цифры вида [0-9]{1,15}
      // не содержат '-' сами по себе).
      const afterSlash = key.slice(key.indexOf('/') + 1);
      const uploadedAt = Number(afterSlash.slice(0, afterSlash.indexOf('-')));
      if (uploadedAt > nowMs + CLOCK_SKEW_ALLOWANCE_MS) { skippedGarbage++; continue; }

      const candidate = {
        sender: '',            // неизвестен — содержимое запечатано, отправитель внутри сообщения
        recipient,
        pairId: '',            // не вычислим без настоящего sender; ничем публично не читается
        size: st.size,
        uploadedAt,
        firstFetchedAt: null,  // консервативно: считается непрочитанным — длинный срок (правило 3)
        dealDeadline: null,    // консервативно: считается не усыновлённым сделкой (правило 1 не применяется)
      };
      if (!isValidBagMetaEntry(key, candidate)) { skippedGarbage++; continue; }

      reconstructed[key] = candidate;
      recoveredCount++;
    }
  }

  return { rawFileCount, recoveredCount, skippedGarbage, reconstructed };
}

export function _loadBagMeta() {
  let raw = {};
  // И-N (закрывающий раунд): раньше «файла нет» (свежая установка) и «файл
  // есть, но не читается как индекс» (потеря доверия) шли одним и тем же
  // путём — raw молча становился {} в обоих случаях, и ничего не отличало
  // первый запуск от испорченного диска. Различаем явно: файла действительно
  // нет → легитимно пусто, indexOk остаётся true; файл есть, но не JSON,
  // или JSON, но не индекс (null/массив/примитив) → потеря доверия, громко.
  let indexOk = true;
  // К-3: «опись» — это теперь ДВА файла, снимок и журнал дозаписи, и
  // существованием описи считается наличие ЛЮБОГО из них.
  //
  // Иначе — не мелочь, а поломка нормальной работы. Снимок пишет только
  // схлопывание (ночная cleanupBags или переполненный журнал), поэтому у
  // свежего сервера, принявшего первую сотню сообщений и перезапущенного
  // до первой ночи, снимка НЕТ ВОВСЕ, а мешки на диске ЕСТЬ. Проверяй мы
  // существование одного снимка — такой сервер уходил бы в режим недоверия
  // на совершенно штатном перезапуске и переставал бы и удалять, и
  // сохранять. Поймано ровно так, живым прогоном.
  const snapshotExists = fs.existsSync(BAG_META_PATH);
  const journalExists = fs.existsSync(BAG_JOURNAL_PATH);
  const indexExists = snapshotExists || journalExists;
  // Считается только когда индекса нет — см. ветку else ниже. Отдельная
  // переменная (не пересчитывать в теле console.error) — нужна и для
  // решения "доверять ли", и для числа в громкой строке лога.
  let diskBagCount = 0;
  // Заполняется ТОЛЬКО в ветке "индекса нет" ниже, одним обходом склада —
  // если решение окажется "недоверие", этот же результат используется
  // ниже вместо повторного обхода (координатор замерил: раньше "описи
  // нет" обходила склад дважды — счёт, потом реконструкция — и была
  // дороже "опись битая" на стоимость второго обхода; 445мс vs 411мс на
  // 60 000 мешков).
  let precomputedScan = null;

  if (snapshotExists) {
    try {
      const parsed = JSON.parse(fs.readFileSync(BAG_META_PATH, 'utf8'));
      // И-2 (пятый раунд): JSON.parse('null') УСПЕШНО возвращает null — не
      // ловится try/catch выше (разбор не бросил). Object.entries(null)
      // чуть ниже бросил бы TypeError, ломая загрузку целиком (а на уровне
      // модуля — и весь процесс). Годен только настоящий объект вида
      // {key: meta}; null/массив/примитив — та же потеря доверия, что и
      // совсем нечитаемый JSON, не крах загрузки.
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
        raw = parsed;
      } else {
        indexOk = false;
      }
    } catch {
      // В том числе обрезанный файл после краха посреди записи — самый
      // вероятный боевой случай (кончилось место на диске, процесс убит
      // между writeFileSync и renameSync temp-файла в _saveBagMeta()).
      indexOk = false;
    }
  } else if (journalExists) {
    // К-3: снимка ещё нет, но журнал есть — штатное состояние сервера до
    // первого схлопывания. Начинаем с пустого снимка; всё содержимое
    // приедет разбором журнала ниже.
    raw = {};
  } else {
    // Продолжение третьего тура (координатор): отсутствие описи —
    // легитимная пустота ТОЛЬКО когда склад тоже пуст или отсутствует.
    // «Мешки лежат, а описи нет» само по себе на свежей установке не
    // возникает — либо файл убрали рукой (самый естественный способ
    // «починить» режим недоверия — и именно он воскрешает беду, от
    // которой режим недоверия и заводился, воспроизведено координатором
    // живьём), либо запись не доехала до диска. Оба случая — недоверие,
    // не свежий старт.
    precomputedScan = _scanDiskBags(Date.now());
    diskBagCount = precomputedScan.rawFileCount;
    if (diskBagCount > 0) indexOk = false;
    // else: и описи нет, и склад пуст/отсутствует — действительно свежая
    // установка, indexOk остаётся true (precomputedScan просто не
    // пригодится — обход всё равно был один-единственный).
  }

  // Третий тур: диск отдельно от описи — см. _isDiskReadable() выше. Опись
  // может быть идеально валидной, а DIR_BAGS в этот самый момент —
  // непрочитанным (не примонтирован, гонка), и это ТОЖЕ повод не доверять
  // ничему, что дальше решит удалить хоть что-то.
  const diskOk = _isDiskReadable();

  if (!indexOk || !diskOk) {
    // Громкая строка НА КАЖДОМ запуске, пока не починят руками — не
    // одноразовая. Три разные причины дают три РАЗНЫХ, узнаваемых текста —
    // человек, который только что удалил файл рукой, обязан понять из
    // лога, почему стало не лучше, а так же, и что сделать вместо этого:
    // либо тоже убрать мешки (чистый лист), либо вернуть индекс
    // (восстановление). Не подделка ни под «dropped N corrupt entries» (та
    // находка про порчу отдельных записей внутри в остальном годного
    // индекса), ни под старое «FAILED TO LOAD INDEX / recovering» (тот
    // текст обещал персист, которого больше нет).
    const reasons = [];
    if (!indexOk && indexExists) {
      reasons.push(
        `index at ${BAG_META_PATH} exists but could not be read as an index (corrupt/truncated JSON, or not an object: null/array/primitive).`
      );
    } else if (!indexOk && !indexExists) {
      reasons.push(
        `index is MISSING — NEITHER the snapshot at ${BAG_META_PATH} nor the append journal at ` +
        `${BAG_JOURNAL_PATH} exists — but the store at ${DIR_BAGS} is not empty (${diskBagCount} file(s) found) — ` +
        `this cannot be a fresh install. Either the index was removed by hand or it never reached disk. ` +
        `To start clean, ALSO remove the bag files on disk; to recover, restore the index file.`
      );
    }
    if (!diskOk) {
      reasons.push(`${DIR_BAGS} could not be enumerated (this is NOT the same as being empty — it means "unknown", not "zero").`);
    }
    console.error(
      `[bags] _loadBagMeta: ENTERING DISTRUST MODE — ${reasons.join(' ')} ` +
      `The index file, if any, is left EXACTLY as it is — it is the evidence, not something to clean up. ` +
      `Nothing will be written to disk (neither the reconstruction below nor any new bag) and nothing will be ` +
      `deleted (neither the orphan sweep nor the main expiry pass in cleanupBags()) until a LATER load reads a ` +
      `genuinely healthy index. No automatic recovery. ` +
      // Закрывающий раунд координатора: режим недоверия закрывает "человек
      // удалил файл", но не "человек сделал, чтобы парсилось" — а это
      // ровно то, что подсказывает фраза "restore the index file" выше,
      // если прочитать её невнимательно. Кода-фикса нет (см. комментарий
      // над describe-блоком в test/bagStore.test.js: легитимный честный
      // конец жизни описи неотличим от подделки по одному только
      // содержимому файла) — единственная защита здесь текстовая, и она
      // обязана быть прямой, а не намёком.
      `WARNING: do NOT "fix" this by hand-writing an empty or made-up index (e.g. an empty {} written directly ` +
      `to the file) — a syntactically valid index that does not match what is really on disk is JUST AS ` +
      `DESTRUCTIVE as no index at all: every bag on disk becomes invisible to it and gets swept as an orphan ` +
      `by mtime alone, regardless of read state or deal adoption. Safe options: restore the REAL index from a ` +
      `backup, or — only if starting genuinely clean — remove the snapshot (${BAG_META_PATH}), the append ` +
      `journal (${BAG_JOURNAL_PATH}) AND every bag file on disk, all three together. Removing only some of ` +
      `them leaves the store lying about itself: a leftover journal replays its entries on top of whatever ` +
      `snapshot it finds, including an empty one.`
    );
    // Один обход на всю функцию: если решение "недоверие" пришло из ветки
    // "индекса нет" выше, обход уже сделан (precomputedScan) — переиспользуем
    // его результат, а не сканируем склад заново. Иначе (индекс есть, но
    // битый, или сам диск не читается) — единственный обход происходит
    // здесь и сейчас.
    const scan = precomputedScan ?? _scanDiskBags(Date.now());
    console.error(
      `[bags] _scanDiskBags: recovered ${scan.recoveredCount} bag(s) from disk scan of ${DIR_BAGS}` +
      (scan.skippedGarbage ? ` (skipped ${scan.skippedGarbage} non-bag/invalid ${scan.skippedGarbage === 1 ? 'entry' : 'entries'})` : '') +
      ` — IN MEMORY ONLY, nothing written to disk. sender, read state and deal adoption are unknown/unread/unadopted.`
    );
    _bagMetaLoadOk = false;
    _bagMeta = scan.reconstructed;
    return _bagMeta;
  }

  // Бесплатное улучшение от ревьюера (пятый раунд): Object.create(null),
  // не {} — assertBagKeyShape уже запирает '__proto__'/'constructor' на
  // входе каждой публичной функции (защита по форме ключа, симптоматическая),
  // но объект без Object.prototype убирает КЛАСС травления прототипа
  // структурно: у него нет '__proto__' как унаследованного аксессора вообще,
  // независимо от того, дошёл ли до него мусорный ключ мимо проверки формы.
  const clean = Object.create(null);
  let dropped = 0;
  for (const [key, meta] of Object.entries(raw)) {
    if (isValidBagMetaEntry(key, meta)) {
      clean[key] = meta;
    } else {
      dropped++;
      // Файл на диске (если есть) НЕ трогается здесь — только запись
      // уходит из индекса. Мы не уверены, что означает отравленная запись
      // (могли отравить и uploadedAt, и recipient, и что угодно ещё), так
      // что безопасный выбор — молчать про файл и дать обычной метле
      // сирот (sweepOrphanFiles, по mtime) разобраться с ним по своему
      // независимому расписанию.
      console.error(`[bags] _loadBagMeta: dropping corrupt index entry ${JSON.stringify(key)} — file on disk, if any, is left untouched, only the index entry is removed`);
    }
  }
  if (dropped) {
    console.error(`[bags] _loadBagMeta: dropped ${dropped} corrupt ${dropped === 1 ? 'entry' : 'entries'} out of ${Object.keys(raw).length} from ${BAG_META_PATH}`);
  }

  // К-3: снимок прочитан — доигрываем поверх него журнал дозаписи. Всё,
  // что было записано горячим путём после последнего схлопывания, живёт
  // только здесь.
  _replayJournal(clean);

  _bagMetaLoadOk = true;
  _bagMeta = clean;
  return _bagMeta;
}

// К-3: доигрывает журнал дозаписи поверх снимка. Вызывается ТОЛЬКО из
// _loadBagMeta(), после того как снимок признан здоровым.
//
// Каждая строка проходит РОВНО ТУ ЖЕ проверку формы (isValidBagMetaEntry),
// что и запись из снимка: журнал — такой же файл на диске, как и снимок, и
// такой же кандидат на порчу. Единственный путь в индекс мимо recordBag()
// не должен быть и путём мимо его проверок.
//
// Неразобранная строка НЕ переводит склад в режим недоверия, в отличие от
// битого снимка, и это осознанная разница. Обрезанный ХВОСТ журнала —
// нормальный, ожидаемый след обрыва процесса посреди дозаписи (ровно тот
// случай, ради которого выбран строчный формат), а не признак того, что
// данным нельзя верить. Битый снимок — другое дело: он не может стать
// битым «штатно».
function _replayJournal(target) {
  let raw;
  try { raw = fs.readFileSync(BAG_JOURNAL_PATH, 'utf8'); } catch { return; }

  const lines = raw.split('\n');
  let applied = 0;
  let skipped = 0;
  for (const line of lines) {
    if (!line) continue;
    let rec;
    try { rec = JSON.parse(line); } catch { skipped++; continue; } // обрезанный хвост живёт здесь
    if (!rec || typeof rec !== 'object' || typeof rec.k !== 'string') { skipped++; continue; }
    if (rec.d) {
      delete target[rec.k];
      applied++;
      continue;
    }
    if (!isValidBagMetaEntry(rec.k, rec.m)) { skipped++; continue; }
    target[rec.k] = rec.m;
    applied++;
  }
  if (applied || skipped) {
    console.log(
      `[bags] _replayJournal: applied ${applied} change(s) from ${BAG_JOURNAL_PATH}` +
      (skipped ? ` (skipped ${skipped} unreadable line(s) — the last one is normally a write cut short by a restart)` : '')
    );
  }
}

// I2: раньше писала напрямую поверх BAG_META_PATH, оба catch были немые.
// Обрезанный файл (крах ровно посреди записи — заполненный диск, убитый
// процесс) → следующая загрузка молча получает пустой индекс: список
// переписки человека исчезает из виду, хотя сами файлы целы на диске. И
// ошибка самой записи глоталась — проверено подменой: markFetched()
// отмечал прочтение в памяти, а на диске не менялось ничего, вызывающий
// (маршрут Задачи 3) узнать об этом не мог никак.
//
// Пишем во временный файл и переименовываем — та же пара примитивов, что
// защищает от обрезанного файла в любой похожей системе: fs.renameSync на
// одной файловой системе атомарен, так что BAG_META_PATH в любой момент
// времени — это либо полностью старое содержимое, либо полностью новое,
// никогда наполовину записанное. И не глотаем ошибку: если запись или
// переименование упали, это НЕ синоним "всё в порядке, продолжаем как ни
// в чём не бывало" — throw после логирования, тот же приём, что и во всех
// остальных assert*-хелперах этого файла (в отличие от более старого,
// снисходительного savePushSubs() в app.js: там цена ошибки — пережить
// рестарт без пуша, здесь — тихо потерять чужую переписку, ставки другие).
// К-3: ЭТО ТЕПЕРЬ СХЛОПЫВАНИЕ, а не «сохранение на каждую запись». Пишет
// полный снимок и обнуляет журнал дозаписи. Горячий путь (recordBag/
// markFetched/adoptPairBags) сюда больше не заходит — он дописывает одну
// строку в журнал (_appendJournal ниже). Остаются два вызывающих: ночная
// cleanupBags() (она и так O(N)) и порог размера журнала.
//
// Порядок «снимок, потом обнуление журнала» — не стилистика, а
// единственный безопасный. Обратный порядок при обрыве между шагами теряет
// всё, что было в журнале и не успело попасть в снимок. В этом порядке
// худший случай — журнал, часть которого уже учтена в снимке: разбор при
// загрузке применяет такую строку повторно, а повтор безвреден (ключи
// уникальны по построению, см. I5 в recordBag; вставка того же значения и
// удаление уже отсутствующего — обе идемпотентны).
export function _saveBagMeta() {
  const tmpPath = `${BAG_META_PATH}.tmp-${process.pid}-${Date.now()}-${randomUUID()}`;
  try {
    // Тот же приём, что у savePushSubs() в app.js:65 — не полагаться на то,
    // что каталог уже создан где-то ещё (assertBagStoreReady() создаёт
    // DIR_BAGS на старте, но её порядок вызова относительно первого
    // recordBag() — забота вызывающего кода, не гарантия этого модуля).
    // На чистой установке без этого первый же recordBag() падал с ENOENT.
    fs.mkdirSync(path.dirname(BAG_META_PATH), { recursive: true });
    fs.writeFileSync(tmpPath, JSON.stringify(_bagMeta), 'utf8');
    fs.renameSync(tmpPath, BAG_META_PATH);
  } catch (e) {
    try { fs.unlinkSync(tmpPath); } catch {}
    console.error(`[bags] FAILED TO SAVE ${BAG_META_PATH} — in-memory index and disk index have diverged: ${e.message}`);
    throw e;
  }
  // Снимок доехал — журнал, накопленный ДО него, полностью в нём учтён и
  // больше не нужен. Ошибка обнуления не откатывает уже сохранённый снимок
  // и не бросается вызывающему: состояние на диске корректно и без этого
  // (лишний журнал просто переиграется поверх снимка при загрузке), а вот
  // превращать успешное сохранение в исключение — значит заставить
  // вызывающего откатывать память, которая на самом деле уже на диске.
  try {
    if (fs.existsSync(BAG_JOURNAL_PATH)) fs.unlinkSync(BAG_JOURNAL_PATH);
  } catch (e) {
    console.error(`[bags] snapshot saved, but journal ${BAG_JOURNAL_PATH} could not be cleared (it will simply be replayed on top of the snapshot at load, which is harmless): ${e.message}`);
  }
}

// К-3: горячий путь. Одна строка на изменение вместо всей описи.
//
// Замер до/после (scratchpad/measure-k3.mjs, боевые умолчания, локальный
// диск): при 20 000 мешках в описи ОДИН PUT стоил 24,9 мс и переписывал
// 7,8 МБ; путь от пустого склада до 20 000 мешков — 281,6 с совокупной
// блокировки цикла событий.
//
// Формат — по строке JSON на изменение, ровно два вида:
//   {"k":"<ключ>","m":{...}}  — запись/обновление
//   {"k":"<ключ>","d":1}      — удаление
// Разбор при загрузке (_replayJournal) применяет их поверх снимка по
// порядку. Обрыв процесса посреди дозаписи оставляет неполную ПОСЛЕДНЮЮ
// строку — она не разберётся и будет пропущена, а всё, что дописано до
// неё, целыми строками уже на диске. Это и есть причина строчного формата:
// у него есть однозначная граница записи, у одного большого JSON её нет.
function _appendJournal(records) {
  const payload = records.map((r) => JSON.stringify(r)).join('\n') + '\n';
  try {
    fs.mkdirSync(path.dirname(BAG_JOURNAL_PATH), { recursive: true });
    fs.appendFileSync(BAG_JOURNAL_PATH, payload, 'utf8');
  } catch (e) {
    console.error(`[bags] FAILED TO APPEND ${BAG_JOURNAL_PATH} — in-memory index and disk index have diverged: ${e.message}`);
    throw e;
  }
}

// Журнал не должен расти вечно: чем он длиннее, тем дольше разбор при
// старте. Переваливший потолок схлопывается в снимок — один дорогой проход
// на много тысяч дешёвых записей вместо дорогого прохода на каждую.
// Проверяем размер по факту на диске, а не по счётчику в памяти: счётчик
// врал бы после перезапуска, когда журнал на диске уже длинный, а процесс
// только что поднялся и «ничего ещё не писал».
function _compactJournalIfOversized() {
  let size = 0;
  try { size = fs.statSync(BAG_JOURNAL_PATH).size; } catch { return; }
  if (size <= BAG_JOURNAL_MAX_BYTES) return;
  console.log(`[bags] journal ${BAG_JOURNAL_PATH} reached ${size} bytes (cap ${BAG_JOURNAL_MAX_BYTES}) — folding it into a fresh snapshot`);
  _saveBagMeta();
}

// Третий тур закрывающего ревью Задачи 4: recordBag()/markFetched() persist
// normally EXCEPT while the index is in distrust mode (_bagMetaLoadOk ===
// false, see _loadBagMeta()/_scanDiskBags() above) — then the change
// stays in memory only, for this process, until a session ends. Without
// this, the very first write after a lost index would overwrite the
// missing/corrupt file with itself alone — the exact class of hole this
// whole round exists to close, just from the writer's side instead of the
// reconstruction's. Not an error for the caller: the upload/read-receipt
// still succeeds from the client's point of view, it just doesn't survive
// a restart until a human fixes the index.
//
// К-3: гейт недоверия ОБЯЗАН стоять и на журнале тоже, не только на
// снимке. Дозапись в журнал — такая же запись на диск: пропусти её мимо
// гейта, и первая же строка после потерянной описи начала бы достраивать
// то, чему мы решили не верить.
function _persistUnlessDistrusted(fn, records) {
  if (!_bagMetaLoadOk) {
    console.error(`[bags] ${fn}: DISTRUST MODE — change kept in memory only, NOT written to ${BAG_META_PATH}. Fix or remove the index file and restart to resume persisting.`);
    return;
  }
  if (records && records.length) {
    _appendJournal(records);
    _compactJournalIfOversized();
    return;
  }
  _saveBagMeta();
}

