export const APPEAL_REVIEW_WINDOW_DAYS = 4;
// I2 (находка координатора, закрывающий раунд): FINALIZE_DELAY_HOURS —
// копия ещё одной private-константы того же контракта
// (ArbiterRegistryFacet.sol:140, "FINALIZE_DELAY", 24 часа) — окно, в
// которое можно поднять апелляцию ПОСЛЕ вердикта (raiseAppeal() требует
// block.timestamp < submittedAt + FINALIZE_DELAY, строка 755), и только
// ПОСЛЕ подачи апелляции запускается APPEAL_REVIEW_WINDOW (appealDeadline =
// момент апелляции + APPEAL_REVIEW_WINDOW, строка 781) — не от submittedAt.
// Реальная цепочка на худший случай ПОЛЬЗОВАТЕЛЬСКОГО пути (не единственный
// возможный путь — см. предупреждение ниже):
//   submitVerdict ≤ disputedAt + DISPUTE_WINDOW
//   raiseAppeal   ≤ submittedAt + FINALIZE_DELAY
//   appealDeadline = момент апелляции + APPEAL_REVIEW_WINDOW
//   худший случай = disputedAt + DISPUTE_WINDOW + FINALIZE_DELAY + APPEAL_REVIEW_WINDOW
//
// ⚠️ Не чинится, задокументировано по прямому указанию координатора
// (третий закрывающий раунд ревью): путь владельца/ДАО срока НЕ ИМЕЕТ
// ВООБЩЕ. freezeVerdict() (ArbiterRegistryFacet.sol, onlyOwnerOrDAO) ставит
// v.frozen = true без какого-либо таймаута — снять заморозку может только
// unfreezeVerdict(), тем же кругом вызывающих, когда угодно, хоть через
// год. Пока вердикт заморожен, дело остаётся живым БЕССРОЧНО. Значит
// "худший случай" выше — это худший случай ИМЕННО пользовательского пути
// (спор → вердикт → обычная апелляция), а не абсолютный потолок времени,
// в течение которого дело теоретически может понадобиться. Отдельный
// потолок BAG_MAX_AGE_MS (bagExpiryAt() ниже) — вот что реально ограничивает
// мешок сверху при любом раскладе, включая заморозку; формула здесь просто
// не пытается угнаться за путём владельца/ДАО отдельно — он не имеет
// конечного "худшего случая" по определению, формулой его не выразить.
// Формула ниже (dealDeadlineFromDispute/dealDeadlineFromCreation) раньше
// этого звена не имела вовсе — BAG_DEAL_GRACE_MS (умолчание — сутки) молча
// подменял собой это слагаемое: на умолчаниях запас получался РОВНО 0 (сутки
// GRACE в точности гасились отсутствующим днём FINALIZE_DELAY), а на
// легальной настройке BAG_DEAL_GRACE_MS=0 срок отставал от истинного конца
// апелляции на день — доказательства стирались бы за сутки до того, как
// апелляция реально закрывается. В ЧАСАХ, не в днях — контракт объявляет
// её как `24 hours`, гейт грепает именно эту форму.
export const FINALIZE_DELAY_HOURS = 24;
// BAG_DEAL_GRACE_MS — небольшой буфер СВЕРХ disputedAt+DISPUTE_WINDOW+
// APPEAL_REVIEW_WINDOW (см. dealDeadlineFromDispute() ниже). Бриф Задачи 5
// не дал умолчания для этой ручки явно (в отличие от 30 дней для лукбэка и
// 4 дней для окна апелляции) — выбрано намеренно: сутки, тот же порядок
// величины, что и ночной цикл чистки (runFileCleanup через node-cron), с
// запасом на то, что цепь и релеер не проверяют время в один и тот же миг.
// 0 — легитимное значение (см. assertNonNegativeFiniteNumber ниже), не
// assertPositiveFiniteNumber: "без буфера вообще" осмысленная настройка,
// в отличие от нулевого TTL/потолка/лукбэка, каждый из которых фактически
// выключил бы соответствующее правило целиком.
export let BAG_DEAL_GRACE_MS;
