// ─── Срок жизни ─────────────────────────────────────────────────────────────
//
// Три правила, в этом порядке:
//   1. Усыновлён сделкой (dealDeadline задан) → живёт до dealDeadline, но не
//      дольше потолка BAG_MAX_AGE_MS от загрузки. Потолок — против
//      злоупотребления: пометка сделкой, как и нынешняя пометка парой в
//      app.js, не имеет доказательства участия.
//   2. Прочитан (firstFetchedAt задан) → firstFetchedAt + BAG_TTL_MS.
//   3. Не прочитан → uploadedAt + BAG_UNREAD_TTL_MS.
//
// Усыновление ПРОДЛЕВАЕТ и никогда не обрезает: сделка, закрывшаяся завтра,
// не должна стирать переписку, которой по обычному правилу жить ещё месяц —
// иначе привязка к сделке из защиты превратилась бы в способ ускоренно
// стереть неудобное. Отсюда Math.max(base, ...): итог никогда не короче
// того, что дало бы правило 2/3 само по себе.
//
// Осознанное следствие: потолок усыновления — это BAG_MAX_AGE_MS (90д) от
// uploadedAt, но фактический предельный срок мешка может доехать до
// BAG_MAX_AGE_MS + BAG_TTL_MS (90+7д). Тот же Math.max(base, ...) выше: если
// мешок усыновлён сделкой и прочитан за миг до потолка, base (правило 2 —
// firstFetchedAt + BAG_TTL_MS) обгоняет ceiling (min(dealDeadline, потолок))
// ещё на BAG_TTL_MS, и Math.max берёт большее. Это не отдельная дыра, а то
// же самое правило "усыновление не обрезает", применённое ещё раз: коль
// скоро правило 2 само по себе дало бы срок дольше потолка, потолок его не
// укорачивает — потолок ограничивает только вклад САМОЙ сделки, а не общий
// результат. Заперто тестом ниже.
//
// C1 (координатор, критическая находка следующего раунда после решения
// владельца): освобождение от потолка BAG_MAX_AGE_MS — раньше per-мешок
// флаг (meta.dealFunded, монотонный) — оказалось СВОЙСТВОМ ЗАПИСИ, а не
// свойством того продления, которое его выдало. Дыра: пара платит ОДИН
// раз (любая сделка, хоть на день), dealFunded встаёт в true НАВСЕГДА —
// и дальше ЛЮБАЯ другая сделка той же пары, включая НИКОГДА не оплаченную,
// двигает срок вперёд без всякого потолка, потому что ежедневный храповик
// (adoptPairBags → Math.max) видел флаг уже true и не спрашивал, ктО
// именно сейчас продлевает. Хуже того: у зарегистрированной неоплаченной
// сделки НЕТ выхода из активных без оплаты или запуска (все девять путей
// завершения контракта требуют одного из двух), а таймаут активации
// возвращает клиенту ВСЮ сумму — то есть капитал, "купивший" освобождение,
// возвращается, остаётся один газ. Обоснование решения владельца
// ("хранение оплачивается чужим капиталом") перестаёт быть правдой ровно
// в момент, когда капитал вернули — а флаг на мешке об этом не узнаёт.
//
// Правка: потолок BAG_MAX_AGE_MS вообще не хранится и не читается ЗДЕСЬ
// как отдельное правило — он ПОЛНОСТЬЮ переехал в adoptPairBags() (см. её
// докстринг ниже): решение "резать потолком или нет" принимается НА
// КАЖДОЕ ПРОДЛЕНИЕ отдельно, ДО того, как кандидат идёт в Math.max с уже
// хранящимся значением, а не постфактум здесь, на чтении. meta.dealDeadline
// приходит уже в правильном виде — либо честно обрезанным (если ПОСЛЕДНЕЕ
// продление, которое реально его подвинуло, было от неоплаченной сделки),
// либо безлимитным (если было от оплаченной) — bagExpiryAt() просто берёт
// его как есть, тем же Math.max(base, ...), что и было до всей истории с
// оплатой (правило "усыновление не обрезает" не изменилось — см. докстринг
// выше, "Осознанное следствие").
export function bagExpiryAt(meta, _nowMs = Date.now()) {
  if (!meta || typeof meta !== 'object') fail('bagExpiryAt', 'invalid meta');
  assertSafeInt('bagExpiryAt', 'meta.uploadedAt', meta.uploadedAt);
  if (meta.firstFetchedAt != null) assertSafeInt('bagExpiryAt', 'meta.firstFetchedAt', meta.firstFetchedAt);
  if (meta.dealDeadline != null) assertSafeInt('bagExpiryAt', 'meta.dealDeadline', meta.dealDeadline);
  assertFetchNotBeforeUpload('bagExpiryAt', meta.uploadedAt, meta.firstFetchedAt);

  // != null, не истинность: 0 (эпоха Unix) — валидный safe integer, тот же
  // модуль сам его принимает через assertNullableSafeInt. С проверкой на
  // истинность firstFetchedAt: 0 читался как "не прочитан", и правило 3
  // (30д от загрузки) срабатывало вместо правила 2 (7д от прочтения).
  const base = meta.firstFetchedAt != null
    ? meta.firstFetchedAt + BAG_TTL_MS
    : meta.uploadedAt + BAG_UNREAD_TTL_MS;

  if (!meta.dealDeadline) return base;

  return Math.max(base, meta.dealDeadline);
}

// ─── Усыновление сделкой ────────────────────────────────────────────────────
//
// Задача 5 (chat-transport-storage). §6 спеки: бриф обсуждают ДО сделки —
// без усыновления самое важное истечёт раньше, чем возникнет спор, а
// цепочка сообщений укажет на человека как на утаившего, хотя он ничего не
// прятал. Вызывающий (app.js, тем же путём, каким он уже узнаёт о спорах —
// см. getDisputedPairIds()) зовёт adoptPairBags() при появлении спорной
// сделки между парой.
//
// ДВА ЭТАПА, не один (находка координатора при ревью первой версии этой
// задачи). Формула "до конца апелляции" (dealDeadlineFromDispute ниже)
// требует disputedAt — а его физически не существует, пока сделка не
// оспорена. Усыновление ТОЛЬКО по спору не закрывает риск, ради которого
// заведена вся задача: если сделка живёт дольше "непрочитанного" TTL
// (умолчание — 30 дней, правило 3 bagExpiryAt) от момента загрузки мешка с
// брифом до момента спора, обычная ночная чистка выметет мешок задолго до
// того, как спор вообще возникнет и появится шанс его усыновить —
// воспроизведено координатором числами, см. task-5-report.md, раздел
// "Замер: дыра закрыта".
//
//   Этап 1 — dealDeadlineFromCreation(), при создании сделки (адрес пары
//   виден в registry.getActive(), тот же путь, что getDisputedPairIds()
//   выше). Срок ПРЕДВАРИТЕЛЬНЫЙ: у соглашения есть свой срок (deadlineDays_,
//   читается с getDetails() сразу при регистрации, до всякой активации), от
//   МОМЕНТА СОЗДАНИЯ — а не от disputedAt, которого ещё нет.
//
//   Этап 2 — dealDeadlineFromDispute(), при споре, ТОЧНЫЙ, от реального
//   disputedAt. Не отменяет этап 1 — усыновление, что бы ни вызывало его
//   повторно, только ПРОДЛЕВАЕТ (Math.max в adoptPairBags() ниже): если
//   сделка закрылась спором раньше своего предварительного срока, этап 2
//   не откатывает то, что уже дал этап 1 (заперто тестом на интеграцию в
//   test/bagAdoption.test.js — "усыновление в два этапа").
const DAY_MS = 24 * 60 * 60 * 1000;
const HOUR_MS = 60 * 60 * 1000;
// I2: слагаемое обеих формул ниже — FINALIZE_DELAY между вердиктом и правом
// подать апелляцию (см. докстринг у FINALIZE_DELAY_HOURS выше). Вынесено
// один раз сюда, а не дублируется в обеих функциях по отдельности.
const FINALIZE_DELAY_MS = FINALIZE_DELAY_HOURS * HOUR_MS;

// Этап 1: срок ПРЕДВАРИТЕЛЬНЫЙ, посчитанный от якоря и ownDeadlineMs
// (собственный срок сделки, Agreement.getDetails().deadlineDays_ * 1 day —
// известен сразу при регистрации, ДО funded/activated). disputeWindowMs —
// тот же смысл, что в dealDeadlineFromDispute ниже: контракт может однажды
// изменить окно спора, читаем с цепи, не хардкодим.
//
// C1 (находка координатора, закрывающий раунд ревью): якорь — max(createdAtMs,
// activatedAtMs), НЕ просто createdAtMs, КОГДА activatedAtMs известен (> 0).
// Главный путь доски заказов (JobBoardFacet.acceptApplicant() →
// FactoryFacet.sol:232-273) регистрирует сделку НЕОПЛАЧЕННОЙ — activatedAt на
// этот момент 0 — а у fund() нет дедлайна вообще (Agreement.sol:557): между
// "создали" и "оплатили" может пройти сколько угодно дней. Настоящий дедлайн
// работы контракт считает от activatedAt (Agreement.deadline(): activatedAt +
// deadlineDays*1 days), не от createdAt.
//
// I-B (третий закрывающий раунд ревью, находка координатора): просто
// max(createdAtMs, activatedAtMs) — недостаточно само по себе. Пока
// activatedAtMs всё ещё 0, якорь остаётся createdAtMs НАВСЕГДА (createdAt —
// число, зафиксированное в день регистрации, не растёт) — а первое
// усыновление мешков когда-то (тогда — по возрасту, после И-2 — когда
// запись уже мертва, см. докстринг adoptPairBags()) перестаёт пускать
// ПЕРВОЕ усыновление, и даже после починки этого гейта для УЖЕ усыновлённых
// записей (см. докстринг adoptPairBags()) сам ПРЕДВАРИТЕЛЬНЫЙ срок
// (createdAt + ownDeadline + хвост) остаётся коротким,
// если ownDeadline — короткая сделка: запись сметает cleanupBags() ДО того,
// как активация вообще случится, и переякоривать уже нечего. Координатор
// воспроизвёл двумя таблицами (test/bagAdoption.test.js, describe "I-B"):
// без активации срок сделки в 3 дня умирает на 13-й день независимо от
// задержки оплаты, 30-дневная — на 40-й.
//
// Починка: пока activatedAtMs ещё 0 (сделка ЕЩЁ НЕ активирована), якорь —
// nowMs (момент ЭТОГО прогона), не createdAtMs. Каждую ночь, пока сделка
// остаётся ACTIVE (adoptActivePairBags зовётся КАЖДУЮ ночь для каждой ещё
// ACTIVE сделки, не только в день регистрации), якорь сдвигается на день
// вперёд вместе с "сегодня" — предварительный срок никогда не отстаёт
// больше чем на ownDeadline+хвост от текущей ночи, и запись не может
// сгореть, пока ночной прогон продолжает происходить. Правило "только
// продлевать" (Math.max в adoptPairBags()) не даёт этому откатиться назад.
// Как только контракт покажет activatedAtMs > 0, якорь ПЕРЕКЛЮЧАЕТСЯ на
// max(createdAtMs, activatedAtMs) — стабильное, не растущее дальше значение,
// отражающее НАСТОЯЩИЙ график сделки, а не бесконечно уезжающую оценку.
//
// deadlineGraceMs/autoApproveWindowMs — мелочь того же раунда: собственный
// худший случай сделки БЕЗ спора длиннее, чем просто ownDeadlineMs —
// Agreement.DEADLINE_GRACE (запас перед автовозвратом, 1 день) и
// AUTO_APPROVE_WINDOW (окно клиента среагировать после markDone, 2 дня) тоже
// сдвигают момент, до которого спор в принципе возможен. Обе — public
// constant в ТОМ ЖЕ контракте, откуда уже читаем DISPUTE_WINDOW — не лишний
// класс чтения, тот же приём, тот же кэш (см. app.js).
// Мелочь (координатор, пятый закрывающий раунд ревью): два вида мусора с
// цепи молча проходили и раньше не проверялись отдельно:
//   • отрицательный ownDeadlineMs (Agreement.getDetails().deadlineDays_ *
//     1 day) — складывается со знаком минус, УКОРАЧИВАЯ формулу, без единой
//     строки в логе (не бросок — тихий более короткий срок, худший вид
//     ошибки: выглядит как успех). Тот же риск — у трёх остальных "длин",
//     читаемых staticcall'ом (disputeWindowMs/deadlineGraceMs/
//     autoApproveWindowMs) — тот же класс входа, тот же контракт, тот же
//     принцип "не полагаться на то, что uint256 не может декодироваться в
//     отрицательное" — assertNonNegativeSafeInt на все четыре разом, не
//     только на названную координатором.
//   • activatedAtMs из будущего (относительно nowMs, этого же прогона) —
//     давал абсурдный срок на годы вперёд, спасаемый только потолком
//     BAG_MAX_AGE_MS (тот же класс дыры, ради которой чинили C-1: лог мог
//     бы рапортовать честный потолок, но сам вход остаётся мусором).
//     Тот же assertNotFromFuture, что уже применяется к uploadedAt в
//     recordBag() — тот же принцип, применённый здесь. createdAtMs —
//     того же происхождения (то же getActive()/тот же контракт), закрыт
//     тем же способом заодно, не как отдельная находка.
export function dealDeadlineFromCreation({
  createdAtMs, activatedAtMs, ownDeadlineMs, disputeWindowMs,
  deadlineGraceMs, autoApproveWindowMs, nowMs,
}) {
  assertSafeInt('dealDeadlineFromCreation', 'createdAtMs', createdAtMs);
  assertSafeInt('dealDeadlineFromCreation', 'activatedAtMs', activatedAtMs);
  assertNonNegativeSafeInt('dealDeadlineFromCreation', 'ownDeadlineMs', ownDeadlineMs);
  assertNonNegativeSafeInt('dealDeadlineFromCreation', 'disputeWindowMs', disputeWindowMs);
  assertNonNegativeSafeInt('dealDeadlineFromCreation', 'deadlineGraceMs', deadlineGraceMs);
  assertNonNegativeSafeInt('dealDeadlineFromCreation', 'autoApproveWindowMs', autoApproveWindowMs);
  assertSafeInt('dealDeadlineFromCreation', 'nowMs', nowMs);
  assertNotFromFuture('dealDeadlineFromCreation', 'createdAtMs', createdAtMs, nowMs);
  assertNotFromFuture('dealDeadlineFromCreation', 'activatedAtMs', activatedAtMs, nowMs);

  const anchor = activatedAtMs > 0
    ? Math.max(createdAtMs, activatedAtMs)
    : Math.max(createdAtMs, nowMs);

  return anchor + ownDeadlineMs + deadlineGraceMs + autoApproveWindowMs
    + disputeWindowMs + FINALIZE_DELAY_MS + APPEAL_REVIEW_WINDOW_DAYS * DAY_MS + BAG_DEAL_GRACE_MS;
}

// Этап 2. Срок сделки — до ОКОНЧАТЕЛЬНОГО закрытия дела, не до вердикта:
// вердикт вынесен, человек его оспаривает — а доказательства уже стёрты,
// апелляция без них превращается в лотерею. disputedAtMs/disputeWindowMs —
// уже в мс и уже читаны вызывающим с цепи (Agreement.getDetails().disputedAt_
// и Agreement.DISPUTE_WINDOW() — тем же способом, каким уже читает фронт,
// frontend/src/app/deal/[address]/page.tsx:389-392, и каким app.js уже
// читает DISPUTE_WINDOW для disputeResponseDeadline()). APPEAL_REVIEW_WINDOW
// прочитать с цепи нельзя (private constant, ArbiterRegistryFacet.sol:147) —
// отсюда собственная копия релеера, APPEAL_REVIEW_WINDOW_DAYS, и гейт
// script/check-appeal-window.sh, держащий копию в согласии с оригиналом.
//
// I2 (находка координатора, закрывающий раунд): формула раньше пропускала
// целое звено цепочки. Настоящая последовательность ПОЛЬЗОВАТЕЛЬСКОГО пути —
//   submitVerdict   ≤ disputedAt + DISPUTE_WINDOW
//   raiseAppeal     только до submittedAt + FINALIZE_DELAY (24ч,
//                   ArbiterRegistryFacet.sol:140,755)
//   appealDeadline  = МОМЕНТ АПЕЛЛЯЦИИ + APPEAL_REVIEW_WINDOW (не от
//                   submittedAt, строка 781)
//   худший случай   = disputedAt + DISPUTE_WINDOW + FINALIZE_DELAY + APPEAL_REVIEW_WINDOW
// ⚠️ "Худший случай" здесь — худший случай ИМЕННО пользовательского пути,
// не абсолютный потолок: путь владельца/ДАО (freezeVerdict(), onlyOwnerOrDAO)
// срока не имеет вовсе — заморозка держит дело живым, пока unfreezeVerdict()
// её не снимет, без какого-либо таймаута. Формула этот путь не пытается
// покрыть отдельно (у него нет конечного "худшего случая", который можно
// было бы в неё вписать) — реальный потолок сверху при любом раскладе,
// включая заморозку, даёт BAG_MAX_AGE_MS (bagExpiryAt() ниже), не эта
// формула. Не чинится, задокументировано по прямому указанию координатора.
// Без FINALIZE_DELAY_MS ниже формула давала ровно disputedAt+9д на
// умолчаниях — численно совпадало с истинным минимумом только потому, что
// BAG_DEAL_GRACE_MS (умолчание — сутки) молча покрывал недостающий день;
// реальный запас был РОВНО 0, а на легальной настройке BAG_DEAL_GRACE_MS=0
// срок отставал от истинного конца апелляции на день — доказательства
// стирались бы за сутки до того, как апелляция реально закрывается.
// Заперто тестом на точную границу (BAG_DEAL_GRACE_MS=0) в
// test/bagAdoption.test.js.
//
// Обе функции этого раздела — чистые: не трогают _bagMeta и не делают I/O,
// поэтому проверяются напрямую, без мока цепи (test/bagAdoption.test.js).
export function dealDeadlineFromDispute(disputedAtMs, disputeWindowMs) {
  assertSafeInt('dealDeadlineFromDispute', 'disputedAtMs', disputedAtMs);
  // Мелочь (координатор, пятый закрывающий раунд): тот же класс входа, что
  // ownDeadlineMs/disputeWindowMs и т.д. в dealDeadlineFromCreation выше —
  // отрицательный disputeWindowMs укоротил бы формулу молча. Нет nowMs в
  // сигнатуре этой функции (не менялась ради этого мелкого пункта — сигнатура
  // используется и тестами, и app.js как позиционная, без него), так что
  // "не из будущего" здесь не проверяется — только неотрицательность.
  assertNonNegativeSafeInt('dealDeadlineFromDispute', 'disputeWindowMs', disputeWindowMs);
  return disputedAtMs + disputeWindowMs + FINALIZE_DELAY_MS + APPEAL_REVIEW_WINDOW_DAYS * DAY_MS + BAG_DEAL_GRACE_MS;
}

// pairId — опаковая строка, та же форма, что производит _pairIdFromAddresses
// (и app.js:pairIdFromAddresses — заперто тестом на совпадение обеих в
// test/bagStore.test.js). dealDeadline — уже готовое число мс, посчитанное
// вызывающим (обычно через dealDeadlineFromDispute() выше); эта функция сама
// формулу не знает и не пересчитывает — только применяет её ко всем
// подходящим записям.
//
// ВАЖНО (Q5 отчёта Задачи 5): adoptPairBags() НЕ имеет способа проверить,
// что вызывающий действительно вправе усыновлять именно эту пару — тот же
// класс допущения, что уже есть у пометки пары disputedPairIds для вложений
// (app.js: "peerA/peerB tagging on /files/presign has no proof-of-
// participation check"). Единственная граница, реально ограничивающая
// злоупотребление, — потолок BAG_MAX_AGE_MS в bagExpiryAt() (не здесь):
// сколько бы ни было передано в dealDeadline, итоговый срок мешка никогда
// не превышает uploadedAt + BAG_MAX_AGE_MS. adoptPairBags() сознательно не
// дублирует эту проверку — дублирование двух копий одного правила в двух
// местах разошлось бы молча при следующей правке одного из них.
//
// I-B (третий закрывающий раунд ревью, находка координатора): гейт первого
// усыновления (ниже — какой именно) применяется ТОЛЬКО к первому
// усыновлению записи (meta.dealDeadline ещё null) — уже усыновлённая
// запись пересчитывается на КАЖДОМ прогоне НЕЗАВИСИМО от него. Раньше этот
// гейт (тогда — по возрасту, см. И-2 ниже) проверялся всегда, и это ломало
// главный путь доски заказов: этап 1 (adoptActivePairBags) усыновляет
// мешок В ДЕНЬ СОЗДАНИЯ сделки (мешок тогда свежий, гейт проходит), но
// якорь на тот момент — только createdAt (activatedAt ещё 0, см. С1). Если
// оплата задерживалась достаточно долго, к моменту, когда контракт наконец
// покажет activatedAt, старый код тут просто пропускал запись (`continue`)
// НАВСЕГДА, и предварительный срок, посчитанный от createdAt в день ноль,
// оставался замороженным, даже когда правильный, куда более поздний
// dealDeadline (от activatedAt) был уже известен и ждал применения.
// Воспроизведено координатором таблицей задержек.
//
// Правило «только продлевать» (Math.max ниже) уже гарантирует, что
// пропуск гейта для уже усыновлённой записи не может НИЧЕГО ухудшить —
// max(current, dealDeadline) либо оставляет прежнее значение, либо
// увеличивает его, никогда не уменьшает. Значит снятие гейта здесь
// безопасно при любом раскладе, ровно как и написал координатор.
//
// И-2 (пятый закрывающий раунд ревью, находка координатора): сам гейт для
// НИКОГДА не усыновлявшейся записи раньше был по ВОЗРАСТУ (uploadedAt
// младше BAG_ADOPTION_LOOKBACK_MS, умолчание — 30 дней) — координатор нашёл
// конкретный провал: мешок 30-37 дней от загрузки, но ПРОЧИТАННЫЙ недавно,
// правилом 2 (7д от прочтения) остаётся живым дольше 30 дней САМ ПО СЕБЕ —
// и старый гейт всё равно отвергал его усыновление, хотя запись физически
// ещё существует. Возраст — не то, что должно решать: "продлевать нечего"
// ровно тогда, когда запись уже МЕРТВА по своему текущему правилу
// (bagExpiryAt(meta, nowMs) <= nowMs), не когда она просто "старая". Гейт
// заменён на прямую проверку живости: bagExpiryAt(meta, nowMs) > nowMs.
// Мешок моложе 30 дней и мешок старше 30 дней, но ещё живой правилом 2/3,
// теперь усыновляются одинаково — критерий один и тот же для обоих.
// BAG_ADOPTION_LOOKBACK_MS как отдельная env-ручка убрана целиком (см.
// докстринг у бывшего объявления, ближе к началу файла) — параметризовать
// было больше нечего, критерий "жив" уже целиком выражен тремя правилами
// bagExpiryAt().
//
// Персист — ОДИН раз на весь вызов (после цикла по всем подходящим записям),
// не по одной записи за раз: либо весь вызов целиком лёг на диск, либо (при
// ошибке записи) НИ ОДНА мутация этого вызова не осталась в памяти дольше
// самого вызова — тот же приём отката, что у recordBag()/markFetched() (I2).
// (cleanupBags() своего отката больше не держит — К-2 сняла его вместе со
// сменой порядка «сначала снести, потом записать»: там к моменту ошибки
// файлы уже физически удалены, и откат в память стал бы враньём. Здесь
// ничего физически не удаляется, так что откат остаётся честным.)
// Режим недоверия (_bagMetaLoadOk) через
// _persistUnlessDistrusted() — та же дисциплина, что и у остальных писателей
// этого файла: мутация применяется к памяти, на диск не уходит, пока индекс
// не заслужит доверие заново честной загрузкой.
//
// C-1 (координатор, четвёртый закрывающий раунд ревью): возврат раньше был
// голым числом (adopted) — вызывающий (app.js) логировал ЗАПРОШЕННЫЙ
// dealDeadline, а не то, что реально получилось после потолка
// BAG_MAX_AGE_MS (ceiling у каждой записи свой — uploadedAt + BAG_MAX_AGE_MS,
// у мешков одной пары могут быть разные uploadedAt). Замер координатора:
// лог рапортовал "extended 1 bag(s) ... to 2030-01-23 (preliminary)" (378
// дней вперёд), а мешок реально жил 90 дней — молчаливое расхождение между
// тем, что в логе, и тем, что на диске. Теперь возвращает объект: adopted
// (как раньше — число реально изменённых записей), requested (что было
// запрошено этим вызовом), minEffectiveExpiry (худший — самый ранний —
// РЕАЛЬНЫЙ bagExpiryAt среди записей, изменённых ИМЕННО этим вызовом, или
// null, если ничего не изменилось), cappedCount (сколько из них получили
// реальный срок КОРОЧЕ запрошенного — то есть потолок реально их обрезал)
// и funded (см. ниже). Вызывающий (app.js) обязан логировать
// minEffectiveExpiry, не requested, и явно предупреждать, когда
// cappedCount > 0 — см. adoptActivePairBags()/adoptDisputedPairBags().
//
// funded (решение владельца) — true, если СДЕЛКА, ВЫДАЮЩАЯ ИМЕННО ЭТО
// ПРОДЛЕНИЕ, оплачена (Agreement.getDetails().fundedAt_ > 0 — деньги
// реально в эскроу), false/не передан — неоплаченная. C1 (координатор,
// критическая находка следующего раунда): раньше это был флаг НА МЕШКЕ
// (meta.dealFunded), монотонный и НАВСЕГДА — и в этом была дыра. Пара
// платит ОДИН раз (любая сделка, хоть на день) — флаг встаёт в true
// навсегда, а дальше ЛЮБАЯ ДРУГАЯ сделка той же пары, включая никогда не
// оплаченную, безнаказанно двигает срок вперёд без потолка, потому что
// ежедневный храповик видел флаг уже true и не спрашивал, кто именно
// СЕЙЧАС продлевает. Хуже того: у зарегистрированной неоплаченной сделки
// нет способа выйти из активных без оплаты или запуска (контракт не даёт
// такого пути), а таймаут активации возвращает клиенту ВСЮ сумму — капитал,
// "купивший" освобождение, возвращается, платить продолжает только газ.
//
// Правка: funded больше НЕ хранится как состояние записи — он решает
// РОВНО ОДИН РАЗ, В МОМЕНТ ЭТОГО КОНКРЕТНОГО ВЫЗОВА, обрезать ли КАНДИДАТА
// потолком ДО того, как тот пойдёт в Math.max с уже хранящимся значением
// (см. candidate ниже). Правило «только продлевать» не изменилось — это
// тот же Math.max, что и раньше, просто сравнивает уже обрезанного (если
// нужно) кандидата, а не сырой dealDeadline. Следствие само собой:
// — продление оплаченной сделки не обрезается — если оно больше уже
//   хранящегося значения (в т.ч. выданного потолком неоплаченной сделки
//   раньше), Math.max его пропускает;
// — продление НЕОПЛАЧЕННОЙ сделки обрезается потолком ВСЕГДА, даже если
//   мешок уже когда-то был безлимитно продлён оплаченной — обрезанный
//   кандидат просто проигрывает Math.max уже большему значению и не
//   меняет ничего (запись стоит на месте, не откатывается назад — это и
//   есть ответ на "срок, выданный оплаченной, не сокращается");
// — если мешок ещё НЕ был продлён за потолок, неоплаченная сделка может
//   толкать его ВВЕРХ ДО потолка (кандидат растёт вместе с candidate, но
//   упирается в ceiling) — и не дальше, сколько бы ночей подряд ни звали.
export function adoptPairBags(pairId, dealDeadline, nowMs = Date.now(), funded = false) {
  assertPairId('adoptPairBags', pairId);
  assertSafeInt('adoptPairBags', 'dealDeadline', dealDeadline);
  assertSafeInt('adoptPairBags', 'nowMs', nowMs);

  const rollback = []; // [meta, previousDealDeadline] — только записи, реально изменённые этим вызовом
  // К-3: ключи изменённых записей — для журнала дозаписи. Усыновление зовут
  // по разу на КАЖДУЮ активную/спорную сделку за ночной прогон, и каждый
  // такой вызов раньше переписывал опись целиком.
  const changedKeys = [];
  let adopted = 0;
  let minEffectiveExpiry = null;
  let cappedCount = 0;

  for (const [key, meta] of Object.entries(_bagMeta)) {
    if (meta.pairId !== pairId) continue;
    // И-2: гейт первого усыновления — "жив ли мешок ПРЯМО СЕЙЧАС", не
    // "молодой ли он". Уже усыновлённая запись (dealDeadline != null)
    // пересчитывается независимо от этой проверки, см. докстринг выше (I-B).
    const alreadyAdopted = meta.dealDeadline != null;
    if (!alreadyAdopted && !(bagExpiryAt(meta, nowMs) > nowMs)) continue; // строго больше — не >=, тот же принцип, что и у прежнего лукбэка

    // C1: обрезаем КАНДИДАТА здесь, ДО Math.max — не после, и не через
    // состояние на записи. ceiling — тот же, что был у bagExpiryAt() до
    // всей истории с оплатой (per-запись, от uploadedAt ИМЕННО ЭТОГО
    // мешка — у мешков одной пары он может отличаться).
    const ceiling = meta.uploadedAt + BAG_MAX_AGE_MS;
    const candidate = funded ? dealDeadline : Math.min(dealDeadline, ceiling);

    const current = meta.dealDeadline ?? 0;
    const next = Math.max(current, candidate);
    if (next === current) continue; // уже не короче — ничего менять и персистить не нужно

    rollback.push([meta, meta.dealDeadline]);
    meta.dealDeadline = next;
    changedKeys.push(key);
    adopted++;

    // C-1 (было — С-1 раунда логирования): РЕАЛЬНЫЙ срок этой конкретной
    // записи — считаем ПОСЛЕ meta.dealDeadline обновлено. dealDeadline
    // (аргумент функции — запрошенное этим вызовом значение, ДО обрезки
    // кандидата) — то, с чем сравниваем: если candidate был обрезан
    // потолком (неоплаченная сделка), effective окажется меньше исходного
    // dealDeadline — ИМЕННО это и должно попасть в cappedCount/лог, а не
    // сравнение с уже обрезанным candidate (которое было бы тавтологией).
    const effective = bagExpiryAt(meta, nowMs);
    if (minEffectiveExpiry === null || effective < minEffectiveExpiry) minEffectiveExpiry = effective;
    if (effective < dealDeadline) cappedCount++;
  }

  if (adopted) {
    try {
      _persistUnlessDistrusted('adoptPairBags', changedKeys.map((k) => ({ k, m: { ..._bagMeta[k] } })));
    } catch (e) {
      // I2, тот же приём, что у recordBag()/markFetched(): не оставлять
      // память впереди диска. Откатываем РОВНО те записи, что изменил этот
      // вызов, к их прежнему значению (undefined, если поля не было вовсе —
      // но dealDeadline всегда присутствует в валидной записи как минимум
      // null, так что previousDealDeadline здесь всегда null или число).
      for (const [meta, previousDeadline] of rollback) {
        meta.dealDeadline = previousDeadline;
      }
      throw e;
    }
  }
  // funded — прямое отражение входного параметра этого вызова (C1: больше
  // не агрегат по записям — funded описывает САМ ВЫЗОВ, не то, что
  // когда-либо было true на затронутых записях; см. докстринг выше).
  return { adopted, requested: dealDeadline, minEffectiveExpiry, cappedCount, funded: !!funded };
}

// ─── Чистка ─────────────────────────────────────────────────────────────────

// Файлы на диске без записи в индексе — например, крах между записью файла и
// recordBag(), или потерянный/повреждённый bag-meta.json. Метётся по mtime,
// не раньше чем через BAG_UNREAD_TTL_MS (самый долгий срок "ещё не прочитан")
// — иначе потерянный индекс оставит мусор на складе навсегда, а слишком
// ранняя метла снесёт файл, для который recordBag() ещё просто не успел
// выполниться следом за записью на диск.
// Мелочь (f): возвращает число реально удалённых файлов — cleanupBags()
// складывает его со своим removed. Раньше не возвращала ничего, и снесённый
// файл-сирота не отражался в {removed, kept} вообще: вызывающий (лог/
// метрика после ночной чистки) видел бы "ничего не сделано" при реально
// удалённых файлах.
// И-1 (пятый раунд), находка снята шестым: protectedKeys когда-то был
// нужен, чтобы защитить от метлы файлы, чьё удаление из _bagMeta ещё не
// подтверждено диском. Больше не нужен — cleanupBags() (мелочь, пятый
// раунд, коммит 3592a82) теперь ОТКАТЫВАЕТ такие записи обратно в _bagMeta
// в своей catch-ветке, ДО того как finally здесь вообще позовёт эту
// функцию. К моменту, когда sweepOrphanFiles видит файл, чьё удаление не
// удалось сохранить, ключ уже снова в _bagMeta — обычный hasOwnProperty
// ниже его и защищает. Отдельный параметр protectedKeys стал мёртвым
// весом (мутация, отключающая его целиком, переставала на что-либо
// влиять) — убран, а не оставлен неиспользуемым.
// Закрывающий раунд (следующая находка координатора после режима
// недоверия): `fs.statSync(recipientDir)` СЛЕДУЕТ за симлинком — каталог
// получателя, вынесенный симлинком на другой том (обычное администраторское
// действие при нехватке места), проходил `.isDirectory()` как настоящий
// каталог, и обход уходил ПО ССЫЛКЕ НАСКВОЗЬ. Замерено вживую: три мешка за
// симлинком, описи нет → метла сносит 2 из 3, ПЛЮС удаляет файлы, физически
// лежащие СНАРУЖИ DIR_BAGS в целевом каталоге ссылки — то есть чужое, не
// только не проиндексированное. Это НЕ зависит от режима недоверия: тот же
// побег происходит и в обычном, доверенном режиме с честной описью, раз сам
// обход каталогов получателей идёт через statSync. `lstatSync` (как уже
// применяется в _scanDiskBags) видит сам симлинк, не то, на что он
// указывает, — `.isDirectory()` на нём false, и обход внутрь не спускается.
function sweepOrphanFiles(nowMs) {
  const cutoff = nowMs - BAG_UNREAD_TTL_MS;
  let removed = 0;

  let recipients;
  try { recipients = fs.readdirSync(DIR_BAGS); } catch { return removed; }

  for (const recipient of recipients) {
    const recipientDir = path.join(DIR_BAGS, recipient);
    let files;
    try {
      if (!fs.lstatSync(recipientDir).isDirectory()) continue; // симлинк — не спускаемся
      files = fs.readdirSync(recipientDir);
    } catch { continue; }

    for (const file of files) {
      const key = `${recipient}/${file}`;
      if (Object.prototype.hasOwnProperty.call(_bagMeta, key)) continue;

      const filePath = path.join(recipientDir, file);
      try {
        if (fs.statSync(filePath).mtimeMs < cutoff) {
          fs.unlinkSync(filePath);
          removed++;
        }
      } catch {}
    }
  }
  return removed;
}

// Мелочь (e): без этого bags/<адрес>/ переживает каждый мешок, когда-либо
// в нём лежавший — на диске оседает список всех, кто когда-либо получал
// мешок, дольше самих мешков. Для проекта, обещающего не быть архивом
// (сервер не хранит то, чего не должен), это лишнее. Запускается ПОСЛЕ
// основного цикла удаления и sweepOrphanFiles — только тогда каталог,
// опустевший в этом же проходе чистки, действительно пуст.
function removeEmptyRecipientDirs() {
  let recipients;
  try { recipients = fs.readdirSync(DIR_BAGS); } catch { return; }

  for (const recipient of recipients) {
    const recipientDir = path.join(DIR_BAGS, recipient);
    try {
      // lstat — та же причина, что в sweepOrphanFiles выше: не следовать за
      // симлинком. fs.rmdirSync на симлинке (не каталоге) само по себе
      // бросило бы ENOTDIR и ничего не сломало бы, но isDirectory() через
      // statSync уже увёл бы readdirSync/дальнейшую логику по цепочке за
      // пределы DIR_BAGS — тот же класс дыры, что и в метле сирот.
      if (!fs.lstatSync(recipientDir).isDirectory()) continue;
      if (fs.readdirSync(recipientDir).length === 0) fs.rmdirSync(recipientDir);
    } catch {}
  }
}

// Мелочь (координатор, закрывающий раунд): _saveBagMeta() пишет во
// временный файл `${BAG_META_PATH}.tmp-<pid>-<ts>-<uuid>` и переименовывает
// его — но обрыв МЕЖДУ writeFileSync и renameSync (кончилось место,
// процесс убит) оставляет обрезок лежать в корне STORAGE_DIR НАВСЕГДА:
// ни sweepOrphanFiles (смотрит только внутрь DIR_BAGS), ни основной цикл
// cleanupBags (смотрит только на _bagMeta) его никогда не видели. Копится
// именно тогда, когда обрывы и случаются чаще всего — на нехватке места.
// Порог — час, заведомо дольше, чем может идти одна запись+переименование
// (миллисекунды в норме); не трогаем свежие осколки, чтобы не забежать
// вперёд ещё идущей записи другого процесса.
function sweepStaleTmpFiles(nowMs) {
  const cutoff = nowMs - 60 * 60 * 1000;
  const dir = path.dirname(BAG_META_PATH);
  const prefix = `${path.basename(BAG_META_PATH)}.tmp-`;
  let entries;
  try { entries = fs.readdirSync(dir); } catch { return 0; }

  let removed = 0;
  for (const entry of entries) {
    if (!entry.startsWith(prefix)) continue;
    const fp = path.join(dir, entry);
    try {
      // lstat — тот же принцип, что и везде в этом раунде: имя осколка
      // предсказуемо (наш собственный формат), но что физически лежит по
      // этому имени — не обязано быть обычным файлом.
      const st = fs.lstatSync(fp);
      if (!st.isFile()) continue;
      if (st.mtimeMs < cutoff) {
        fs.unlinkSync(fp);
        removed++;
      }
    } catch {}
  }
  return removed;
}

export function cleanupBags(nowMs = Date.now()) {
  assertSafeInt('cleanupBags', 'nowMs', nowMs);

  // Третий тур закрывающего ревью Задачи 4: ЕДИНЫЙ гейт в начале функции,
  // не два разных (раньше только sweepOrphanFiles() была под гейтом внутри
  // finally — основной цикл истечения срока чуть выше был открыт всегда).
  // Координатор замерил живьём: мешок с полусотней оставшихся дней снесён
  // немедленно основным циклом в прогоне, где лог сам печатал «описи
  // нельзя верить» — гейта на этом пути не было вообще. Ничего не удаляем
  // ни через один путь, пока индекс не заслужил доверия свежей штатной
  // загрузкой.
  if (!_bagMetaLoadOk) {
    console.error(
      '[bags] cleanupBags: DISTRUST MODE — deletion disabled entirely this run, both the main expiry pass and ' +
      'the orphan sweep. The index could not be trusted at load time (see _loadBagMeta). Fix or remove the ' +
      'index file and restart to resume deleting anything.'
    );
    return { removed: 0, kept: Object.keys(_bagMeta).length };
  }

  let removed = 0;
  let kept = 0;
  // Мелочь (порядок): файлы удаляемых мешков собираются здесь, но не
  // трогаются немедленно — см. ниже, почему удаление файла идёт ПОСЛЕ
  // сохранения индекса, а не до.
  const keysToDeleteFiles = [];
  // К-3: ключи ВСЕХ снятых записей — и просроченных, и «мелочи g». Уходят в
  // журнал строками удаления ДО снимка (см. ниже, зачем).
  const removedKeys = [];
  // К-2: накопитель removedEntries (для отката при падении сохранения) убран
  // как мёртвый вес, а не оставлен неиспользуемым — тем же правилом, что
  // сняло protectedKeys у sweepOrphanFiles() шестым раундом. Откатывать
  // больше нечего и незачем: файлы к моменту catch уже физически снесены
  // (см. комментарий в try/catch ниже), вернуть их в память означало бы
  // обещать несуществующее.

  for (const [key, meta] of Object.entries(_bagMeta)) {
    if (bagExpiryAt(meta, nowMs) <= nowMs) {
      delete _bagMeta[key];
      keysToDeleteFiles.push(key);
      removedKeys.push(key);
      removed++;
      continue;
    }

    // Мелочь (g): формально живая по сроку запись, чей файл пропал с диска
    // (ручное вмешательство, сбой ФС) — индекс не должен утверждать
    // существование того, чего физически нет. Без этого listBagsFor()
    // продолжал бы отдавать такой мешок, и Задача 3 получила бы ошибку
    // чтения на попытке выдачи вместо честного "мешка больше нет".
    let fileExists;
    try { fileExists = fs.existsSync(bagPathFor(key)); } catch { fileExists = false; }
    if (!fileExists) {
      console.error(`[bags] cleanupBags: index entry ${JSON.stringify(key)} has no file on disk — dropping from index`);
      delete _bagMeta[key];
      removedKeys.push(key);
      removed++;
      continue;
    }

    kept++;
  }

  try {
    // К-2 (аудит устойчивости, 6 августа): СНАЧАЛА сносим файлы, ПОТОМ
    // пишем опись. Порядок был обратным, и ровно он делал уборку
    // бесполезной на полном диске — том единственном случае, ради которого
    // уборка и существует.
    //
    // Замер до правки (scratchpad/measure-k2.mjs, боевые умолчания,
    // единственная подмена — writeFileSync бросает ENOSPC, как настоящая
    // полная ФС): 500 просроченных мешков по 1 КиБ → освобождено 0 файлов,
    // 0 байт. _saveBagMeta() падала первой, catch откатывал всё, и до
    // строки удаления файлов управление не доходило НИКОГДА. После правки —
    // 500 из 500, 512 000 байт.
    //
    // Чем платим и почему это дешевле. Прежний порядок покупал одно
    // свойство: при обрыве между шагами на диске остаётся осиротевший файл
    // (его подберёт метла сирот по mtime), а не опись, обещающая
    // несуществующий файл. Новый порядок меняет знак: худший случай —
    // опись, пережившая снос своих файлов. Это НЕ потеря данных и не
    // тупик — ветка «мелочь g» чуть выше в этой же функции штатно ловит
    // ровно такую запись (жива по сроку, файла нет) и убирает её из описи
    // на следующем же прогоне. То есть цена нового порядка — одна лишняя
    // строка в логе на следующую ночь; цена старого — сервер, который
    // физически не может освободить место и не освободит его никогда.
    //
    // И удаление файлов — единственное, что вообще может дать записи описи
    // шанс пройти В ЭТОМ ЖЕ прогоне: место, освобождённое строкой выше, —
    // то самое место, которого не хватало строке ниже.
    for (const key of keysToDeleteFiles) {
      try { fs.unlinkSync(bagPathFor(key)); } catch {}
    }
    if (removed) {
      // К-3, ВАЖНО: строки удаления уходят в журнал ПЕРЕД снимком, а не
      // вместо него. Без этого шага чистка была бы ЕДИНСТВЕННОЙ мутацией
      // склада, которой нет в журнале — и любой обрыв в окне между «снимок
      // записан» и «журнал обнулён» ВОСКРЕШАЛ БЫ снесённое: разбор при
      // старте доиграл бы поверх свежего снимка старую строку записи того
      // самого ключа, который снимок уже не содержит. Поймано живым
      // прогоном при реализации К-3, а не рассуждением.
      //
      // Отсюда общее правило склада, на которое опирается вся конструкция:
      // ЛЮБАЯ мутация сначала попадает в журнал; снимок — только свёртка
      // журнала, никогда не самостоятельный источник изменений. Тогда
      // «журнал старше снимка» безвреден по построению: журнал полон и
      // упорядочен, снимок — его префикс, доигрывание хвоста всегда даёт
      // верный итог.
      _appendJournal(removedKeys.map((k) => ({ k, d: 1 })));
      _saveBagMeta();
    }
  } catch (e) {
    // К-2: отката БОЛЬШЕ НЕТ, и это не упущение, а следствие нового
    // порядка. Прежний откат (пятый раунд, дисциплина I2 из recordBag()/
    // markFetched()) был честен ровно потому, что файлы к моменту catch
    // гарантированно не были тронуты. Теперь они тронуты — снесены
    // физически и безвозвратно. Вернуть запись в _bagMeta означало бы
    // утверждать существование файла, которого нет: listBagsFor() снова
    // отдавал бы мешок, GET /bags/:key отвечал бы ошибкой чтения вместо
    // честного «мешка больше нет», а метла сирот (finally ниже) обходила
    // бы стороной ключ, для которого и обходить уже нечего.
    //
    // Память остаётся в том состоянии, которое соответствует диску:
    // мешков нет. Разошлась с диском только ОПИСЬ — и её расхождение
    // самолечится «мелочью g» на следующем прогоне. Бросок остаётся
    // (вызывающий обязан узнать, что опись не сохранилась), меняется
    // только то, что мы при этом НЕ врём себе в память.
    throw e;
  } finally {
    // Мелочь (независимость): sweepOrphanFiles/removeEmptyRecipientDirs
    // работают с файловой системой напрямую, не зависят от успеха
    // сохранения индекса — finally гарантирует, что упавшее сохранение не
    // отменяет их молча для НЕСВЯЗАННЫХ настоящих сирот. Гейт на
    // sweepOrphanFiles() больше не нужен здесь отдельно — весь путь уже
    // отсекается ранним возвратом в начале функции, когда индексу нельзя
    // верить (третий тур, см. верх cleanupBags()). removeEmptyRecipientDirs()
    // по-прежнему безопасен всегда (сносит только каталоги, физически
    // пустые на диске, — реальному мешку в них ничего не грозит).
    removed += sweepOrphanFiles(nowMs);
    removeEmptyRecipientDirs();
    // Мелочь (координатор): осколки .tmp-* от оборванных сохранений — та
    // же независимость от успеха ЭТОГО прохода, тот же finally.
    sweepStaleTmpFiles(nowMs);
  }

  return { removed, kept };
}
